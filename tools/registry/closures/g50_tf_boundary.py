"""Г-50: активность у границ таймфрейма (закрытие 1м/5м/1ч/4ч). Плагин KIND='keep' (М5, В-227 пакет F): сигнал, чей t0 лежит не дальше
window секунд ПОСЛЕ границы бара (t0 mod tf <= window, границы сетки UTC от эпохи), исключается; остальные остаются.
Выбор Инженера (Судье отметить): исключение «после границы», не «вокруг» и не «только у границы» — домены спеки (tf × window)
направления не задают; обратное направление (только у границы) = дополнение набора и в спеку не входит. Окно >= tf исключает всё."""
NAME = "g50"
KIND, SOURCES = "keep", ()
PARAMS = {"tf": (60, 300, 3600, 14400), "window": (5, 10, 20, 30, 60, 120, 300)}


def run(data, ctx, tf, window):
    tf_ns, w_ns = tf * 1_000_000_000, window * 1_000_000_000
    return [(d["symbol"], d["day_utc"], d["form"], d["signal_index"]) for d in data if int(d["t0_ns"]) % tf_ns > w_ns]
