"""TK-451 возврат Судьи: §7 сводная таблица, годы слоя 1, A9, ТФ, ДИ, BTC/ETH, ранние/поздние. Запуск: python -I tools/sancho_tk451_ret.py"""
import pandas as pd
D = 'data/tk451/'; O = 'docs/findings/sancho-2026-10-30'
NL = chr(10)
f = lambda x, n=1: f'{x:.{n}f}'.replace('.', ',')
y1 = pd.concat([pd.read_csv(D + f'l1years-k{k}.csv').assign(k=k) for k in (1, 2)])
y1.to_csv(O + '-layer1-years.csv', index=False)
l2 = pd.read_csv(D + 'l2-layer2.csv'); l2.to_csv(O + '-layer2.csv', index=False)
pd.read_csv(D + 'l2-layer2-years.csv').to_csv(O + '-layer2-years.csv', index=False)
pd.read_csv(D + 'l2-layer2-syms.csv').to_csv(O + '-layer2-syms.csv', index=False)
ag = pd.read_csv(D + 'l1agg.csv'); v = pd.read_csv(D + 'l1verdict.csv')
auth = {'A1': ('истинный пробой', '61'), 'A2': ('пробой <0,2 ATR', '49,2'), 'A3': ('пробой 0,2–0,5', '53,9'),
        'A4': ('пробой >0,5 ATR', '66,5'), 'A5': ('свип → разворот', '62,2'), 'A6': ('свип+имбаланс', '84,1'),
        'A7': ('свип+слом', '89'), 'A8': ('все три', '91,6'), 'A9': ('прокол тенью, мед. ATR', '0,27')}
YRS = [f'y{y}' for y in range(2020, 2027)]
m1 = {'воспроизводится': 'подтверждено', 'не воспроизводится': 'оспорено'}
rank = {'воспроизводится': 3, 'не различимо (остров)': 2, 'не различимо': 2, 'не воспроизводится': 1}
rows = []
for c, (nm, an) in auth.items():
    g = y1[(y1.claim == c) & (y1.k == 2)]
    hits = []; cells = []
    for s in YRS:
        r = g[g.subset == s]; hits.append(int(r.hit.sum() >= (1 if len(r) <= 2 else 2))); cells.append(f'{int(r.hit.sum())}/{len(r)}')
    ny = sum(hits)
    vy = 'подтверждено' if ny == 7 else 'оспорено' if ny == 0 else 'не различимо'
    t = v[(v.subset == 'all84') & (v.claim == c)]
    if len(t):
        v1 = m1.get(t.loc[t.verdict.map(rank).idxmax()].verdict, 'не различимо')
    else:
        v1 = 'подтверждено' if hits[0] + sum(hits) >= 8 else 'не различимо'
    s2 = l2[l2.claim == c]
    v2 = (f'подтверждено (1 строка из {len(s2)})' if (s2.verdict == 'подтверждено').any() else 'не различимо') if len(s2) else '—'
    ps = []
    for s in YRS:
        r = g[g.subset == s]
        ps.append(f(r.p.iloc[0] if c in ('A1', 'A5', 'A9') else r.p.median(), 2 if c == 'A9' else 1))
    rows.append(f'| {c} | {nm} {an} | {v1} | {" · ".join(ps)} | {ny}/7 ({" ".join(cells)}) | {vy} | {v2} |')
T0 = NL.join(rows)
a = ag[(ag.subset == 'all84') & (ag.tf == 60) & (ag.k == 2) & (ag.N == 10) & (ag.oc == 'x1') & ag.claim.isin(['A1', 'A5'])]
ci = ['| id | p, % | наш ДИ по дням | ДИ «как для независимых» | ширина: наш / независимых |', '|---|---|---|---|---|']
for _, r in a.drop_duplicates('claim').iterrows():
    ci.append(f'| {r.claim} | {f(r.p)} | {f(r.lo)}–{f(r.hi)} | {f(r.lo_ind)}–{f(r.hi_ind)} | {f(r.hi-r.lo,2)} / {f(r.hi_ind-r.lo_ind,2)} (×{f((r.hi-r.lo)/(r.hi_ind-r.lo_ind))}) |')
names = {5: '5m', 15: '15m', 30: '30m', 60: '1H', 240: '4H', 1440: '1D', 10080: '1W'}


def tftab(k):
    out = [f'| ТФ | A1 (k={k}) | A5 | A9 мед. ATR | касаний |', '|---|---|---|---|---|']
    for t_, nm in names.items():
        g = ag[(ag.subset == 'all84') & (ag.tf == t_) & (ag.k == k)]

        def pick(c, oc):
            r = g[(g.claim == c) & (g.oc == oc) & ((g.N == 10) | (c == 'A9'))]
            return f(r.p.iloc[0], 2 if c == 'A9' else 1) if len(r) else '—'
        out.append(f'| {nm} | {pick("A1","x1")} | {pick("A5","x1")} | {pick("A9","med")} | {int(g[g.claim=="TOUCHES"].n.sum())} |')
    return NL.join(out)


sb = ['| подмножество | монет | A1 [95 %] | A5 [95 %] | A9 | ячеек в допуске A1 / A5 (k=2) |', '|---|---|---|---|---|---|']
for s, nm in [('all84', '84 монеты'), ('BTCUSDT', 'BTC'), ('ETHUSDT', 'ETH')]:
    g = ag[(ag.subset == s) & (ag.tf == 60) & (ag.k == 2)]
    pk = lambda c, oc: g[(g.claim == c) & (g.oc == oc) & ((g.N == 10) | (c == 'A9'))].iloc[0]
    a1, a5, a9 = pk('A1', 'x1'), pk('A5', 'x1'), pk('A9', 'med')
    sb.append(f'| {nm} | {84 if s=="all84" else 1} | {f(a1.p)} [{f(a1.lo)}–{f(a1.hi)}] | {f(a5.p)} [{f(a5.lo)}–{f(a5.hi)}] | {f(a9.p,2)} | {int(g[g.claim=="A1"].hit.sum())} / {int(g[g.claim=="A5"].hit.sum())} |')
for s, nm in [('early', 'ранние (события в 2020)'), ('late', 'поздние')]:
    g = y1[(y1.subset == s) & (y1.k == 2)]
    r1 = g[g.claim == 'A1'].iloc[0]; r5 = g[g.claim == 'A5'].iloc[0]; r9 = g[g.claim == 'A9'].iloc[0]
    sb.append(f'| {nm} | {int(r1.nsym)} | {f(r1.p)} [{f(r1.lo)}–{f(r1.hi)}] | {f(r5.p)} [{f(r5.lo)}–{f(r5.hi)}] | {f(r9.p,2)} | {int(g[g.claim=="A1"].hit.sum())} / {int(g[g.claim=="A5"].hit.sum())} |')
q = ['| id | строк | Δ>0 против C1 / C2 | медиана Δ, пп (C1 / C2) | min p Холм | подтверждено |', '|---|---|---|---|---|---|']
for c in ('A2', 'A3'):
    s = l2[l2.claim == c]
    q.append(f'| {c} | {len(s)} | {int((s.delta_C1>0).sum())} / {int((s.delta_C2>0).sum())} | {s.delta_C1.median()*100:+.1f} / {s.delta_C2.median()*100:+.1f} | {s.p_holm.min():.3f} | {int((s.verdict=="подтверждено").sum())} |')
n9 = int(y1[(y1.claim == 'A9') & (y1.k == 2) & y1.subset.isin(YRS)].hit.sum())
txt = f'''

## 7. Возврат Судьи (30.10; по готовым таблицам l1/l2, события не пересчитывались — В-213)

Артефакты: `-layer1-years.csv` (слой 1 по годам UTC 2020…2026 и ранние/поздние монеты, k=1,2), `-layer2.csv` / `-layer2-years.csv` / `-layer2-syms.csv` (слой 2 с A2/A3, 188 строк; заменяют прежние `-layer2*.csv`), `tools/sancho_tk451_ret.py`.

### 7.1 Сводная таблица (1H, 84 монеты; итог и годы рядом)

Вердикт из трёх слов. «Слой 1, итог» — воспроизведение числа автора по правилу протокола §4 (связная область ≥ 2 ячеек → подтверждено; одна ячейка → не различимо; ни одной → оспорено). «По годам» — в скольких из 7 лет есть связная область в допуске автора (≥ 2 ячеек, если в году их больше двух; иначе одна; k=2); **правило годов этого отчёта**: 7/7 — подтверждено, 0/7 — оспорено, иначе не различимо (записано до чтения таблицы, в протоколе его не было). «Доля по годам» — якорь (A1, A5, A9) либо медиана по ячейкам сетки (A2–A4, A6–A8), %; для A6–A8 допуск проверяет процент, не долю события; для A9 «итог» — по 7 годам. «Слой 2» — честная проверка (Δ к контролям C1/C2, Холм).

| id | заявление автора, % | слой 1, итог | доля по годам 2020 · 21 · 22 · 23 · 24 · 25 · 26 | лет в допуске (ячеек в допуске / всего) | слой 1, по годам | слой 2 |
|---|---|---|---|---|---|---|
{T0}

Годы с малой выборкой для слоя 1 нет (N события ≥ 17 тыс. на год); 2026 — неполный год. Слой 2 по годам — `-layer2-years.csv`, знаки Δ по годам — `yrs_pos/yrs_neg` в `-layer2.csv`.

### 7.2 A2/A3 слоем 2

Раньше 0 строк: агрегатор не включал эти заявления в список (не ошибка данных). Теперь по 24 строки на каждое:

{NL.join(q)}

### 7.3 ДИ автора против наших (1H, k=2, N=10)

Автор: 1H свип 62,6–63,8 % (ширина ≈ 1,2 пп) — как для независимых событий.

{NL.join(ci)}

### 7.4 ТФ 5m…1W отдельно (84 монеты, якорь N=10; **выборка автора по ТФ не названа**, в 15–20 раз меньше «Сводки»; у нас — все касания)

5-свечный свинг (k=2):

{tftab(2)}

3-свечный свинг (k=1):

{tftab(1)}

### 7.5 A9 — прокол тенью

Автор, 1H свип: 0,27 ATR (медиана). В допуск ±0,005 попадает {n9} из 7 лет; значения по годам — таблица 7.1, по ТФ — 7.4.

### 7.6 BTC/ETH отдельно и смещение выжившего (ранние/поздние монеты)

{NL.join(sb)}

Ранние — монеты с событиями в 2020, поздние — остальные. Разница ранние/поздние по A1, A5 — оценка смещения выжившего списка 88 (набор «сегодняшних» по объёмам).

### 7.7 Не сделано

X3 («ход m·ATR») слоем 2: событийные таблицы l2 хранят только исходы x1/x2, X3 потребовал бы пересчёта событий (В-213) — слой 2 остался K=188 строк (из 216 протокола). Число испытаний: слой 1 — ячеек сетки (`-layer1.csv`, `-layer1-years.csv`), слой 2 — 188 строк с поправкой Холма.
'''
p = O + '.md'; s = open(p, encoding='utf-8').read()
s = s.replace('Слой 1 по годам **не считался** (только слой 2).', 'Слой 1 по годам — §7.1.')
import re
s = re.sub(r'- Семейство K=144 вместо 216:[^\n]*', '- Семейство слоя 2: K=188 строк (X3 не считался — §7.7).', s)
s = re.sub(r'- Не вынесено в отчёт[^\n]*', '- Таблицы по ТФ, A9, ДИ «как для независимых» — §7.3–7.5.', s)
s = re.sub(r'- Смещение выжившего[^\n]*', '- Смещение выжившего — срез ранних/поздних монет, §7.6.', s)
s = re.sub(r'1\. Дособрать пропущенное[^\n]*', '1. Возврат Судьи закрыт по готовым таблицам — §7; X3 слоем 2 требует пересчёта событий.', s)
