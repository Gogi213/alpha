#!/usr/bin/env bash
# TK-219 (В-229 п.9): сутки месяца «тяжёлые первыми» — по числу символов в плане суток (убывание), хвост не растягивает проход.
#   day-order.sh <b1-symdays.csv: мес,сутки,символ> <мес>
awk -F, -v m="$2" 'NR>1 && $1==m {n[$2]++} END{for(d in n) print n[d], d}' "$1" | sort -k1,1nr -k2,2 | awk '{print $2}'
