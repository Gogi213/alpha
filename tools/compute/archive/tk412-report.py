#!/usr/bin/env python3
"""TK-412: vol.csv (tk412-volatility.py) -> docs/findings/volatile-coins-sep-<дата>.{csv,md}. Использование: tk412-report.py <vol.csv> <дата>"""
import re
import sys
import pandas as pd

src, date = sys.argv[1], sys.argv[2]
d = pd.read_csv(src)
C = "диапазон_дня_мед_%"


def key(r):
    s = r["инструмент"].split("-")[0]
    if r["биржа"] == "gate":
        s = s.split("_")[0]
    else:
        s = re.sub(r"(USDT|USDC|PERP)$", "", s)
    return re.sub(r"^(1000000|10000|1000)(?=[A-Z])", "", s)


d["ключ_монеты"] = d.apply(key, axis=1)
d = d.sort_values([C, "оборот_дня_мед_usd"], ascending=False, na_position="last")
d.to_csv(f"docs/findings/volatile-coins-sep-{date}.csv", index=False)

x = d[d["дней_с_данными"] > 0]
coin = x[(x["тип"] == "монета") & (x["котировка_usd"] == "да")]
L = []
L.append(f"# Волатильные монеты сентября 2026 по свечам 1 м + дневной оборот (TK-412, {date})\n")
L.append("Вход: свечи 1 м сентября (TK-411, calc `/srv/alpha-sda/candles-1m`), окно 01.09–30.09 UTC; 35 закрытых Bybit linear и инструменты без данных "
         "исключены (делисты — слово владельца). Счёт: `tools/compute/tk412-volatility.py` (alsched prod, 15 яд., 1 мин), "
         "отчёт `tools/compute/tk412-report.py`. Полная таблица: `docs/findings/volatile-coins-sep-" + date + ".csv` (все инструменты со свечами, "
         "сорт. по медианному дневному диапазону).\n")
L.append("## Что посчитано (на инструмент = биржа × рынок)\n")
L.append("- **Диапазон дня** = (max high − min low) / open первой свечи суток, UTC; даны медиана и максимум за сутки с данными.\n"
         "- **σ дня** = √Σ ln(c_i/c_{i−1})² по закрытиям внутри суток (минуты без сделок строки не имеют → нулевая доходность; прыжок через дыру — одна доходность); медиана и макс.\n"
         "- **Часов с ходом >5 % / >10 %** = часы, у которых (high−low)/open часа больше порога (из часов, где были сделки).\n"
         "- **Диапазон месяца** = (max high − min low) / первый open; **диапазон часа макс**.\n"
         "- **Оборот дня** = Σ quote_v за сутки: медиана и среднее по дням с данными. В USD для котировок USDT/USDC/USD/USD1/USDE/FDUSD/DAI/PYUSD/GUSD/RLUSD/USDG/USDD/TUSD "
         "(`котировка_usd=да`); пары к BTC/ETH/EUR/BRL/TRY/AED/PLN/SOL — оборот в единицах котировки (`нет`), в списки ниже не входят.\n"
         "- `тип`: монета / плечевой токен (ABC3L, ABC5S, CSOP…2L) / датированный (поставочный фьюч «-ДДМММГГ»).\n")
L.append("## Оговорки\n")
L.append("- Gate-свечи собраны из сделок (TK-411): плохие принты (одиночные сделки далеко от рынка) попадают в high/low. Максимумы (диапазон дня/часа/месяца, σ макс) Gate "
         "ими загрязнены (напр. STONKS_USDT макс дня 63 603 %); медианы и счётчики часов устойчивее, но не чисты. Фильтр выбросов не вводился (порог был бы придуманным числом) — решение Судьи.\n"
         "- Инструменты с малым `дней_с_данными` (листинг в середине месяца, пре-маркет) имеют медиану по нескольким дням: SI_USDT — 1 день, XDP — 2.\n"
         "- Тонкие инструменты: большой диапазон при малом обороте — шум спреда/редких сделок, не ход рынка; оборот дан рядом, порога ликвидности нет (за Судьёй).\n"
         "- Bybit `o` = close предыдущей минуты (конвенция API); Gate `o` — цена первой сделки минуты.\n")
L.append("## Распределение (монеты, котировка USD, " + str(len(coin)) + " инструментов)\n")
L.append("| показатель | p10 | p25 | p50 | p75 | p90 | p95 | p99 |\n|---|---|---|---|---|---|---|---|")
for c, nm in [(C, "диапазон дня, медиана, %"), ("sigma_дня_мед_%", "σ дня, медиана, %"), ("часов_ход_>10%", "часов с ходом >10 %"),
              ("оборот_дня_мед_usd", "оборот дня, медиана, $")]:
    q = coin[c].quantile([.1, .25, .5, .75, .9, .95, .99])
    L.append(f"| {nm} | " + " | ".join(f"{v:,.1f}" if c != "оборот_дня_мед_usd" else f"{v:,.0f}" for v in q) + " |")
L.append("\nЧисло инструментов (монеты, USD) с медианным дневным диапазоном не ниже порога:\n")
L.append("| порог | " + " | ".join(f"≥{t} %" for t in (5, 8, 10, 15, 20, 30)) + " |\n|---|" + "---|" * 6)
L.append("| инструментов | " + " | ".join(str(int((coin[C] >= t).sum())) for t in (5, 8, 10, 15, 20, 30)) + " |")
L.append("| из них с оборотом дня (мед.) ≥ $1 млн | " + " | ".join(str(int(((coin[C] >= t) & (coin["оборот_дня_мед_usd"] >= 1e6)).sum())) for t in (5, 8, 10, 15, 20, 30)) + " |\n")
L.append("По биржам и рынкам (все со свечами / монеты USD / из них диапазон ≥ 10 %):\n")
L.append("| биржа | рынок | со свечами | монеты, USD | ≥10 % |\n|---|---|---|---|---|")
for (e, m), g in x.groupby(["биржа", "рынок"]):
    cg = coin[(coin["биржа"] == e) & (coin["рынок"] == m)]
    L.append(f"| {e} | {m} | {len(g)} | {len(cg)} | {int((cg[C] >= 10).sum())} |")
L.append("\nТипы: " + ", ".join(f"{k} {v}" for k, v in x["тип"].value_counts().items()) + ".\n")

L.append("## Топ-50 монет по медианному дневному диапазону (предварительный порядок; метрику и порог выбирает Судья, В-53)\n")
L.append("Монета = ключ без приставки 1000/10000/1000000 и котировки; ранг — по лучшему из её инструментов (монеты, USD, ≥ 10 дней с данными). "
         "В ячейке: диапазон дня мед. % · σ дня мед. % · часов >10 % · оборот дня мед. $ (дней с данными, если < 30).\n")
rk = coin[coin["дней_с_данными"] >= 10]
best = rk.groupby("ключ_монеты")[C].max().sort_values(ascending=False).head(50)
mk = [("bybit", "linear"), ("bybit", "spot"), ("gate", "futures_usdt"), ("gate", "spot")]
L.append("| # | монета | Bybit linear | Bybit spot | Gate фьюч | Gate спот |\n|---|---|---|---|---|---|")
for i, (k, _) in enumerate(best.items(), 1):
    cells = []
    for e, m in mk:
        g = coin[(coin["ключ_монеты"] == k) & (coin["биржа"] == e) & (coin["рынок"] == m)]
        if len(g) == 0:
            cells.append("—")
            continue
        r = g.iloc[0]
        s = f"{r[C]:.1f} · {r['sigma_дня_мед_%']:.1f} · {int(r['часов_ход_>10%'])} · {r['оборот_дня_мед_usd']:,.0f}"
        if r["дней_с_данными"] < 30:
            s += f" ({int(r['дней_с_данными'])} дн.)"
        cells.append(s)
    L.append(f"| {i} | {k} | " + " | ".join(cells) + " |")
open(f"docs/findings/volatile-coins-sep-{date}.md", "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print(len(d), len(x), len(coin), len(rk))
