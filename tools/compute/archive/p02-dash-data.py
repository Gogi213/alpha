#!/usr/bin/env python3
"""Данные панели «Гипотезы П-02» дашборда (T-27): из перечтения R2 (`p02-r2-read.py` → JSON) и вердиктов §10 отчётов
П-02. Страница ничего не пересчитывает — только показывает.

    python tools/compute/p02-dash-data.py --r2 docs/findings/p02-r2-read-2026-09-26.json \\
        --out data/titration-dashboard/p02-hypotheses.json
"""
import argparse
import json

# гипотеза → (что проверяли, единица, вердикт §10, причина «не определена»)
META = [
    ("Г-28 (H1)", "Сила стены = завал + фронтран: верхняя треть силы против нижней, доля отскоков", "п.п.", "не ясно", None),
    ("Г-33 (H2)", "Декоративная стена (цепочка перестановок ≥ 2) против без цепочки, доля отскоков", "п.п.", "не ясно", None),
    ("Г-07 (H3)", "Глубина стакана позади стены: верхняя треть против нижней, доля отскоков", "п.п.", "не ясно", None),
    ("Г-08 (H4)", "Стена на круглом числе (≥ 2 нулей) против остальных, доля отскоков", "п.п.", "не ясно", None),
    ("Г-46 (H5)", "Поток тейкеров за 60 с против движения цены, доля отскоков", "п.п.", "не ясно", None),
    ("Г-36 (H6)", "Айсберг: прошлые касания проторговали ≥ видимого размера, доля отскоков", "п.п.", "не ясно", None),
    ("Г-85 (H7)", "Вход одной заявкой от фронтрана вплотную против лестницы, $ на позицию $500", "$", "не ясно", None),
    ("Г-88 (H8)", "Вход после «закола»", "$", "не определена",
     "на главном варианте не определима: закол обнуляет возраст стены, а вариант берёт стены старше 45 мин"),
    ("Г-86 (H9)", "Рыночный вход на разъедании стены против лимитного, $ на позицию $500", "$", "не определена",
     "лимитная заявка на сигнале касания всегда пересекает спред и отклоняется — 0 исполнений, сравнивать не с чем"),
    ("Г-105 (H10)", "Стоп перед стеной против стопа 2 %, $ на позицию $500", "$", "не ясно", None),
    ("пара Г-85×Г-105", "Вход от фронтрана + стоп перед стеной вместе", "$", "не определена",
     "0 сигналов: форма стопа отклоняет план, когда фронтран в 1 тике от стены (почти всегда)"),
]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--r2", required=True)
    ap.add_argument("--r2-status", default="на проверке у Судьи")
    ap.add_argument("--coins-status", default="считается ночью")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    r2 = json.load(open(a.r2, encoding="utf-8"))
    rows = []
    for h, what, unit, v10, why in META:
        r = r2.get(h, {})
        months = {}
        for m in ("август", "сентябрь"):
            x = r.get(m, {})
            if "est" not in x:
                months[m] = None
                continue
            st = x.get("sign_test") or {}
            months[m] = {"est": round(x["est"], 2), "lo": round(x["ci95"][0], 2), "hi": round(x["ci95"][1], 2),
                         "p_holm": round(x["p_holm"], 4), "days_plus": st.get("days_plus"), "days": st.get("days"),
                         "drop_ok": x.get("sign_kept_after_drops")}
        rows.append({"h": h, "what": what, "unit": unit, "v10": v10, "why": why,
                     "r2": "не определена (p = 1 в Холме)" if why else r.get("r2", "не ясно"), "months": months})
    out = {"rows": rows, "r2_status": a.r2_status, "coins_status": a.coins_status,
           "note": "R2 — правило изменено после счёта (владелец 26.09: без порога эфф. N ≥ 30); кандидаты — находки на тех же "
                   "месяцах, не подтверждение. Доли отскоков — признаки стены, не деньги. Интервал — 95 %, блочный бутстреп по "
                   "суткам; p — после поправки Холма по всему пакету (11 испытаний в месяце)."}
    json.dump(out, open(a.out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(len(rows), "строк")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
