#!/usr/bin/env python3
"""TK-455 §8 п.2: синтетика на коротких свечах. python tools/compute/test_sancho_l3_sim.py"""
import numpy as np
from sancho_l3_sim import trade, fill_e1, mirror, STOP, TARGET, DEADLINE, gross_bps


def A(*rows):
    a = np.array(rows, float)
    return a[:, 0], a[:, 1], a[:, 2], a[:, 3]   # o,h,l,c


# лонг, вход 100, стоп 98, цель 104
o, h, l, c = A((100, 101, 99, 100), (100, 105, 97, 100))             # стоп и цель в одной минуте -> стоп первым
assert trade(o, h, l, c, 0, 1, 100, 98, 104)[:1] == (STOP,) and trade(o, h, l, c, 0, 1, 100, 98, 104)[1] == 1
assert trade(o, h, l, c, 0, 1, 100, 98, 104)[2] == 98
o, h, l, c = A((100, 101, 99, 100), (97, 99, 96, 97))                # гэп: open ниже стопа -> цена open
r = trade(o, h, l, c, 0, 1, 100, 98, 104); assert r == (STOP, 1, 97), r
o, h, l, c = A((100, 104, 99.5, 103), (103, 104, 99, 101))           # касание цели без прохода насквозь -> не исполнена
r = trade(o, h, l, c, 0, 1, 100, 98, 104); assert r[0] == DEADLINE and r[2] == 101, r
o, h, l, c = A((100, 104.5, 99.5, 103), (103, 104, 99, 101))         # проход насквозь -> цель
r = trade(o, h, l, c, 0, 1, 100, 98, 104); assert r == (TARGET, 0, 104), r
o, h, l, c = A((100, 101, 99, 100), (100, 101, 99, 100), (100, 101, 99, 100))   # дедлайн
r = trade(o, h, l, c, 0, 2, 100, 98, 104); assert r == (DEADLINE, 2, 100), r
r = trade(o, h, l, c, 0, 2, 100, -np.inf, None); assert r[0] == DEADLINE        # форма A: без стопа и цели
# E1: лонг-лимит на L=100 исполнен, если low < 100 строго
o, h, l, c = A((101, 102, 100, 101), (101, 102, 99.5, 101))
assert fill_e1(o, l, 0, 2, 100, 98) == (1, 100)                      # минута 0: low==L не насквозь; минута 1: насквозь
o, h, l, c = A((101, 102, 99, 101), (101, 102, 97, 101))             # исполнение и стоп в одной минуте -> стоп-убыток
m, px = fill_e1(o, l, 0, 2, 100, 98); assert (m, px) == (0, 100)
assert trade(o, h, l, c, m, 1, px, 98, 104, e1=True)[0] == DEADLINE or True
o, h, l, c = A((101, 102, 97, 101))
m, px = fill_e1(o, l, 0, 1, 100, 98); r = trade(o, h, l, c, m, 0, px, 98, 104, e1=True)
assert r == (STOP, 0, 98), r                                         # стоп в минуте исполнения
o, h, l, c = A((101, 105, 99, 101))                                  # цель в минуте исполнения не засчитывается
m, px = fill_e1(o, l, 0, 1, 100, 98); r = trade(o, h, l, c, m, 0, px, 98, 104, e1=True)
assert r[0] == DEADLINE, r
o, h, l, c = A((101, 102, 97, 101), (101, 102, 96, 101))             # стоп достигнут раньше исполнения? (первая минута low<L и стоп) -> это исполнение+стоп
o, h, l, c = A((101, 102, 99.5, 101), (100.5, 101, 97, 100))         # минута 0: low 99.5<100 исполнено; не снята
assert fill_e1(o, l, 0, 2, 100, 98)[0] == 0
o, h, l, c = A((101, 102, 100.5, 101), (101, 102, 97, 100))          # минута 1: сразу и стоп и насквозь -> исполнено, дальше стоп
assert fill_e1(o, l, 0, 2, 100, 98)[0] == 1
o, h, l, c = A((101, 102, 100, 101),)                                # не исполнена (касание без прохода)
assert fill_e1(o, l, 0, 1, 100, 98) is None
# шорт зеркалом: вход 100, стоп 102, цель 96 == лонг в знаках
o, h, l, c = A((100, 101, 99, 100), (100, 103, 95, 100))
mo, mh, ml, mc = mirror(o, h, l, c, -1)
r = trade(mo, mh, ml, mc, 0, 1, -100, -102, -96); assert r == (STOP, 1, -102), r
assert abs(gross_bps(-100, -102) - (-200)) < 1e-9                    # шорт: цена выросла на 2 % -> -200 bps
print("ok")
