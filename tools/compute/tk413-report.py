#!/usr/bin/env python3
"""TK-413: отчёт .md по csv эпизодов (tk413-episodes.py). Использование: tk413-report.py <episodes.csv> <out.md>"""
import collections
import csv
import statistics as st
import sys

rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8")))
HEAD = "10.48"


def f(x):
    return float(x) if x != "" else None


def q(v, p):
    v = sorted(v)
    return v[min(len(v) - 1, int(p * len(v)))] if v else float("nan")


def med(v):
    return st.median(v) if v else float("nan")


def ik(r):
    return (r["биржа"], r["рынок"], r["инструмент"])


by = collections.defaultdict(list)
for r in rows:
    by[r["порог_%"]].append(r)
o = []
w = o.append
w("# Памп/дамп-эпизоды сентября у волатильных монет (TK-413)\n")
w("Вход: свечи 1 м сентября (TK-411), 385 инструментов / 278 монет отбора TK-412 (правило Судьи: тип=монета, USD-котировка, "
  "≥10 дн., медиана дн. диапазона ≥10,48 %%). Время UTC. Счёт: `tools/compute/tk413-episodes.py` на calc (alsched, 15 яд., "
  "≈1 мин), отчёт `tk413-report.py`. csv — `pump-dump-episodes-sep-2026-10-26.csv` (все эпизоды трёх порогов, %d строк).\n" % len(rows))
w("## Определение (для решения Судьи, В-53)\n")
w("Эпизод = нога зигзага по закрытиям 1-м свечей: памп — от впадины до пика, дамп — от пика до дна; нога заканчивается, когда "
  "цена развернулась на θ от экстремума, поэтому каждый эпизод ≥ θ. Конец эпизода = следующий разворот; откат = доля хода, "
  "отыгранная до него (>1 — ушла за старт). Оборот эпизода = Σ quote_v от начала до пика; норма = медианный дневной оборот × "
  "длительность/1440.\n")
w("Пороги θ — из распределения: **10,48 % = p90 медианного дневного диапазона (число TK-412)** — основной; 5 % (наименьший "
  "порог таблицы TK-412) и 20 % — чувствительность. Порог и критерий конца — предложение, выбор за Судьёй.\n")
w("Плохие принты Gate: до зигзага выброшены одиночные закрытия-выбросы глубиной ≥5 %, вернувшиеся минимум на половину к "
  "соседям (число — колонка `выброшено_принтов`); `сомнительный`=да — эпизод держится на ≤3 минутах с торгами (остаток плохих "
  "принтов; в сводках исключён, в csv оставлен). Ограничения: зигзаг по закрытиям, фитили не считаются; выбросы длиннее "
  "1 минуты не ловятся.\n")
w("## Чувствительность к порогу\n")
w("| θ, % | эпизодов | из них сомнит. | на инструмент (мед.) | инстр. с ≥1 | мед. ход пампов, % | мед. длит. до пика, мин | мед. откат (доля) |")
w("|---|---|---|---|---|---|---|---|")
for th in sorted(by, key=float):
    rs = by[th]
    ok = [r for r in rs if r["сомнительный"] == "нет"]
    pc = collections.Counter(ik(r) for r in ok)
    pu = [f(r["ход_%"]) for r in ok if r["знак"] == "памп"]
    w("| %s | %d | %d | %.1f | %d | %.1f | %.0f | %.2f |" % (
        th, len(rs), len(rs) - len(ok), med(list(pc.values())), len(pc), med(pu),
        med([f(r["длит_до_пика_мин"]) for r in ok]), med([f(r["откат_доля"]) for r in ok])))
rs = [r for r in by[HEAD] if r["сомнительный"] == "нет"]
w("\nДалее — основной порог θ=%s %%, без сомнительных (%d эпизодов).\n" % (HEAD, len(rs)))
w("## Типичная форма\n")
w("| знак | N | ход % p25/мед/p75 | до пика, мин p25/мед/p75 | откат p25/мед/p75 | мин. до конца отката, мед. | оборот эпизода к норме, мед. |")
w("|---|---|---|---|---|---|---|")
for s in ("памп", "дамп"):
    x = [r for r in rs if r["знак"] == s]
    mv = [abs(f(r["ход_%"])) for r in x]
    d = [f(r["длит_до_пика_мин"]) for r in x]
    rt = [f(r["откат_доля"]) for r in x]
    rq = [f(r["оборот_к_норме"]) for r in x if r["оборот_к_норме"] != ""]
    w("| %s | %d | %.1f / %.1f / %.1f | %.0f / %.0f / %.0f | %.2f / %.2f / %.2f | %.0f | %.2f |" % (
        s, len(x), q(mv, .25), med(mv), q(mv, .75), q(d, .25), med(d), q(d, .75), q(rt, .25), med(rt), q(rt, .75),
        med([f(r["время_отката_мин"]) for r in x]), med(rq)))
w("\n## Эпизодов на инструмент и монету\n")
pc = collections.Counter(ik(r) for r in rs)
v = list(pc.values())
w("На инструмент: мин %d, p25 %d, мед. %.0f, p75 %d, макс %d (инструментов с эпизодами: %d из 385)." % (
    min(v), q(v, .25), med(v), q(v, .75), max(v), len(pc)))
cc = collections.Counter(r["ключ_монеты"] for r in rs)
w("\nТоп-15 монет по числу эпизодов (все её инструменты вместе):\n")
w("| монета | эпизодов | бирж×рынков |")
w("|---|---|---|")
for k, n in cc.most_common(15):
    w("| %s | %d | %d |" % (k, n, len({(r["биржа"], r["рынок"]) for r in rs if r["ключ_монеты"] == k})))


def table(lst, cols):
    w("| " + " | ".join(c for c, _ in cols) + " |")
    w("|" + "---|" * len(cols))
    for r in lst:
        w("| " + " | ".join(fn(r) for _, fn in cols) + " |")


def usd(r):
    return "{:,.0f}".format(f(r["оборот_эпизода_usd"])).replace(",", " ")


cols = [("инструмент", lambda r: "%s %s %s" % ik(r)), ("знак", lambda r: r["знак"]), ("начало UTC", lambda r: r["начало_utc"]),
        ("ход %", lambda r: r["ход_%"]), ("до пика, мин", lambda r: r["длит_до_пика_мин"]), ("откат", lambda r: r["откат_доля"]),
        ("оборот эп., $", usd), ("к норме", lambda r: r["оборот_к_норме"]),
        ("синхрон (пара, лаг старта мин)", lambda r: ("%s (%s)" % (r["пара_инструмент"], r["лаг_старта_мин"])) if r["синхрон"] == "да" else "нет")]
w("\n## Топ-20 по величине хода (без сомнительных)\n")
table(sorted(rs, key=lambda r: -abs(f(r["ход_%"])))[:20], cols)
w("\n## Топ-20 по обороту эпизода\n")
table(sorted(rs, key=lambda r: -f(r["оборот_эпизода_usd"]))[:20], cols)
liq = [r for r in rs if f(r["мед_оборот_дня_usd"]) >= 1e6]
li = collections.Counter(ik(r) for r in liq)
w("\n## Ликвидные (медианный дневной оборот ≥ 1 млн $)\n")
w("Инструментов: %d, эпизодов: %d (на инструмент мед. %.0f).\n" % (len(li), len(liq), med(list(li.values()))))
w("| знак | N | ход % p25/мед/p75 | до пика, мин мед. | откат мед. | оборот к норме мед. |")
w("|---|---|---|---|---|---|")
for s in ("памп", "дамп"):
    x = [r for r in liq if r["знак"] == s]
    mv = [abs(f(r["ход_%"])) for r in x]
    w("| %s | %d | %.1f / %.1f / %.1f | %.0f | %.2f | %.2f |" % (
        s, len(x), q(mv, .25), med(mv), q(mv, .75), med([f(r["длит_до_пика_мин"]) for r in x]),
        med([f(r["откат_доля"]) for r in x]), med([f(r["оборот_к_норме"]) for r in x if r["оборот_к_норме"] != ""])))
w("\nТоп-15 ликвидных по ходу:\n")
table(sorted(liq, key=lambda r: -abs(f(r["ход_%"])))[:15], cols)
w("\n## Синхронность со второй биржей/рынком той же монеты\n")
pr = [r for r in rs if r["есть_пара_монеты"] != "0"]
sy = [r for r in pr if r["синхрон"] == "да"]
w("Эпизодов с парным инструментом той же монеты: %d; найден эпизод того же знака с пересечением интервалов "
  "[начало, пик]: %d (%.0f %%)." % (len(pr), len(sy), 100 * len(sy) / max(1, len(pr))))
st_ = [r for r in sy if f(r["перекрытие_доля"]) >= 0.5]
w("Для чтения лага взяты пары с перекрытием ≥ 50 %% короткого интервала (порог чтения, не отбора): %d.\n" % len(st_))
w("| наш ← пара | N | лаг старта, мин p25/мед/p75 | первый: мы / пара / вместе |")
w("|---|---|---|---|")
grp = collections.defaultdict(list)
for r in st_:
    grp[((r["биржа"], r["рынок"]), tuple(r["пара_инструмент"].split(":")[0].split("/")))].append(r)
for k, x in sorted(grp.items(), key=lambda kv: -len(kv[1]))[:12]:
    lg = [f(r["лаг_старта_мин"]) for r in x]
    c = collections.Counter(r["первый"] for r in x)
    w("| %s/%s ← %s/%s | %d | %.0f / %.0f / %.0f | %d / %d / %d |" % (
        k[0][0], k[0][1], k[1][0], k[1][1], len(x), q(lg, .25), med(lg), q(lg, .75), c["мы"], c["пара"], c["одновременно"]))
w("\n«первый»: мы — наш инструмент стартовал раньше пары (лаг>0 — пара стартовала позже на лаг минут). Оговорки: перекрытие "
  "длинных эпизодов с короткими даёт большие лаги; разрешение — минута; у тонких Gate-инструментов мало минут с торгами "
  "(`минут_с_торгами`).\n")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(o) + "\n")
