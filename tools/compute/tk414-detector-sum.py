#!/usr/bin/env python3
"""TK-414: сводка детектора общих точек (tk414-detector.py). Вес ноги = 1/(число ног её инструмента в группе) — равный вес инструментов.
Использование: tk414-detector-sum.py <det15-legs.csv> <det15-fp.csv> > md-таблицы"""
import sys
import numpy as np
import pandas as pd

L = pd.read_csv(sys.argv[1])
F = pd.read_csv(sys.argv[2])
V = F[F.вариант == "5"][["биржа", "рынок", "инструмент", "волатильный"]]
L = L.merge(V, on=["биржа", "рынок", "инструмент"], how="left")
L = L[L.волатильный == 1]  # ноги — только отобранные волатильные монеты (правило Судьи TK-412), там плохие принты отсеяны TK-413


def wq(v, w, qs=(0.25, 0.5, 0.75)):
    m = v.notna()
    v, w = v[m].to_numpy(), w[m].to_numpy()
    if len(v) == 0:
        return [float("nan")] * len(qs)
    o = np.argsort(v)
    v, w = v[o], w[o]
    cw = np.cumsum(w) / w.sum()
    return [float(v[min(np.searchsorted(cw, q), len(v) - 1)]) for q in qs]


def fmt(x, d=1):
    return "—" if x != x else f"{x:.{d}f}"


def tab(g, cols):
    g = g.copy()
    g["w"] = 1.0 / g.groupby(["биржа", "рынок", "инструмент"])["ход_pct"].transform("size")
    out = {}
    for c, d in cols:
        out[c] = [fmt(x, d) for x in wq(g[c], g.w)]
    return out, len(g), g["инструмент"].nunique()


print("## Запаздывание и ошибки по точкам (кварт. 25/50/75, равный вес инструментов)\n")
for var in ["5", "3.5", "7", "5half"]:
    for sign in ["памп", "дамп"]:
        g = L[(L.вариант == var) & (L.знак == sign)]
        t, n, ni = tab(g, [("D_лаг_мин", 0), ("D_доля_хода", 2), ("старт_ошибка_мин", 0), ("разворот_лаг_мин", 0),
                            ("разворот_отдано_доля", 2), ("пик_ошибка_мин", 0)])
        print(f"**θs={var} {sign}**: ног {n}, инструментов {ni}, ног с ≥1 ложным разворотом внутри {100 * (g.пауз_ложных > 0).mean():.0f} %, "
              f"ложных разворотов на ногу (среднее) {g.пауз_ложных.mean():.2f}")
        print("| точка | 25 % | 50 % | 75 % |\n|---|---|---|---|")
        names = {"D_лаг_мин": "(1) «это памп/дамп»: лаг от старта, мин", "D_доля_хода": "(1) доля хода к моменту",
                 "старт_ошибка_мин": "(2) ошибка оценки старта, мин", "разворот_лаг_мин": "(4) разворот: лаг от пика, мин",
                 "разворот_отдано_доля": "(4) отдано к моменту, доля хода", "пик_ошибка_мин": "(3) ошибка оценки пика, мин"}
        for k, v in t.items():
            print(f"| {names[k]} | " + " | ".join(v) + " |")
        r = g.возобн_мин_от_дна.dropna()
        print(f"(5) возобновление после ложной паузы: ног с паузой {len(r)}, медиана мин от дна паузы {fmt(r.median(), 0)}\n")

print("## Где общее правило ломается: по форме (θs=5 %, равный вес инструментов; формы только у ликвидных ног слоя 2)\n")
print("| форма | знак | ног | D лаг мин (ме) | D доля хода (ме) | разворот лаг мин (ме) | отдано доля (ме) | ног с ложной паузой, % | ложных на ногу |\n|---|---|---|---|---|---|---|---|---|")
G = L[(L.вариант == "5") & L.форма.notna()]
for (form, sign), g in G.groupby(["форма", "знак"]):
    t, n, ni = tab(g, [("D_лаг_мин", 0), ("D_доля_хода", 2), ("разворот_лаг_мин", 0), ("разворот_отдано_доля", 2)])
    print(f"| {form} | {sign} | {n} | {t['D_лаг_мин'][1]} | {t['D_доля_хода'][1]} | {t['разворот_лаг_мин'][1]} | {t['разворот_отдано_доля'][1]} | "
          f"{100 * (g.пауз_ложных > 0).mean():.0f} | {g.пауз_ложных.mean():.2f} |")

print("\n## Ложные срабатывания «нога началась» вне ног эталона (события знака s без ноги θ10,48 % того же знака)\n")
print("| θs | группа | инстр. | инстр.-суток | событий | ложных | доля ложных | ложных на инстр.-сутки |\n|---|---|---|---|---|---|---|---|")
for var in ["5", "3.5", "7", "5half"]:
    f = F[F.вариант == var]
    for name, g in [("все", f)] + [(f"{a} {b}", x) for (a, b), x in f.groupby(["биржа", "рынок"])] + \
                   [("волатильные", f[f.волатильный == 1]), ("прочие", f[f.волатильный == 0])]:
        if len(g) == 0:
            continue
        d, e, fp = g.дней.sum(), g.событий.sum(), g.ложных.sum()
        print(f"| {var} | {name} | {len(g)} | {d} | {e} | {fp} | {100 * fp / max(e, 1):.0f} % | {fp / max(d, 1):.2f} |")
