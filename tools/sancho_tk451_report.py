def ytab(c, k, d, oc):
    s = yr[(yr.claim == c) & (yr.tf == 60) & (yr.k == k) & (yr.dir == d) & (yr.oc == oc)]
    out = ['| год | монет | N | доля события, % | контроль C1, % | Δ C1, пп [95 %] | Δ C2, пп [95 %] |', '|---|---|---|---|---|---|---|']
    for y_, gr in s.groupby('year'):
        r1 = gr[gr.ctl == 'C1']; r2 = gr[gr.ctl == 'C2']
        if r1.empty or r2.empty:
            continue
        r1 = r1.iloc[0]; r2 = r2.iloc[0]
        out.append(f'| {y_} | {r1.nsym} | {int(r1.N)}{" (мало)" if r1.N < 200 else ""} | {r1.p_ev*100:.1f} | {r1.p_ctl*100:.1f} | {r1.delta*100:+.1f} [{r1.lo*100:+.1f}; {r1.hi*100:+.1f}] | {r2.delta*100:+.1f} [{r2.lo*100:+.1f}; {r2.hi*100:+.1f}] |')
    return '\n'.join(out)


