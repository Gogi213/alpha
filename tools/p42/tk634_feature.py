            rows.append([f"{SIDE[side]} · {FAM[fam]} · {CTX[ctx]} история", OUTCOME[unit], str(sl["n"]), num(sl["sum"], 2, True), num(sl["sharpe"], 2, True),
                         str(base["n"]), num(base["sum"], 2, True), num(base["sharpe"], 2, True), f"{num(r['d'], 2, True)} ± {num(r['se'])}"])
