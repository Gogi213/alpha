COLS = ["Сторона · признак · история", "Исход единицы", "Сделок", "Сумма, $", "Шарп (год)", "База: сделок", "База: сумма, $", "База: шарп (год)", "Δ к базе, $ на сделку (± ошибка)"]
rows, cids = [], []
for side in "LS":
    base = S["slices_h775"][side]["база"]
    for fam in ("IMP", "FLOW"):
        for ctx in ("own", "cross"):
            cid = f"{fam}_{ctx}"
            r, sl = S["rows"][side][cid], S["slices_h775"][side][cid]
