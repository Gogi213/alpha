def main():
    base = {}
    for ln in open(APP, encoding="utf-8"):
        c = [x.strip() for x in ln.strip().strip("|").split("|")]
        if re.match(r"^bp(\d\d|P)-\d\d$", c[0]):
            base[c[0]] = c
    rows = []
    for ln in M.strip().splitlines():
        i, cls, defs, axis, chk, test = [x.strip() for x in ln.split("|")]
        b = base.pop(i)
        f = {"да": "да", "ч": "частично", "нет": "нет"}[b[3]]
        rows.append([i, b[1], b[2], cls, f, b[4], axis, b[5], defs.replace(";", " "), chk, test, b[6]])
    assert not base, f"не размечены: {list(base)}"
    with open(OUT, "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["id", "урок", "утверждение", "класс", "формализуется", "что_не_определено",
                    "ось_титрования_или_причина", "данные", "идентификаторы_определений", "проверяется",
                    "тест_B2", "файл:строка"])
        w.writerows(rows)
    print(len(rows), "строк ->", OUT)
    print("формализуется:", dict(collections.Counter(r[4] for r in rows)))
    print("проверяется:", dict(collections.Counter(r[9] for r in rows)))
    print("по классам:", dict(collections.Counter(r[3] for r in rows)))
    nz = [r[0] for r in rows if r[9] == "нет"]
    print("не проверяется:", len(nz), nz)
    ts = collections.Counter(t for r in rows for t in re.findall(r"G\d\.\d", r[10]))
    print("тестов B2 в реестре:", len(ts), sorted(ts))


if __name__ == "__main__":
    main()
