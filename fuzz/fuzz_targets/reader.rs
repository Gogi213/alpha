//! Фаззинг читателя бинлога (Decision 30): произвольные байты в
//! `Reader::open` + вычитка всех кадров до конца. Паника, зависание и OOM
//! здесь — дефект: формат спроектирован против враждебного поля длины
//! (Decision 23), и эта защита ни разу не атакована.
//!
//! Тело намеренно повторяет золотой тест фикстуры один в один — расхождение
//! между ними и есть предмет ловли. Потолок кадров стоит, чтобы злонамеренный
//! вход не превращал прогон в бесконечность: читатель по контракту отдаёт
//! `None` в конце потока, и лимит лишь страхует.
//!
//! Проверено компиляцией в джобе (nightly доступен только там); тело — четыре
//! вызова публичного API, зеркально покрытые `live_fixture_*` тестами.
#![no_main]

use alpha::binlog::Reader;
use libfuzzer_sys::fuzz_target;

/// Верхняя граница кадров на один вход: злонамеренный поток кадров по одному
/// пустому кадру иначе крутился бы вечно в пределах одного прогона.
const MAX_FRAMES_PER_INPUT: usize = 4096;

fuzz_target!(|data: &[u8]| {
    let Ok(mut reader) = Reader::open(data) else {
        return;
    };
    let _ = reader.header();
    let mut frames = 0usize;
    while let Ok(Some(_records)) = reader.read_frame() {
        frames += 1;
        if frames >= MAX_FRAMES_PER_INPUT {
            break;
        }
    }
});
