//! Статистика вывода: wild cluster bootstrap-t.
//!
//! Здесь реализован только bootstrap-t (шаг 7.2, нужен уже в 5.2 для гейта
//! G2). DSR, PBO и CPCV — предмет отдельного шага; они реализованы, но не
//! здесь, а в `crate::lob::final_metrics` (см. doc-комментарий модуля).
//!
//! # Почему bootstrap, а не асимптотический кластерный t-тест
//!
//! Обычный кластерный CRVE-тест сравнивает t-статистику с `t(G-1)`: при семи
//! кластерах (`t = 3` на шести степенях свободы) это даёт `p ≈ 0.012` —
//! правдоподобно, но робастная дисперсия при таком `G` смещена вниз, и
//! асимптотика попросту не подтверждена на такой малой выборке кластеров
//! (Decision 9). Wild cluster bootstrap-t не полагается на асимптотику: он
//! строит референсное распределение самой t-статистики, многократно обнуляя
//! эффект знаковой инверсией остатков по кластерам, и сравнивает наблюдённое
//! значение с ним впрямую.
//!
//! # Почему веса Уэбба, а не Радемахера
//!
//! У знаковой инверсии есть конечная сетка исходов: на `G` кластерах и `k`
//! различных значениях веса возможно ровно `k^G` векторов знаков, и это же —
//! предел разрешения p-значения при полном переборе (реплики — лишь
//! монте-карловская выборка из этого множества, и их число сетку не мельчит).
//! При `G = 7` радемахеровские веса (`k = 2`) дают `128` векторов и минимальный
//! односторонний `p ≈ 1/128 ≈ 0.0078` — грубее альфы гейта G2 (`0.005`), то есть
//! гейт вернул бы красный арифметически, независимо от данных. Шеститочечные
//! веса Уэбба (`k = 6`) дают `6^7 = 279 936` — с запасом уже при семи кластерах.
//! Отсюда и требование печатать достижимое разрешение сетки перед вердиктом:
//! `webb_p_grid_resolution` — ровно эта величина.

use std::collections::BTreeMap;

/// Минимум кластеров, единственное объявление во всём документе (спека
/// редакции 3, §9: назначаемое число — до данных и коммитом, один раз).
/// Ниже него выборка не набрана по построению флага `lob watch`, и это
/// дефект счётчика, а не рыночный исход — вердикт не выносится вовсе.
/// Значение выведено, не подобрано: при `G = 7` весовые вектора Уэбба
/// (`k = 6`) дают `6^7 = 279 936` — с запасом тоньше альфы гейта G2 (см.
/// docs модуля выше), тогда как радемахеровские (`k = 2`) на этом же `G`
/// дают только `128` — грубее альфы арифметически. `lob/shortlist.rs`
/// сводит свой прежний отдельный порог к этой же константе.
pub const G_MIN: usize = 7;

/// Число реплик wild-бутстрапа (Decision 9). Фиксировано планом, а не
/// подобрано: тесты, которым нужна скорость, передают своё меньшее число —
/// сигнатура принимает его параметром ровно затем, чтобы не плодить второй
/// смысл константы.
pub const BOOTSTRAP_REPLICATIONS: u32 = 9999;

/// Единственная объявленная альфа бутстрап-тестов документа: 0.005
/// (изначально — поправка Бонферрони на две ячейки гейта G2, §5.2, снятого
/// таском 17; число не привязано к тому гейту и пережило его снос — сегодня
/// её читают `shortlist::hour_dependence_test` (тест на час суток),
/// `pilot`/`profiles` (интервал `net_fill`) и `backtest` (канонические
/// `alpha`/`replications` вердикта на очереди)). Именованная константа, а
/// не только параметр функции: если б каждый вызывающий заново писал
/// `0.005`, любая опечатка была бы неотличима от сознательного решения.
pub const GATE_ALPHA: f64 = 0.005;

/// Число различных значений одного веса Уэбба (Decision 9): шесть точек,
/// не два радемахеровских — сравнение см. в тесте на арифметике решения.
pub const WEBB_WEIGHT_VALUES: u32 = 6;

/// Причина, по которой тест отказывается вынести p-значение, вместо того
/// чтобы вернуть число, посчитанное на сетке грубее альфы, или запаниковать.
/// Оба варианта — методический отказ, а не рыночный: PLAN.md называет это
/// прямо («если оно грубее 0.005, тест не выносится, и это методический
/// красный, а не рыночный», гейт G2).
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum BootstrapError {
    /// Кластеров меньше `G_MIN`. При открытой записи (Decision 21) это
    /// значит, что `lob watch` выставил флаг неверно, и раньше починки счётчика
    /// вердикт не выносится вовсе — не «недобор как исход», а дефект.
    TooFewClusters { clusters: usize, minimum: usize },
    /// Достижимое разрешение сетки (`webb_p_grid_resolution`) грубее `alpha`:
    /// при полном переборе весовых векторов минимальный ненулевой p больше
    /// alpha, и никакие данные и никакое число реплик этого не изменят.
    GridTooCoarse {
        clusters: usize,
        resolution: f64,
        alpha: f64,
    },
    /// Наблюдённая сумма квадратов внутрикластерных остатков равна нулю
    /// (markout тождественно ноль, или любая константа на всех
    /// наблюдениях): знаменатель `t_obs` — ноль, и результат либо `NaN`
    /// (среднее тоже ноль), либо `±inf` (среднее ненулевое). FIX 1: без
    /// этой проверки сравнение `t_star >= t_obs` в цикле реплик ложно в
    /// IEEE-754 для любой конечной реплики при `t_obs = NaN` (а при `t_obs
    /// = +inf` истинно только для настолько же вырожденных реплик), и
    /// счётчик «не менее экстремальных» остаётся нулевым или почти нулевым
    /// независимо от данных — бутстрап тогда молча возвращает минимальный
    /// достижимый p (~1/(B+1)), то есть максимальную значимость ровно там,
    /// где сигнала нет вообще. Это единственный вариант ошибки, который
    /// говорит не «данных мало» и не «сетка грубая», а «дисперсия этой
    /// выборки не позволяет посчитать t вообще» — гейт G2 обязан отказаться
    /// здесь, а не запаниковать и не вернуть NaN/inf вызывающему коду.
    DegenerateVariance { clusters: usize },
}

/// Достижимое разрешение сетки p при полном переборе весовых векторов на
/// `clusters` кластерах и `weight_values` различных значениях веса на кластер.
///
/// Это свойство пространства весовых векторов, а не числа бутстрап-реплик:
/// реплики — монте-карловская выборка из этого же множества, и увеличение их
/// числа не может различить два исхода тоньше, чем допускает полный перебор.
/// Общая форма нужна ровно затем, чтобы явно посчитать и радемахеровский, и
/// уэббовский случай одной функцией — сравнение между ними и есть арифметика,
/// на которой стоит Decision 9 (см. тест `rademacher_at_seven_clusters...`).
pub fn p_grid_resolution(clusters: u32, weight_values: u32) -> f64 {
    1.0 / (weight_values as f64).powi(clusters as i32)
}

/// То же самое при весах Уэбба — тех, что реально использует бутстрап ниже.
/// PLAN.md требует печатать это число перед каждым тестом гейта G2.
pub fn webb_p_grid_resolution(clusters: u32) -> f64 {
    p_grid_resolution(clusters, WEBB_WEIGHT_VALUES)
}

/// Десятичный логарифм того же разрешения — версия для печати, а не для
/// сравнения с `alpha` (для сравнения годится и `p_grid_resolution`, см.
/// ниже почему).
///
/// FIX 4: `p_grid_resolution` считает `weight_values^clusters` в `f64`, и при
/// весах Уэбба (`weight_values = 6`) эта степень переполняет диапазон `f64`
/// (`> 1.8e308`) начиная с `clusters = 397` — `p_grid_resolution(396, 6)` ещё
/// `≈ 7.1e-397` (denormal), а `p_grid_resolution(397, 6)` уже ровно `0.0`,
/// не приближённо, а побитово (проверено тестом
/// `p_grid_resolution_underflows_to_zero_at_397_clusters...`). На вердикт
/// гейта это не влияет: разрешение убывает по `clusters` монотонно, «стало
/// точным нулём вместо denormal-числа» остаётся на той же стороне сравнения
/// с `alpha`, что и было, и ни один вердикт от этого не переворачивается.
/// Но PLAN.md требует печатать разрешение перед каждым вердиктом как
/// свидетельство, а плоский `0.0` ничего не свидетельствует зрителю отчёта —
/// не видно, разрешение «чуть тоньше alpha» или «на 300 порядков тоньше».
/// `log10(resolution) = clusters · log10(weight_values)` растёт по модулю
/// без остановки и не обнуляется ни при каком `clusters`, поэтому годится
/// для печати там, где сама величина уже недоступна.
pub fn p_grid_resolution_log10(clusters: u32, weight_values: u32) -> f64 {
    -(clusters as f64) * (weight_values as f64).log10()
}

/// Логарифмическая версия `webb_p_grid_resolution` — см. `p_grid_resolution_log10`.
pub fn webb_p_grid_resolution_log10(clusters: u32) -> f64 {
    p_grid_resolution_log10(clusters, WEBB_WEIGHT_VALUES)
}

/// Один из шести весов Уэбба по индексу `0..WEBB_WEIGHT_VALUES`, равновероятному.
///
/// Значения `{-√1.5, -1, -√0.5, √0.5, 1, √1.5}` — стандартное шеститочечное
/// распределение (Webb, 2014): среднее ноль по симметрии, второй момент
/// `(1.5 + 1 + 0.5) · 2 / 6 = 1`, то есть знаковая инверсия не меняет масштаб
/// остатков в среднем по репликам, только их знак и «вес».
pub(crate) fn webb_weight(index: u32) -> f64 {
    debug_assert!(index < WEBB_WEIGHT_VALUES, "индекс веса вне сетки Уэбба");
    match index {
        0 => -(1.5_f64).sqrt(),
        1 => -1.0,
        2 => -(0.5_f64).sqrt(),
        3 => (0.5_f64).sqrt(),
        4 => 1.0,
        _ => (1.5_f64).sqrt(),
    }
}

/// Детерминированный генератор псевдослучайных чисел: SplitMix64.
///
/// Не крейт `rand`: ARCHITECTURE.md A2 требует, чтобы один и тот же вход давал
/// один и тот же результат на любой машине и при любой сборке, а версия `rand`
/// или её движка может смениться вместе с `Cargo.lock` без ведома этого модуля.
/// Собственная реализация фиксирует поведение раз и навсегда тем же кодом,
/// что его использует. Алгоритм — ровно splitmix64 Виньи (2015): golden-ratio
/// приращение состояния плюс два раунда xorshift-умножения, стандартный выбор
/// для «маленького быстрого детерминированного источника», не для криптографии.
pub(crate) struct SplitMix64 {
    state: u64,
}

impl SplitMix64 {
    pub(crate) fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    pub(crate) fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// Индекс веса Уэбба, равновероятный по `0..WEBB_WEIGHT_VALUES`.
    ///
    /// Смещение остатка `u64 % 6` пренебрежимо: `2^64 % 6 = 4`, то есть четыре
    /// из шести значений на одно повторение источника вероятнее прочих на долю
    /// порядка `6 / 2^64` — неразличимо на 9999 репликах ни при каком `alpha`
    /// из этого документа.
    /// Индекс доказуемо < 6 по построению остатка — на любом указателе.
    fn next_webb_weight(&mut self) -> f64 {
        webb_weight((self.next_u64() % WEBB_WEIGHT_VALUES as u64) as u32)
    }
}

/// Счётчик коллекции в `f64` / `u64` — единственные аудированные точки таких
/// преобразований для статистики. Точны, пока счётчик < 2^53 / укладывается
/// в 64 бита: счётчики здесь — длины срезов и числа испытаний в памяти,
/// порядков единиц–миллионов. Исчерпать предел значило бы не влезть в RAM
/// на десятки порядков раньше.
pub(crate) fn count_f64(n: usize) -> f64 {
    n as f64
}

/// См. `count_f64`: та же точка для счётчиков, уже живущих в `u64`
/// (сводки по суткам с насыщающим сложением).
pub(crate) fn count_f64_u64(n: u64) -> f64 {
    n as f64
}

/// См. `count_f64`: та же аудированная точка для целочисленных счётчиков.
pub(crate) fn count_u64(n: usize) -> u64 {
    n as u64
}

/// Группирует наблюдения по кластеру (сутки UTC). `BTreeMap`, а не
/// `HashMap`: порядок обхода кластеров обязан быть детерминирован и не
/// зависеть от порядка входного среза — иначе PRNG раздавал бы веса кластерам
/// в разном порядке при одинаковом seed, и одинаковый вход не давал бы
/// одинаковый p (ARCHITECTURE.md A2).
fn group_by_cluster(observations: &[(i64, f64)]) -> BTreeMap<i64, Vec<f64>> {
    let mut groups: BTreeMap<i64, Vec<f64>> = BTreeMap::new();
    for &(cluster, value) in observations {
        groups.entry(cluster).or_default().push(value);
    }
    groups
}

/// Свод по одному кластеру: число наблюдений и их сумма — и ничего больше.
///
/// FIX 2: в модели с одной константой (markout, без регрессоров) псевдоданные
/// реплики — это `y* = w_g · y`, линейное преобразование внутри кластера, а
/// t-статистика (см. `cluster_robust_t_from_summary`) зависит от кластера
/// только через `(n_g, sum_g)`: домножение суммы на `w_g` даёт сумму
/// псевдокластера без обращения к отдельным наблюдениям. Раньше на каждой из
/// `BOOTSTRAP_REPLICATIONS` реплик заново строился `BTreeMap<i64, Vec<f64>>` и
/// статистика заново проходила по всем `n` наблюдениям — работа, которая от
/// реплики к реплике не меняется вообще, кроме одного веса на кластер. Свод
/// считается один раз до цикла; сама реплика — это `O(G)`, а не `O(n)`.
#[derive(Debug, Clone, Copy)]
struct ClusterSummary {
    n: usize,
    sum: f64,
}

/// Строит свод по кластерам один раз, в порядке обхода `BTreeMap` (том же
/// порядке, в котором ниже расходуются веса генератора, — это и держит
/// детерминизм ARCHITECTURE.md A2).
fn summarize_clusters(groups: &BTreeMap<i64, Vec<f64>>) -> Vec<ClusterSummary> {
    groups
        .values()
        .map(|values| ClusterSummary {
            n: values.len(),
            sum: values.iter().sum(),
        })
        .collect()
}

/// Кластерно-робастная t-статистика для проверки «среднее равно нулю» на
/// модели с одной константой, поверх уже свёрнутого по кластерам `(n_g,
/// sum_g)` и веса на кластер (единицы для наблюдённого `t`, веса Уэбба
/// реплики — для `t*`).
///
/// Та же формула, что применяется к наблюдению, применяется и к каждой
/// реплике этой же функцией — иначе референсное распределение считалось бы
/// не тем же тестом, и сравнение потеряло бы смысл. Отличие от прежней
/// версии — только в том, что вход уже свёрнут (FIX 2): `w_g · sum_g` здесь
/// то же самое, что раньше было суммой `w_g · y_i` по всем точкам кластера.
///
/// Поправка `G / (G - 1)` — стандартная малая-выборочная поправка
/// Cameron-Gelbach-Miller для CRVE с одним регрессором (константой, `K = 1`):
/// `(G/(G-1)) · (n-1)/(n-K) = G/(G-1)` при `K = 1`. Ей отвечает «G-1 степеней
/// свободы» из Decision 9 — без неё дисперсия при малом `G` смещена вниз
/// именно так, как объясняет её обоснование.
///
/// Может вернуть не конечное число (FIX 1): если для этих весов сумма
/// квадратов внутрикластерных остатков — точный ноль (наблюдённые данные —
/// константа, или вырожденное сочетание весов реплики), знаменатель — ноль,
/// и результат `NaN` (среднее тоже ноль) либо `±inf` (среднее ненулевое).
/// Проверка результата — дело вызывающего кода, не этой функции: для
/// наблюдённого `t` это отказ (`DegenerateVariance`), для `t*` реплики —
/// решение, разобранное в комментарии над циклом реплик.
///
/// Касты счётчиков в `f64` точные: `n` — число наблюдений в памяти, `g` —
/// число суток; оба порядков единиц–тысяч, далеко от 2^53.
fn cluster_robust_t_from_summary(clusters: &[ClusterSummary], weights: &[f64]) -> f64 {
    debug_assert_eq!(
        clusters.len(),
        weights.len(),
        "вес на кластер обязан быть по одному на каждый элемент свода"
    );
    let n: usize = clusters.iter().map(|c| c.n).sum();
    let g = clusters.len();

    let total: f64 = clusters.iter().zip(weights).map(|(c, &w)| w * c.sum).sum();
    let mean = total / n as f64;

    let sum_sq_cluster_residuals: f64 = clusters
        .iter()
        .zip(weights)
        .map(|(c, &w)| {
            let cluster_residual_sum = w * c.sum - c.n as f64 * mean;
            cluster_residual_sum * cluster_residual_sum
        })
        .sum();

    let correction = g as f64 / (g as f64 - 1.0);
    let variance = correction * sum_sq_cluster_residuals / (n as f64 * n as f64);
    mean / variance.sqrt()
}

/// Односторонний wild cluster bootstrap-t (Decision 9): проверяет `H0: среднее
/// ≤ 0` против `H1: среднее > 0`. Односторонний — потому что Decision 14
/// приводит знак `m` так, что предсказанное направление всегда положительно,
/// и гейт G2 читает ровно эту гипотезу.
///
/// `observations` — пары (кластер = сутки UTC, значение, например `m` в bps).
/// Кластер — целое (A1: сравнение и группировка идут по целому, не по `f64`).
///
/// Возвращает `Err`, а не паникует и не занижает вердикт молча, в двух
/// случаях: кластеров меньше минимума, или сетка p грубее `alpha` — оба
/// прописаны в PLAN.md как методический, а не рыночный отказ.
///
/// Каст ниже точен: кластеров — дни в памяти (единицы), далеко от 2^32.
pub fn wild_cluster_bootstrap_t(
    observations: &[(i64, f64)],
    replications: u32,
    alpha: f64,
    seed: u64,
) -> Result<f64, BootstrapError> {
    let groups = group_by_cluster(observations);
    let clusters = groups.len();

    if clusters < G_MIN {
        return Err(BootstrapError::TooFewClusters {
            clusters,
            minimum: G_MIN,
        });
    }

    let resolution = webb_p_grid_resolution(clusters as u32);
    if resolution > alpha {
        return Err(BootstrapError::GridTooCoarse {
            clusters,
            resolution,
            alpha,
        });
    }

    // FIX 2: свод считается один раз, а не заново на каждой реплике внутри
    // цикла ниже (см. `ClusterSummary`).
    let summary = summarize_clusters(&groups);
    let unit_weights = vec![1.0; summary.len()];
    let t_obs = cluster_robust_t_from_summary(&summary, &unit_weights);

    // FIX 1: наблюдённая статистика обязана быть конечной, иначе сравнение
    // `t_star >= t_obs` ниже ложно для NaN на любой реплике (IEEE-754) или
    // истинно только для настолько же вырожденных `t_star` при `t_obs =
    // ±inf`, — в обоих случаях счётчик «не менее экстремальных» перестаёт
    // отражать данные, и функция вернула бы p, посчитанный на основании
    // числа, которое числом не является. Отказ здесь, а не NaN/inf наружу.
    if !t_obs.is_finite() {
        return Err(BootstrapError::DegenerateVariance { clusters });
    }

    let mut rng = SplitMix64::new(seed);
    // FIX 2: один буфер весов на весь цикл реплик, аллоцированный один раз
    // до цикла. Внутри цикла `iter_mut()` только перезаписывает элементы на
    // месте — ни длина, ни ёмкость не меняются, значит ни на одной из
    // `replications` реплик этот буфер повторно не аллоцируется.
    let mut weights = vec![0.0; summary.len()];
    let mut at_least_as_extreme = 0u32;
    for _ in 0..replications {
        for w in weights.iter_mut() {
            *w = rng.next_webb_weight();
        }
        let t_star = cluster_robust_t_from_summary(&summary, &weights);
        // FIX 1: не конечный `t_star` — не «слабая» реплика и не «сильная»,
        // а реплика, для которой знаменатель t тоже выродился в ноль (тот
        // же дефект дисперсии, что и у `t_obs`, но случившийся для этого
        // конкретного вектора весов реплики). Молчаливо считать её «не
        // экстремальной» (пропустить) означало бы повторить именно ту
        // ошибку, которую чинит `DegenerateVariance` для наблюдённой
        // статистики — только на уровне одной реплики, а не всего теста, и
        // с тем же результатом: заниженный p. Гейт G2 обязан скорее
        // недосчитать сигнал, чем переучесть его (см. шапку модуля про
        // методический красный вместо рыночного), поэтому вырожденная
        // реплика считается «не менее экстремальной» — это увеличивает p,
        // а не уменьшает, и никогда не может протолкнуть гейт по ошибке.
        if !t_star.is_finite() || t_star >= t_obs {
            at_least_as_extreme += 1;
        }
    }

    // +1/+1 (Davison & Hinkley): наблюдённая статистика — тоже одна из
    // реализаций под нулём, а не привилегированная точка сравнения. Без этого
    // конечное число реплик могло бы дать ровный ноль там, где верно лишь
    // «меньше одной реплики из B», что не одно и то же.
    Ok((at_least_as_extreme as f64 + 1.0) / (replications as f64 + 1.0))
}

