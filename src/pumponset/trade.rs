//! Сделка «встать рано» без стратегии (П-34 §7.5): вход по `close_ff` минуты `t_f + 1`, выход по `close_ff` минуты
//! `t_f + H`, фандинг за удержание по реальным ставкам файла. Издержки входа/выхода здесь НЕ вычитаются — их
//! берёт `verdict` из `crate::lob::costs`. Значение после `t_f` на факт срабатывания не влияет: сюда приходит
//! уже найденное срабатывание.
//!
//! Допущения (протокол не называет):
//! 1. Фандинг считается в bps номинала входа: `rate · 1e4` за каждую выплату с минутой в `(t_f + 1, t_f + H]`
//!    (выплата в минуту входа позицию ещё не застаёт; в минуту выхода — застаёт). Лонг платит `rate`, шорт получает
//!    (`sign · rate`): положительное значение — издержка стороны.
//! 2. Нет данных (`Skip::NoData`, в `nret` не входит): цены входа/выхода нет (до первой свечи, за концом ряда),
//!    знак 0, `H = 0` либо у контракта вообще нет ставок фандинга (иначе net без фандинга выглядел бы лучше правды).
//! 3. Покрытие окна фандингом (`Skip::Funding`, в `nret` тоже не входит, но считается отдельно — `run-meta.json`):
//!    файл ставок не покрывает удержание, если его первая ставка позже минуты входа `t_f + 1` (выплаты до неё
//!    неизвестны) либо его последняя ставка раньше `t_f + H − G`, где `G` — наибольший интервал между соседними
//!    ставками ЭТОГО файла (измеряется, не назначается): раньше этого срока одна выплата в окне обязательно была бы,
//!    а в файле её нет. Иначе молчаливый ноль занижал бы фандинг там, где файл просто кончился. Окно удержания
//!    внутри покрытого файла без единой выплаты — ноль, это не «нет данных».
//! 4. **Доходность стороны — простая, не логарифмическая.** Для линейного фьючерса на номинал `N` результат сделки —
//!    `N·(c_out/c_in − 1)` для лонга и `N·(1 − c_out/c_in)` для шорта (= минус простая доходность лонга на той же паре
//!    цен): `gross_bps = sign·(c_out/c_in − 1)·1e4`. Знаковый `ln` завышал шорт на ≈ σ²/2 хода и занижал лонг на ту же
//!    величину (`E[e^x − 1] = E[x] + σ²/2 + …`). Это отклонение от дословного П-34 §7.5 (там `ln`) обосновано и записано
//!    в `docs/findings/pumponset-run-spec-2026-11-05.md`. Метки вперёд («ход ≥ X_D», `control.rs`) идут по `ln`-ходу цены
//!    и этим не затронуты: метка — величина движения, а не результат сделки.

#![allow(
    // индексы ограничены проверенными длинами; бюджет линтов (TK-211) не растим
    clippy::indexing_slicing,
    clippy::cast_possible_truncation,
    clippy::cast_precision_loss
)]

/// Перевод доли в bps (единица измерения, не параметр).
const BPS: f64 = 1.0e4;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Trade {
    /// `sign · (c[t_f + H] / c[t_f + 1] − 1) · 1e4` — простая доходность стороны (допущение 4).
    pub gross_bps: f64,
    /// Фандинг, уплаченный позицией стороны `sign` за удержание, bps номинала (положительное — издержка).
    pub fund_bps: f64,
}

/// Почему сделка не состоялась.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Skip {
    /// Нет цены входа/выхода, знак 0, `H = 0` либо файл фандинга пуст.
    NoData,
    /// Цены есть, но файл фандинга не покрывает окно удержания (допущение 3).
    Funding,
}

/// Ставки фандинга контракта: выплаты `(минута, ставка)` по возрастанию минуты и наибольший интервал между соседними.
#[derive(Debug, Clone, Copy)]
pub struct Funding<'a> {
    rates: &'a [(i64, f64)],
    max_gap: i64,
}

impl<'a> Funding<'a> {
    /// `rates` — по возрастанию минуты (вызывающий сортирует).
    pub fn new(rates: &'a [(i64, f64)]) -> Funding<'a> {
        let max_gap = rates.windows(2).map(|w| w[1].0 - w[0].0).max().unwrap_or(0);
        Funding { rates, max_gap }
    }

    /// Выплаты с минутой в `(after, upto]` по возрастанию минуты — те же границы, что у `round_trip`
    /// (`after = t_f + 1` — выплата в минуту входа позицию не застаёт; `upto` — минута выхода, включительно).
    /// Нужны выходам П-35 (`exits`): выход в произвольную минуту, а не только в `t_f + H`.
    pub fn window(&self, after: i64, upto: i64) -> &'a [(i64, f64)] {
        let lo = self.rates.partition_point(|&(m, _)| m <= after);
        let hi = self.rates.partition_point(|&(m, _)| m <= upto);
        &self.rates[lo..hi.max(lo)]
    }
}

/// Сделка срабатывания: `cf` — `close_ff` (индекс 0 ↔ минута `first_min`), `funding` — выплаты контракта,
/// `t_f` — минута срабатывания, `h` — удержание в минутах, `sign` — сторона (±1).
pub fn round_trip(
    cf: &[f64],
    first_min: i64,
    funding: &Funding,
    t_f: i64,
    h: u32,
    sign: i8,
) -> Result<Trade, Skip> {
    let rates = funding.rates;
    if sign == 0 || h == 0 || rates.is_empty() {
        return Err(Skip::NoData);
    }
    let (m_in, m_out) = (t_f + 1, t_f + i64::from(h));
    let (b, e) = (m_in - first_min, m_out - first_min);
    if b < 0 || e < 0 || e as usize >= cf.len() {
        return Err(Skip::NoData);
    }
    let (c_in, c_out) = (cf[b as usize], cf[e as usize]);
    if !(c_in.is_finite() && c_in > 0.0 && c_out.is_finite() && c_out > 0.0) {
        return Err(Skip::NoData);
    }
    let (first, last) = (rates[0].0, rates[rates.len() - 1].0);
    if first > m_in || last < m_out - funding.max_gap {
        return Err(Skip::Funding);
    }
    let side = f64::from(sign);
    let lo = rates.partition_point(|&(m, _)| m <= m_in);
    let hi = rates.partition_point(|&(m, _)| m <= m_out);
    let mut rate_sum = 0.0;
    for &(_, r) in &rates[lo..hi] {
        rate_sum += r;
    }
    Ok(Trade {
        gross_bps: side * (c_out / c_in - 1.0) * BPS,
        fund_bps: side * rate_sum * BPS,
    })
}
