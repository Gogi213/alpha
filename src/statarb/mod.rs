//! Стат-арбитраж: сверхбыстрое ядро (TK-479, G-021). Бэктест — отдельным тикетом после приёмки ядра.
//!
//! Виды (G-021): пары (две монеты одной биржи), корзины (монета против взвешенной группы),
//! кросс-биржа (одна монета на двух биржах, β = 1, базис), фандинг (перп против спота / перп против
//! перпа другой биржи, выплаты фандинга) — все четыре сводятся к одному ядру `kernel::run_pair`:
//! нога Y против ноги X (одна или `K` компонент с весами), разные только входы и `Params`.
//!
//! Правило пропусков (явное): минута без свечи у ноги — `NaN` в панели, не выдумывается и не
//! заполняется. Такая минута не входит в окно оценки, по ней нет сигнала, ордер ждёт минуты, где
//! открытие есть у всех ног. Каждая из этих ситуаций считается в `kernel::Counters`.
//!
//! Модель: сигнал по закрытию минуты `t`, исполнение по open минуты `t+1`; комиссии по ногам
//! (`lob::costs`), фандинг платит нога-перп, державшаяся строго через момент выплаты.
//! Пороги, окна, сетки не назначаются — это `Params` прогона.

