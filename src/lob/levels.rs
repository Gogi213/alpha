//! Жизнь уровня и шесть признаков его истории (план, §1.1).
//!
//! Уровень **рождается**, когда размер впервые превышает порог `H3`;
//! **умирает**, когда размер падает ниже 20% своего максимума или цена уходит
//! за топ-50. Повторное превышение на той же цене — **новый** уровень, объём
//! через разрыв не переносится.
//!
//! Правила, зафиксированные здесь, потому что план допускает одно прочтение
//! только вместе с ними:
//!
//! - Порог рождения строгий: размер должен быть **больше** `H3`, равенство
//!   не рождает. Порог смерти строгий в другую сторону: мёртв, когда размер
//!   **строго ниже** 20% максимума; ровно 20% — ещё жив (проверяется тестом
//!   на уровне L3: `28 * 5 == 140` не убивает, `27 * 5 < 140` убивает).
//! - Смерть считается целочисленно, `5 * size < max` в 128 битах: граница
//!   проходит по трейту с крейтом, глубже целые (`ARCHITECTURE.md` A1).
//! - Рождение только внутри топ-50: наблюдение вне топ-50 с размером выше
//!   порога уровень не создаёт — такой уровень по определению уже мёртв.
//! - Отсутствие тика в кадре читается как размер ноль: либо уровень снят,
//!   либо цена ушла из отслеживаемого окна — в обоих случаях он мёртв по
//!   правилу «ниже 20%» (максимум всегда положителен, раз рождение строгое).
//! - `repeat_count` считает **все** прошлые рождения на этой цене и стороне
//!   строго внутри скользящего часа, включая рождения прогревных уровней,
//!   которых нет в выборке: они рождались буквально, план спрашивает именно
//!   это. Граница окна строгая: рождение ровно час назад уже не считается.
//! - `repriced` — эвристика, в гейты не входит: в том же кадре, где уровень
//!   умер, на соседней цене (`tick ± 1`) той же стороны родился уровень
//!   сопоставимого размера — размер новорождённого внутри удвоенного
//!   максимума умершего в обе стороны. Печатается как есть.
//! - Монотонность — точная, а не «в основном рос»: пара последовательных
//!   наблюдений с убыванием, случившаяся не позже кадра максимума, гасит
//!   флаг. Убывание после максимума флаг не трогает.
//! - `time_to_max_ms` меряется до **первого** достижения максимума.
//! - Прогрев: рождения раньше `первый_кадр + warmup_ms` отслеживаются (нужны
//!   для `repeat_count`), но в выборку не попадают. Уровень, видимый уже в
//!   первом кадре с размером выше порога, считается рождённым в первом кадре:
//!   более ранней метки у реплея нет. **В режиме `floor` (`H3Mode`) прогрева
//!   нет вовсе** — эмиссия начинается с первого рождения; `warmup_ms`
//!   конфигурации в этом режиме не читается (план D-H3, таск 02).
//! - Порядок выдачи детерминирован: смерти одного кадра идут по возрастанию
//!   `(сторона, тик)`. Один и тот же журнал, прогнанный дважды, даёт
//!   побайтово одинаковый вывод — проверяемое свойство A1/A2 из архитектуры.
//!
//! Классификация исхода (`eaten`/`pulled`/`mixed`, шаг 1.2) — этот модуль:
//! объём трейдов с агрессором против уровня копится в `observe_trade`,
//! на смерти пишется в `traded_lots`, правило 70/20 читает `outcome`.
//! Блочные сделки в объём не входят; сторона агрессора решает, чей уровень
//! трейд ест: бид — продавец, аск — покупатель. Склейка по времени матчинга:
//! у трейда берётся `exch_ms` (время исполнения), у кадра — метка кадра,
//! подачи вне жизни уровня не считаются. Вызывающий подаёт события
//! в неубывающем времени матчинга и уже перевёл цену в тики,
//! а количество — в лоты: здесь только целые, кучи нет.
//!
//! # Касания (таск 35, В-42)
//!
//! Третий тип записи рядом со смертью — **касание** живого уровня
//! (`TouchRecord`): практики торгуют не смерть плотности, а подход цены к
//! ней и отскок (`docs/findings/practitioners-2026-09-13.md`, §1). Правила
//! назначены до данных, числа — только из существующих констант:
//!
//! - Касание **начинается** в кадре, где живой уровень, **живший до кадра**
//!   (`birth_ms < ts_ms`, В-43), **стал лучшей ценой своей стороны** —
//!   наблюдением с индексом 0, не будучи ею на прошлом наблюдении. Кадр
//!   идёт от лучшей цены вглубь — тот же контракт, на котором у вызывающего
//!   стоит `in_top50 = i < 50` (`Book::levels`), второго порядка здесь нет.
//!   Рождение лучшей ценой — **не касание**: «цена дошла» — переход, а не
//!   появление; такой уровень касается при следующем становлении лучшим
//!   после ухода. Кадры одной миллисекунды — один момент: уровень, ставший
//!   лучшим в миллисекунду рождения, читается как родившийся лучшим.
//! - Касание **заканчивается** в кадре, где уровень перестал быть лучшей
//!   ценой (появилась цена лучше), либо смертью уровня — тогда
//!   `ended_by_death`, `end_ms` — кадр смерти. Смерть и уход с лучшей цены
//!   в одном кадре читаются как смерть: конец касания ждёт свипа.
//! - Один уровень касается сколько угодно раз, `touch_index` 0, 1, 2…;
//!   касания уровней прогрева считаются (индекс растёт), но не эмитируются —
//!   тот же режим, что у их смертей.
//! - `frontrun_lots` — сумма лотов той же стороны **строго лучше** уровня по
//!   цене (префикс кадра до индекса уровня) на кадре **за секунду до
//!   касания** (В-45: последний кадр с меткой не позже `start_ms −
//!   HORIZONS_MS[1]`). Точная выборка требовала бы хранить все кадры
//!   секунды; вместо неё — два слота в `Live` (`FrontrunSlot`) шагом
//!   `FRONTRUN_BACK_MS` от первого наблюдения слота: «новый» копит первое и
//!   последнее наблюдение текущей секунды, «старый» — предыдущей. На старте
//!   касания читается старый слот: его последнее наблюдение, если оно не
//!   позже `start_ms − 1 с` (тогда это ровно искомый кадр), иначе первое
//!   (оно не позже `start_ms − 1 с` по построению шага). Значение — с
//!   кадра в 1–2 с до касания (плюс интервал между кадрами), никогда с
//!   кадра позже секунды до касания. Уровень моложе слота (старого нет) —
//!   его первое наблюдение. Почему не последний кадр до касания: там
//!   впереди уровня всегда стоит прежняя лучшая цена — корзина «фронтран 0»
//!   пуста по построению (0 из 44 086 касаний, В-45).
//! - `swept_lots` — та же сумма на **последнем кадре до** касания: сколько
//!   ликвидности впереди уровня смёл последний шаг цены («снял
//!   ликвидность», практики D 07:48). Прежнее значение `frontrun_lots` до
//!   В-45.
//! - `size_max_before` — максимум размера до кадра начала; `size_at_touch` —
//!   размер в кадре начала; `traded_during` — объём против уровня,
//!   накопленный `observe_trade` между началом и концом.
//! - `stack_levels` — сколько уровней той же стороны живы после кадра начала
//!   с размером не ниже `H3` **не дальше `DISTANCE_MAX_BPS` (25 bps, последняя
//!   корзина расстояния) от цены уровня** (В-45; сам коснувшийся уровень
//!   входит, если его размер не ниже `H3`); окно переводится в тики
//!   целочисленно один раз на старте касания (`stack_window_ticks`),
//!   считается по состоянию после свипа этого кадра. Вся сторона топ-50
//!   (до В-45) при заглушке `k = 1.0` вырождалась в «49 из 50».
//! - `round_zeros` — число нулей в конце `price_tick` в десятичной записи,
//!   0/1/2/3+ (`round_zeros`).
//! - Порядок выдачи детерминирован: касания умерших за кадр — в порядке
//!   `(сторона, тик)` вместе с их смертями, затем касания выживших — в
//!   порядке кадра. Горячий путь тот же: состояние касания — несколько целых
//!   в `Live`, ключи с событием касания копятся в предвыделенном буфере,
//!   записи уходят в `&mut Vec<TouchRecord>` вызывающего.

//! # Подход (F1 этапа F, В-73)
//!
//! Четвёртый тип записи — **подход** (`ApproachRecord`): момент, когда цена
//! **другая** сторона подошла к живому уровню на полосу `D` bps, то есть
//! лимитку по практикам ещё можно поставить заранее, до касания. Записей две
//! на «заход» не бывает; правила, как у касаний, фиксированы здесь:
//!
//! - Включается конфигом (`LevelsConfig::approach_bps`, `None` — сигнала нет
//!   вовсе: ни состояния, ни вычислений, байты касаний прежние — гейт F1).
//! - **Взвод** — на кадре стороны уровня: уровень жив (не умирает в этом
//!   кадре), держит порог В-66 на этом кадре (`H3Mode::holds_at_size` — тот
//!   же порог, что у касания), возраст не меньше `approach_min_age_ms`, не
//!   является лучшей ценой своей стороны (цена ещё не дошла) и расстояние от
//!   лучшей цены **другой** стороны до уровня впервые вошло в `D` bps:
//!   `gap_ticks × 10⁴ ≤ D × price_tick` целочисленно (`gap_bps`, тот же
//!   расчёт, что `dist_bps` ёмкости). Чужая лучшая цена — с её последнего
//!   кадра: кадры приходят по одной стороне, и это ближайшая известная цена.
//! - **Снятие** — касанием (уровень стал лучшей ценой; `touch_start_ms`),
//!   смертью уровня (`LevelDeath`) или уходом чужой лучшей цены за
//!   `2 × D` (`PriceLeft`; `D2 = 2·D` — гистерезис, **число замера**: без
//!   него цена на границе полосы взводила бы подход в каждом кадре). Записи
//!   уровней прогрева считаются, но не эмитируются; `approach_index` растёт
//!   как `touch_index`.
//! - Взводиться снова уровень может только после того, как цена ушла за
//!   `2 × D` (снятие касанием такого ухода не даёт) — один взвод на «заход».
//! - Порядок выдачи детерминирован: снятия касанием и уходом цены — в
//!   порядке кадра, затем снятия смертью — в порядке `(сторона, тик)` вместе
//!   со смертью и перед записью оборванного ею касания.
//!
//! Порядок кадров двух сторон вызывающий выбирает сам (`feed_frames`: бид,
//! затем аск) — для полосы это значит, что чужая цена читается с последнего
//! кадра чужой стороны, а своя обновляется этим же кадром. Обе стороны
//! пишутся в `best_tick` трекера.

use std::collections::{BTreeMap, VecDeque};

use crate::book::Side;
use crate::lob::markout::HORIZONS_MS;
use crate::lob::shortlist::DISTANCE_MAX_BPS;

/// Как задан порог `H3` — план D-H3 (таск 02): два режима, какой войдёт в
/// предрегистрацию, решает двухчасовой пилот, не этот код. Явный выбор без
/// умолчания — вызывающий (`commands/lob`) обязан подставить один из двух.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum H3Mode {
    /// Пол в лотах — из `instruments.csv` (пишет отдельный шаг сборки пула),
    /// **без прогрева**: уровень эмитится с первого рождения. Рабочий режим
    /// отладки — держит `levels > 0` на прогонах короче часа.
    Floor { h3_lots: i64 },
    /// Порог — заранее измеренный 99-й перцентиль `size_max` по
    /// времени-взвешенной выборке за скользящий час (измерение — вне этого
    /// модуля, число приходит параметром, как раньше). Прогрев `warmup_ms`
    /// действует как в прежнем определении: рождения раньше него
    /// отслеживаются, но не эмитируются.
    Percentile { h3_lots: i64 },
    /// Абсолютный пол «от N» в деньгах (владелец 2026-09-18, В-61): уровень —
    /// плотность, если его номинал `цена × размер ≥ min_usd`. В лотах порог
    /// зависит от цены: `ceil(min_usd_e9 × 1e9 / (tick × tick_e9 × step_e9))`.
    /// Без прогрева, как `Floor`.
    Notional {
        min_usd_e9: i64,
        tick_e9: i64,
        step_e9: i64,
    },
    /// Относительная сила «×соседи» (roadmap 2026-09-17 §3, знаменатель B;
    /// владелец 2026-09-18, В-61): уровень — плотность, если
    /// `100 × size / mean(size соседей той же стороны в ±window_bps)` не
    /// меньше `pct`. Соседи — остальные уровни кадра в окне; без соседей
    /// сила не определена и уровень не рождается. Числа в сотых: `pct_e2`
    /// — проценты × 100, `window_bps_e2` — bps × 100.
    Strength { pct_e2: i64, window_bps_e2: i64 },
    /// И то и другое (владелец: «сила + от денежного объёма»).
    Both {
        min_usd_e9: i64,
        tick_e9: i64,
        step_e9: i64,
        pct_e2: i64,
        window_bps_e2: i64,
    },
}

impl H3Mode {
    /// Порог рождения в лотах — общий для обоих режимов кусок конфигурации.
    /// Единый порог в лотах — только у режимов с одним числом (`Floor`,
    /// `Percentile`); у `Notional`/`Strength`/`Both` его нет (оси «×H3» в
    /// командах уровней и касаний для них не определены).
    pub fn single_h3_lots(self) -> Option<i64> {
        match self {
            H3Mode::Floor { h3_lots } | H3Mode::Percentile { h3_lots } => Some(h3_lots),
            H3Mode::Notional { .. } | H3Mode::Strength { .. } | H3Mode::Both { .. } => None,
        }
    }

    /// Порог рождения в лотах на цене `tick`: у денежного пола — с округлением
    /// вверх, чтобы `size ≥ порог` означало ровно `номинал ≥ N`.
    fn notional_lots_at(min_usd_e9: i64, tick_e9: i64, step_e9: i64, tick: i64) -> i64 {
        if tick <= 0 {
            return i64::MAX;
        }
        let num = (min_usd_e9 as i128) * 1_000_000_000i128;
        let den = (tick as i128) * (tick_e9 as i128) * (step_e9 as i128);
        let lots = (num + den - 1) / den;
        lots.clamp(1, i64::MAX as i128) as i64
    }

    /// Проходит ли наблюдение абсолютный порог **при рождении**: у пола в
    /// лотах — строго выше (как было), у денежного — не ниже номинала; у
    /// чистой силы абсолютного порога нет (размер положителен).
    fn passes_birth(self, tick: i64, size_lots: i64) -> bool {
        match self {
            H3Mode::Floor { h3_lots } | H3Mode::Percentile { h3_lots } => size_lots > h3_lots,
            H3Mode::Notional {
                min_usd_e9,
                tick_e9,
                step_e9,
            }
            | H3Mode::Both {
                min_usd_e9,
                tick_e9,
                step_e9,
                ..
            } => size_lots >= Self::notional_lots_at(min_usd_e9, tick_e9, step_e9, tick),
            H3Mode::Strength { .. } => size_lots > 0,
        }
    }

    /// То же для «завала» касания (`stack`): у пола в лотах — не ниже (как
    /// было), у денежного — не ниже номинала.
    fn passes_stack(self, tick: i64, size_lots: i64) -> bool {
        match self {
            H3Mode::Floor { h3_lots } | H3Mode::Percentile { h3_lots } => size_lots >= h3_lots,
            other => other.passes_birth(tick, size_lots),
        }
    }

    /// Порог силы `(pct_e2, window_bps_e2)`, если режим его требует.
    fn strength_gate(self) -> Option<(i64, i64)> {
        match self {
            H3Mode::Strength {
                pct_e2,
                window_bps_e2,
            }
            | H3Mode::Both {
                pct_e2,
                window_bps_e2,
                ..
            } => Some((pct_e2, window_bps_e2)),
            H3Mode::Floor { .. } | H3Mode::Percentile { .. } | H3Mode::Notional { .. } => None,
        }
    }

    /// Держится ли порог **в момент касания** (В-66, база E1: «крупная при
    /// подходе цены»): уровень рождается сильным, но к касанию соседи могли
    /// вырасти, а его самого — частично съесть. Номинал — по `size_at_touch`,
    /// сила — по `strength_e2` окна, равного окну порога. `None` — окно
    /// порога не из `STRENGTH_WINDOWS_BPS`, проверить нечем (вызывающий
    /// отказывает, не пропускает молча).
    pub fn holds_at_touch(self, touch: &TouchRecord) -> Option<bool> {
        self.holds_at_size(touch.price_tick, touch.size_at_touch, &touch.strength_e2)
    }

    /// То же правило порога В-66, но по кадру, а не по записи касания: размер
    /// на этом кадре и сила «×соседи» того же кадра — общий порог касания и
    /// сигнала подхода (F1). `None` — окно силы не из `STRENGTH_WINDOWS_BPS`,
    /// проверить порог нечем.
    pub fn holds_at_size(
        self,
        tick: i64,
        size_lots: i64,
        strength_e2: &[i64; STRENGTH_WINDOWS_BPS.len()],
    ) -> Option<bool> {
        if !self.passes_birth(tick, size_lots) {
            return Some(false);
        }
        match self.strength_gate() {
            None => Some(true),
            Some((pct_e2, window_bps_e2)) => {
                let k = STRENGTH_WINDOWS_BPS
                    .iter()
                    .position(|&w| w.saturating_mul(100) == window_bps_e2)?;
                Some(strength_e2[k] >= pct_e2)
            }
        }
    }

    /// Порог обязан быть положителен: нулевой рождал бы уровень из пустого места.
    fn validate(self) {
        match self {
            H3Mode::Floor { h3_lots } | H3Mode::Percentile { h3_lots } => {
                assert!(h3_lots > 0, "порог H3 обязан быть положителен")
            }
            H3Mode::Notional {
                min_usd_e9,
                tick_e9,
                step_e9,
            } => assert!(
                min_usd_e9 > 0 && tick_e9 > 0 && step_e9 > 0,
                "денежный порог, тик и шаг лота обязаны быть положительны"
            ),
            H3Mode::Strength {
                pct_e2,
                window_bps_e2,
            } => assert!(
                pct_e2 > 0 && window_bps_e2 > 0,
                "сила и окно соседей обязаны быть положительны"
            ),
            H3Mode::Both {
                min_usd_e9,
                tick_e9,
                step_e9,
                pct_e2,
                window_bps_e2,
            } => assert!(
                min_usd_e9 > 0 && tick_e9 > 0 && step_e9 > 0 && pct_e2 > 0 && window_bps_e2 > 0,
                "денежный порог, тик, шаг, сила и окно обязаны быть положительны"
            ),
        }
    }
}

