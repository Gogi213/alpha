#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WallStopMode {
    /// `wall` — стоп плана, пока цена не вернётся к новому стопу; тогда перенос.
    Soft,
    /// `wallx` — выход по рынку сразу.
    Hard,
    /// `wallk` — стоп плана до конца сделки, стена больше не учитывается.
    Keep,
}

impl TradePlan {
    /// Время жизни неисполненного входа у этого плана.
    pub(super) fn entry_ttl_ns(&self) -> i64 {
        match *self {
            TradePlan::SpreadHold => ENTRY_TTL_NS,
            TradePlan::Bounce { entry_ttl_ns, .. } => entry_ttl_ns,
        }
    }

    /// Сколько после сигнала круг этого плана длится до выхода, без подтверждений: срок входа + дедлайн
    /// (горизонт). Р6: начальный горизонт развёртки событий круга в `bounce-grid`; точность от него не
    /// зависит — короткий горизонт ловит проверка и пересчитывает круг.
    pub fn round_span_ns(&self) -> i64 {
        match *self {
            TradePlan::SpreadHold => ENTRY_TTL_NS.saturating_add(HOLD_NS),
            TradePlan::Bounce {
                entry_ttl_ns,
                deadline_ns,
                ..
            } => entry_ttl_ns.saturating_add(deadline_ns),
        }
    }
}

/// Почему отправлен выход. У Decision 20 причина одна — горизонт; у
/// сделки-отскока их три (тейк, стоп, дедлайн), и бэктест считает их
/// отдельно, потому что «сколько раз выбило стопом» — это и есть вопрос
/// практиков о винрейте.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ExitReason {
    /// Выход ровно на горизонте `HOLD_NS` (Decision 20).
    Horizon,
    /// Тейк-лимит сработал.
    Take,
    /// Стоп: сделка прошла по `stop_px`, выходим по рынку.
    Stop,
    /// Дедлайн плана истёк — выход по рынку.
    Deadline,
    /// Трейл-тейк: цена откатилась от лучшего исхода на `trail_bps`, выходим
    /// по рынку (решение владельца 2026-09-13 — тянуть прибыль дальше 1:1).
    Trail,
    /// Досрочный выход по «прилипанию» (B4, В-58 п. 5): через `early_exit_ns`
    /// после входа уровень **всё ещё лучшая цена** — касание не разрешилось ни
    /// в отскок, ни в пробой, и сделка стоит в нём, платя за неопределённость.
    /// Выход по рынку (тейкер). Причина считается отдельно от `deadline`:
    /// дедлайн — конец плана, «прилипание» — свойство касания.
    Early,
    /// Плотность съедена (E5/E7): остаток на уровне упал ниже порога от
    /// максимума с входа — выход по рынку. Первый порог закрывает часть
    /// (`partial: true` в `Action`), второй — всё.
    Eaten,
    /// F7 (Б-75): стена съедена сделками — накопленные сделки в стену с
    /// момента входа ≥ X % от размера стены на входе. Выход по рынку всего
    /// остатка.
    EatenByTrades,
    /// F7 (Б-75): стена снята без сделок — размер упал ниже (1 − W %) от
    /// размера на входе, И съедение сделками < половины падения. Выход по
    /// рынку всего остатка.
    WallGone,
    /// TK-014 `weat*`: стену съели сделками после входа, BTC за окно ≤ −Y bps («рынок»).
    WallEatBtc,
    /// TK-014 `weat*`: стену съели сделками после входа, BTC за окно > −Y bps («местный»).
    WallEatLocal,
    /// Г-119: цена уходила от стены на `A` bps и вернулась к ней — выход по рынку.
    Converge,
    /// Г-112: лента против позиции за окно с входа ≥ порога (нормирована на размер стены), позиция в минусе.
    Tape,
    /// Г-116: отмены на нашей стороне за окно с входа ≥ порога (нормированы на размер стены), позиция в минусе.
    Resilience,
}
