/// Почему отправлен выход. У Decision 20 причина одна — горизонт; у
/// сделки-отскока их три (тейк, стоп, дедлайн), и бэктест считает их
/// отдельно, потому что «сколько раз выбило стопом» — это и есть вопрос
/// практиков о винрейте.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ExitReason {
    /// Выход ровно на горизонте `HOLD_NS` (Decision 20).
    Horizon,
    /// Тейк-лимит сработал.
    Take,
    /// Стоп: сделка прошла по `stop_px`, выходим по рынку.
    Stop,
    /// Дедлайн плана истёк — выход по рынку.
    Deadline,
    /// Трейл-тейк: цена откатилась от лучшего исхода на `trail_bps`, выходим
    /// по рынку (решение владельца 2026-09-13 — тянуть прибыль дальше 1:1).
    Trail,
    /// Досрочный выход по «прилипанию» (B4, В-58 п. 5): через `early_exit_ns`
    /// после входа уровень **всё ещё лучшая цена** — касание не разрешилось ни
    /// в отскок, ни в пробой, и сделка стоит в нём, платя за неопределённость.
    /// Выход по рынку (тейкер). Причина считается отдельно от `deadline`:
    /// дедлайн — конец плана, «прилипание» — свойство касания.
    Early,
    /// Плотность съедена (E5/E7): остаток на уровне упал ниже порога от
    /// максимума с входа — выход по рынку. Первый порог закрывает часть
    /// (`partial: true` в `Action`), второй — всё.
    Eaten,
    /// F7 (Б-75): стена съедена сделками — накопленные сделки в стену с
    /// момента входа ≥ X % от размера стены на входе. Выход по рынку всего
    /// остатка.
    EatenByTrades,
    /// F7 (Б-75): стена снята без сделок — размер упал ниже (1 − W %) от
    /// размера на входе, И съедение сделками < половины падения. Выход по
    /// рынку всего остатка.
    WallGone,
}

/// Состояние одного круга одной стратегии на одном активе. `sigma` — сторона
/// этого круга (`SIGMA_LONG`/`SIGMA_SHORT`, `backtest::entry_side`),
/// назначается снаружи один раз при вооружении: какой именно сигнал
/// ловить — решение уровня `lob/levels`, не этого модуля (границы модулей,
/// `interfaces.md`). `plan` — чем этот круг торгует (см. `TradePlan`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct StrategyState {
    asset_no: usize,
    sigma: i8,
    qty: f64,
    next_order_id: u64,
    phase: Phase,
    plan: TradePlan,
    /// Лучшая цена «в пользу позиции» с момента входа (для трейл-тейка): у
    /// лонга — максимум лучшего бида, у шорта — минимум лучшего аска.
    /// `0.0` — вход ещё не состоялся.
    best_favourable: f64,
    /// Лучшая цена «в пользу позиции» **с момента снятия стены** — база трейла после снятия
    /// (`gone_trail_bps`). `0.0` — снятия ещё не было (трейл не взведён).
    gone_peak: f64,
    /// Безубыток после снятия (`gone_be`): снятие уже было (защёлка) и стоп уже в безубытке.
    gone_seen: bool,
    be_active: bool,
    /// E7: частичный выход уже был в этом круге (второй раз не делится).
    partial_done: bool,
    /// Максимум размера плотности уровня с момента входа — база съедания
    /// «от максимума» (динамический режим чужих ботов). `0.0` — не считаем.
    level_qty_max: f64,
    /// F7 (Б-75): размер плотности уровня в момент входа — база для `gone<W>`.
    level_qty_at_entry: f64,
    /// F7 (Б-75): накопленные сделки в стену (против нашей позиции) с момента
    /// входа — база для `eat<X>`.
    eaten_qty: f64,
    /// Накопленное исполнение входа и его стоимость — по ордерам крейта
    /// (`entry_snapshot`): средняя цена входа `entry_notional / entry_qty` и
    /// она же — база стопа и тейка (F4, В-78). Живут в состоянии, а не в
    /// `bot.position`: крейт обновляет позицию только на `Filled`.
    entry_qty: f64,
    entry_notional: f64,
    /// Накопленное исполнение выходов этого круга (F4, В-78): размер выхода —
    /// своя позиция `entry_qty − exit_qty`, а не плановый размер круга.
    exit_qty: f64,
    /// Исполнение текущей заявки выхода, уже зачтённое в `exit_qty` (у заявки
    /// оно накапливается от отклика к отклику, а в позицию обязан войти
    /// прирост, а не вся сумма заново).
    exit_accounted: f64,
    /// F8b (В5/Р2): сколько раз потолок `CANCEL_WAIT_NS` сорвал ожидание
    /// подтверждения отмены **лимитки выхода** — круг пошёл по плану, не
    /// дожидаясь биржи. Счётчик назван в артефактах (`n_exit_cancel_timeout`):
    /// предохранитель, который никто не видит, — это молчаливая потеря.
    exit_cancel_timeouts: u64,
    /// F8c (К1): «сироты» — заявки, чьё снятие не подтвердилось за потолок
    /// `CANCEL_WAIT_NS`. Круг они не держат (потолок его освободил), но из
    /// рынка их никто не убрал: пока сирота стоит, снятие повторяется на
    /// каждом событии в любой фазе (`sweep_orphans`), а исполнение сироты не
    /// теряется — нога входа гасится по рынку, нога выхода зачитывается в
    /// `exit_qty`. Партии — массив фиксированной ёмкости (`OrphanCarry`, без
    /// кучи): вторая партия до ухода первой (лимитка выхода дважды не
    /// отменилась за потолок) не затирает первую (ревью 22.09, блокер 2);
    /// переполнение ёмкости считается (`orphan_overflow`), тогда вытесняется
    /// старейшая. Партии **переживают круг**: драйвер забирает их
    /// (`take_orphans`) и отдаёт следующему состоянию (`inherit_orphans`),
    /// иначе сирота входа, чей круг закрылся тем же событием, не снималась бы
    /// ни разу (ревью 22.09, блокер 1).
    orphans: OrphanCarry,
    /// Остаток стоящих сирот **выхода** (по последней уборке): новые выходы
    /// сайзятся по свободной позиции `position − orphan_exit_open`, иначе
    /// исполнятся обе заявки и позиция уйдёт в перепрод (ревью 22.09, п. 4).
    orphan_exit_open: f64,
    /// Сколько раз исполнение сироты было замечено — колонка `n_orphan_fills`.
    orphan_fills: u64,
    /// Сколько раз новая партия сирот вытеснила живую из-за переполнения.
    orphan_overflow: u64,
}

/// Чьи ноги стали сиротами (F8c, К1): исполнение ноги **входа** — лишняя
/// позиция, её гасят по рынку; исполнение ноги **выхода** — наш же выход, его
/// зачитывают в `exit_qty`, а не откупают обратно.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum OrphanKind {
    Entry,
    Exit,
}

/// Одна партия сирот: ноги `first .. first + legs` одной заявки/лестницы.
#[derive(Debug, Clone, Copy, PartialEq)]
struct OrphanBatch {
    first: u64,
    legs: u8,
    kind: OrphanKind,
    /// Исполненное партии, уже учтённое (погашено или зачтено в выход).
    accounted: f64,
}

/// Ёмкость партий сирот на состояние: вход + выход + запас; больше — считается
/// переполнением (`orphan_overflow`), не молчаливой потерей.
pub const MAX_ORPHAN_BATCHES: usize = 4;

/// Сироты, переносимые между кругами (F8c): драйвер бэктеста создаёт состояние
/// на сигнал и рвёт круг на `Idle`, поэтому партии отдаются наружу и
/// наследуются следующим состоянием; живой контур с долгоживущей стратегией
/// держит их внутри. `Copy` и без кучи — на пути события.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct OrphanCarry {
    batches: [OrphanBatch; MAX_ORPHAN_BATCHES],
    n: u8,
}

impl OrphanCarry {
    pub const NONE: OrphanCarry = OrphanCarry {
        batches: [OrphanBatch {
            first: 0,
            legs: 0,
            kind: OrphanKind::Entry,
            accounted: 0.0,
        }; MAX_ORPHAN_BATCHES],
        n: 0,
    };

    pub fn is_empty(&self) -> bool {
        self.n == 0
    }

    /// Живых партий.
    pub fn len(&self) -> usize {
        usize::from(self.n)
    }

    /// Те же партии в нумерации другого прогона: номера заявок сдвинуты с базы `from` на базу
    /// `to` (память кругов сетки, G10: круг, взятый из памяти другого набора, отдаёт сирот в
    /// нумерации своего прогона — иначе номер сироты мог бы совпасть с заявкой следующего круга).
    pub fn rebased(mut self, from: u64, to: u64) -> OrphanCarry {
        for b in self.batches.iter_mut().take(usize::from(self.n)) {
            b.first = b.first.wrapping_sub(from).wrapping_add(to);
        }
        self
    }
}

impl StrategyState {
    /// Круг Decision 20: вход у спреда, выход на горизонте.
    pub fn new(asset_no: usize, sigma: i8, qty: f64, first_order_id: u64) -> Self {
        Self::with_plan(asset_no, sigma, qty, first_order_id, TradePlan::SpreadHold)
    }

    /// Круг с планом: цены и сроки сделки приходят снаружи (В-44).
    pub fn with_plan(
        asset_no: usize,
        sigma: i8,
        qty: f64,
        first_order_id: u64,
        plan: TradePlan,
    ) -> Self {
        Self {
            asset_no,
            sigma,
            qty,
            next_order_id: first_order_id,
            phase: Phase::Idle,
            plan,
            best_favourable: 0.0,
            gone_peak: 0.0,
            gone_seen: false,
            be_active: false,
            partial_done: false,
            level_qty_max: 0.0,
            level_qty_at_entry: 0.0,
            eaten_qty: 0.0,
            entry_qty: 0.0,
            entry_notional: 0.0,
            exit_qty: 0.0,
            exit_accounted: 0.0,
            exit_cancel_timeouts: 0,
            orphans: OrphanCarry::NONE,
            orphan_exit_open: 0.0,
            orphan_fills: 0,
            orphan_overflow: 0,
        }
    }

    /// F8b (В5/Р2): сколько раз круг пережил потолок ожидания подтверждения
    /// отмены лимитки выхода — читает драйвер для колонки `forms.csv`.
    pub fn exit_cancel_timeouts(&self) -> u64 {
        self.exit_cancel_timeouts
    }

    /// F8c (К1): сколько раз исполнилась заявка-сирота (после потолка
    /// отмены) — колонка `n_orphan_fills`; ноль — норма.
    pub fn orphan_fills(&self) -> u64 {
        self.orphan_fills
    }

    /// F8c (К1): сколько раз новая партия сирот вытеснила живую прежнюю.
    pub fn orphan_overflow(&self) -> u64 {
        self.orphan_overflow
    }

    /// Сироты ещё стоят в рынке (или их снятие летит).
    pub fn has_orphans(&self) -> bool {
        !self.orphans.is_empty()
    }

    /// Забрать партии сирот у состояния (драйвер — на границе круга): у
    /// состояния их больше нет, у следующего состояния будут (`inherit_orphans`).
    pub fn take_orphans(&mut self) -> OrphanCarry {
        let c = self.orphans;
        self.orphans = OrphanCarry::NONE;
        self.orphan_exit_open = 0.0;
        c
    }

    /// Унаследовать партии сирот прежнего круга (F8c): уборка продолжится с
    /// первого события нового круга. Своих партий у нового состояния ещё нет.
    pub fn inherit_orphans(&mut self, carry: OrphanCarry) {
        self.orphans = carry;
    }

    /// Потолок отмены сорвал ожидание: ноги `first .. first + legs` — новая
    /// партия сирот (F8c, К1). Ёмкость исчерпана — вытесняется старейшая,
    /// переполнение считается.
    fn adopt_orphans(&mut self, first: u64, legs: u8, kind: OrphanKind) {
        let b = OrphanBatch {
            first,
            legs: legs.max(1),
            kind,
            accounted: 0.0,
        };
        let n = self.orphans.len();
        if n < MAX_ORPHAN_BATCHES {
            self.orphans.batches[n] = b;
            self.orphans.n += 1;
        } else {
            self.orphan_overflow = self.orphan_overflow.saturating_add(1);
            self.orphans.batches.copy_within(1.., 0);
            self.orphans.batches[MAX_ORPHAN_BATCHES - 1] = b;
        }
    }

    /// Свободная позиция под новый выход: своя позиция минус остаток стоящих
    /// сирот выхода (они ещё могут исполниться).
    fn free_position(&self) -> f64 {
        (self.position() - self.orphan_exit_open).max(0.0)
    }

    /// F8c (К1): на каждом событии, в любой фазе — сироты снимаются снова,
    /// пока стоят, а их исполнение учитывается: нога входа гасится по рынку
    /// (IOC по лучшей цене другой стороны), нога выхода зачитывается в
    /// `exit_qty`. Партия отпускается, когда ни одна нога не стоит и не
    /// снимается. Без сирот — ноль работы.
    fn sweep_orphans<MD, B>(&mut self, bot: &mut B) -> Result<(), B::Error>
    where
        MD: MarketDepth,
        B: Bot<MD>,
    {
        if self.orphans.is_empty() {
            return Ok(());
        }
        let mut exit_open = 0.0_f64;
        let mut k = 0usize;
        while k < self.orphans.len() {
            let mut b = self.orphans.batches[k];
            let mut alive = false;
            let mut executed = 0.0_f64;
            let mut side = HbtSide::None;
            for i in 0..u64::from(b.legs) {
                let id = b.first.saturating_add(i);
                // Снимок полей заявки — до `bot.cancel` (заём карты крейта).
                let Some((exec, o_side, cancellable, in_flight, leaves)) =
                    bot.orders(self.asset_no).get(&id).map(|o| {
                        (
                            executed_qty(o),
                            o.side,
                            o.cancellable(),
                            o.req != Status::None || o.status == Status::None,
                            o.leaves_qty.max(0.0),
                        )
                    })
                else {
                    continue;
                };
                executed += exec;
                side = o_side;
                if cancellable {
                    bot.cancel(self.asset_no, id, false)?;
                }
                if cancellable || in_flight {
                    alive = true;
                    if b.kind == OrphanKind::Exit {
                        exit_open += leaves;
                    }
                }
            }
            let delta = executed - b.accounted;
            if delta > 0.0 {
                match b.kind {
                    OrphanKind::Exit => {
                        self.exit_qty += delta;
                        b.accounted = executed;
                        self.orphan_fills = self.orphan_fills.saturating_add(1);
                        // Сирота закрыла позицию целиком, пока план её вёл:
                        // выхода ставить не на что (`Holding` нулевой позиции
                        // отправил бы заявку на ноль).
                        if self.position() <= 0.0 && matches!(self.phase, Phase::Holding { .. }) {
                            self.phase = Phase::Idle;
                        }
                    }
                    OrphanKind::Entry => {
                        let depth = bot.depth(self.asset_no);
                        let (bid, ask) = (depth.best_bid(), depth.best_ask());
                        let flat_side = match side {
                            HbtSide::Buy => HbtSide::Sell,
                            HbtSide::Sell => HbtSide::Buy,
                            HbtSide::None | HbtSide::Unsupported => HbtSide::None,
                        };
                        // Цена гашения — как у выхода из позиции той же стороны
                        // (`exit_price` берёт сторону **позиции**: лонг гасится по
                        // биду). Нет книги или стороны — гасить нечем, повтор на
                        // следующем событии (`accounted` не двигается).
                        if let Some(px) = exit_price(side, bid, ask) {
                            let id = self.take_order_id();
                            match flat_side {
                                HbtSide::Buy => bot.submit_buy_order(
                                    self.asset_no,
                                    id,
                                    px,
                                    delta,
                                    TimeInForce::IOC,
                                    OrdType::Market,
                                    false,
                                )?,
                                _ => bot.submit_sell_order(
                                    self.asset_no,
                                    id,
                                    px,
                                    delta,
                                    TimeInForce::IOC,
                                    OrdType::Market,
                                    false,
                                )?,
                            };
                            b.accounted = executed;
                            self.orphan_fills = self.orphan_fills.saturating_add(1);
                        }
                    }
                }
            }
            if alive {
                self.orphans.batches[k] = b;
                k += 1;
            } else {
                // Партия отпущена: сдвиг хвоста, ёмкость фиксированная.
                let n = self.orphans.len();
                self.orphans.batches.copy_within(k + 1..n, k);
                self.orphans.n -= 1;
            }
        }
        self.orphan_exit_open = exit_open;
        Ok(())
    }

    /// Своя позиция круга: исполненный вход минус исполненные выходы (F4,
    /// В-78). Именно она — размер выхода и признак открытой позиции:
    /// `bot.position` крейта частичного исполнения не видит (находка F3),
    /// поэтому на нём решения о круге стоять не могут.
    pub fn position(&self) -> f64 {
        (self.entry_qty - self.exit_qty).max(0.0)
    }

    /// Средняя цена исполненного входа (`None` — исполнения не было).
    fn entry_vwap(&self) -> Option<f64> {
        if self.entry_qty > 0.0 {
            Some(self.entry_notional / self.entry_qty)
        } else {
            None
        }
    }

    /// Зачитать исполнение ног входа в состояние (`first_id .. first_id+legs`) —
    /// накопленный объём и стоимость исполненного. Возвращает снимок: по
    /// `open` решается, жив ли ещё вход. После входа числа заморожены — ордера
    /// остаются в учёте крейта с теми же значениями, а состояние хранит
    /// последние.
    fn observe_entry<MD, B>(&mut self, bot: &B, first_id: u64, legs: u8) -> EntrySnapshot
    where
        MD: MarketDepth,
        B: Bot<MD>,
    {
        let snap = entry_snapshot(bot, self.asset_no, first_id, legs);
        self.entry_qty = snap.qty;
        self.entry_notional = snap.notional;
        snap
    }

    /// Зачитать исполнение заявки выхода: в позицию входит **прирост** её
    /// исполненного (`exec_qty` крейта — объём последнего исполнения, у
    /// накопленного — `qty − leaves_qty`).
    fn observe_exit<MD, B>(&mut self, bot: &B, order_id: u64)
    where
        MD: MarketDepth,
        B: Bot<MD>,
    {
        let executed = bot
            .orders(self.asset_no)
            .get(&order_id)
            .map_or(0.0, executed_qty);
        if executed > self.exit_accounted {
            self.exit_qty += executed - self.exit_accounted;
            self.exit_accounted = executed;
        }
    }

    /// Позиция открыта — круг начинается: сброс частичного выхода, база
    /// съедания — размер плотности на сигнале.
    fn enter_holding(&mut self, now: i64) {
        self.partial_done = false;
        self.eaten_qty = 0.0;
        let (level_qty, level_qty_max) = match self.plan {
            TradePlan::Bounce { level_qty, .. } => (level_qty.max(0.0), level_qty.max(0.0)),
            TradePlan::SpreadHold => (0.0, 0.0),
        };
        self.level_qty_at_entry = level_qty;
        self.level_qty_max = level_qty_max;
        self.phase = Phase::Holding { entry_ns: now };
    }

    /// F7 (Б-75): зачесть сделки этого шага, бьющие **в стену**. Вызывается
    /// драйвером (`run_round`) **до** очистки буфера `bot.last_trades` — сам
    /// буфер живёт под управлением драйвера (он чистит его на каждом шаге,
    /// чтобы память не росла с длиной круга), поэтому сделки приходят сюда
    /// снаружи, а правило «что считать ударом в стену» остаётся здесь.
    ///
    /// У бид-стены (лонг) в неё бьёт агрессор-продавец (`SELL_EVENT`), у
    /// аск-стены (шорт) — агрессор-покупатель (`BUY_EVENT`); учитывается
    /// только сделка **на нашей цене уровня** (целый тик). При выключенных
    /// формах F7 (`exit_eat_pct`/`exit_gone_pct` = 0) счётчик не читается
    /// никем — прохода по буферу нет, и числа прежних прогонов не меняются
    /// (на этом стоит гейт «те же круги»).
    pub fn observe_wall_trades(&mut self, trades: &[Event]) {
        let TradePlan::Bounce {
            level_px,
            tick_px,
            exit_eat_pct,
            exit_gone_pct,
            ..
        } = self.plan
        else {
            return;
        };
        // `gone<W>` тоже читает накопленное (сравнение с половиной падения),
        // поэтому счётчик ведётся при любой из двух форм.
        if exit_eat_pct <= 0.0 && exit_gone_pct <= 0.0 {
            return;
        }
        if tick_px <= 0.0 || level_px <= 0.0 {
            return;
        }
        let Some(entry_side) = entry_side(self.sigma) else {
            return;
        };
        // У лонга стену едят продажи, у шорта — покупки.
        let want_sell = entry_side == HbtSide::Buy;
        #[allow(clippy::cast_possible_truncation)]
        let level_tick = (level_px / tick_px).round() as i64;
        let mut eaten = 0.0;
        for trade in trades {
            let hit = if want_sell {
                trade.ev & EXCH_SELL_TRADE_EVENT != 0
            } else {
                trade.ev & EXCH_BUY_TRADE_EVENT != 0
            };
            if !hit {
                continue;
            }
            #[allow(clippy::cast_possible_truncation)]
            if (trade.px / tick_px).round() as i64 == level_tick {
                eaten += trade.qty;
            }
        }
        self.eaten_qty += eaten;
    }

    /// Лучший исход с момента входа — для трейл-тейка: вызывается на каждом
    /// событии, пока позиция открыта. Цена «в пользу» — та, по которой
    /// закрылись бы сейчас (лучший бид для лонга, лучший аск для шорта).
    fn observe_favourable(&mut self, price: f64) {
        if price <= 0.0 {
            return;
        }
        // Сравнение в `if`, а не образцом по константе: `SIGMA_LONG` в позиции
        // образца стал бы новым связыванием, а не сравнением (clippy:
        // unreachable pattern, «переменная должна быть snake_case»).
        let better = if self.sigma == crate::lob::backtest::SIGMA_LONG {
            self.best_favourable == 0.0 || price > self.best_favourable
        } else {
            self.best_favourable == 0.0 || price < self.best_favourable
        };
        if better {
            self.best_favourable = price;
        }
    }

    /// Лучший исход с момента снятия стены — для трейла после снятия: первый вызов взводит
    /// трейл ценой снятия, дальше вызывается на каждом событии, пока позиция открыта.
    fn observe_gone_peak(&mut self, price: f64) {
        if price <= 0.0 {
            return;
        }
        let better = if self.sigma == crate::lob::backtest::SIGMA_LONG {
            self.gone_peak == 0.0 || price > self.gone_peak
        } else {
            self.gone_peak == 0.0 || price < self.gone_peak
        };
        if better {
            self.gone_peak = price;
        }
    }

    pub fn is_idle(&self) -> bool {
        matches!(self.phase, Phase::Idle)
    }

    /// Размер круга: драйверу он нужен для `Fill`, сам драйвер его не хранит.
    pub fn qty(&self) -> f64 {
        self.qty
    }

    fn take_order_id(&mut self) -> u64 {
        let id = self.next_order_id;
        self.next_order_id = self.next_order_id.saturating_add(1);
        id
    }

    /// Снимает живые ноги лестницы: исполненные и уже снятые трогать нельзя —
    /// `cancel` по ним возвращает `OrderNotFound`/`InvalidOrderStatus`, а не
    /// «ничего не произошло». Повторный вызов безопасен: нога с запросом в
    /// полёте пропускается (`cancel_open`), иначе крейт отвечает
    /// `OrderRequestInProcess` — это и позволяет звать снятие на каждом шаге
    /// фазы `CancelPending` (F8b), пока нога не стала `New`/`PartiallyFilled`.
    fn cancel_resting<MD, B>(&self, bot: &mut B, first_id: u64, legs: u8) -> Result<(), B::Error>
    where
        MD: MarketDepth,
        B: Bot<MD>,
    {
        for i in 0..legs as u64 {
            self.cancel_open(bot, first_id.saturating_add(i))?;
        }
        Ok(())
    }

    /// Снять заявку, если она стоит в рынке и **не снимается прямо сейчас**:
    /// `New`/`PartiallyFilled` без запроса в полёте (`req == None`). Нога, чей
    /// запрос постановки летел в момент снятия входа, остаётся живой — её
    /// снимает следующий вызов; без него фаза ждала бы её вечно (F8b, В5/Р2).
    fn cancel_open<MD, B>(&self, bot: &mut B, id: u64) -> Result<(), B::Error>
    where
        MD: MarketDepth,
        B: Bot<MD>,
    {
        // Крейт: `New`/`PartiallyFilled` без запроса в полёте (`req == None`).
        if bot
            .orders(self.asset_no)
            .get(&id)
            .is_some_and(|o| o.cancellable())
        {
            bot.cancel(self.asset_no, id, false)?;
        }
        Ok(())
    }

    /// Условия снятия неисполненного входа **до потолка** (F5, В-74):
    ///
    /// * «стена умерла» — размер на цене уровня (`level_px`) в текущем кадре
    ///   книги упал ниже порога В-66 (`level_floor_qty`, в единицах крейта);
    /// * «цена ушла из полосы» — лучшая цена нашей стороны дальше дальней
    ///   ноги лестницы больше чем на `band_exit_bps`.
    ///
    /// `None` — вход продолжает стоять: либо условий нет в плане (прежний
    /// режим `--entry-ttl-secs touch`, у него оба поля нули), либо книга ещё
    /// неполна. Размер уровня берётся **по целому тику** — тем же приёмом,
    /// что съедание E7 (`bid_qty_at_tick`/`ask_qty_at_tick`): цена уровня
    /// переводится в тик, сравнение идёт по размеру, а не по `f64`-цене.
    fn entry_cancel_reason<MD, B>(&self, bot: &B) -> Option<EntryCancelReason>
    where
        MD: MarketDepth,
        B: Bot<MD>,
    {
        let TradePlan::Bounce {
            entry_px,
            level_px,
            tick_px,
            level_floor_qty,
            band_exit_bps,
            grid_legs,
            grid_step_px,
            ladder,
            ..
        } = self.plan
        else {
            return None;
        };
        if level_floor_qty <= 0.0 && band_exit_bps <= 0.0 {
            return None;
        }
        let entry_side = entry_side(self.sigma)?;
        let depth = bot.depth(self.asset_no);
        // Стена: размер на цене уровня в текущем кадре. Сторона уровня — та же,
        // что у входа (у лонга бид-стена, у шорта аск-стена).
        if level_floor_qty > 0.0 && tick_px > 0.0 && level_px > 0.0 {
            #[allow(clippy::cast_possible_truncation)]
            let level_tick = (level_px / tick_px).round() as i64;
            let now_qty = match entry_side {
                HbtSide::Buy => depth.bid_qty_at_tick(level_tick),
                _ => depth.ask_qty_at_tick(level_tick),
            };
            if now_qty < level_floor_qty {
                return Some(EntryCancelReason::WallDead);
            }
        }
        // Полоса: дальняя нога — последняя в построении входа (`px ± step × i`,
        // `Idle` ниже), расстояние до неё меряем в bps и берём по модулю
        // направления (`away`): у лонга цена уходит вверх, у шорта — вниз.
        if band_exit_bps > 0.0 && entry_px > 0.0 {
            let (bid, ask) = (depth.best_bid(), depth.best_ask());
            if bid.is_finite() && ask.is_finite() && bid > 0.0 && ask > 0.0 {
                let away = if entry_side == HbtSide::Buy {
                    1.0
                } else {
                    -1.0
                };
                let outer = match ladder.outer_tick() {
                    // Лестница формы F6: дальняя нога — последняя в наборе.
                    #[allow(clippy::cast_precision_loss)]
                    Some(t) => t as f64 * tick_px,
                    None => entry_px + away * grid_step_px * f64::from(grid_legs.max(1) - 1),
                };
                let own = if entry_side == HbtSide::Buy { bid } else { ask };
                if outer > 0.0 && (own - outer) * away / outer * 10_000.0 > band_exit_bps {
                    return Some(EntryCancelReason::PriceLeft);
                }
            }
        }
        None
    }
}

/// Почему неисполненный вход кончился без позиции (F5, В-74). Причина
/// считается отдельно (`forms.csv`, `n_entry_cancelled_*`): «стена снята» и
/// «цена ушла» — события рынка и повод снять вход, потолок — страховка, а
/// непоставленная биржа заявка (пост-онли, В-72) — «сигнал без входа».
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EntryCancelReason {
    /// Потолок `entry_ttl_ns`: вход простоял свой срок и снят (F5, В-74).
    Ttl,
    /// Стена снята: размер на `level_px` упал ниже порога В-66
    /// (`level_floor_qty`) — практики снимают по событию, не таймером.
    WallDead,
    /// Цена ушла из полосы: лучшая цена нашей стороны дальше дальней ноги
    /// лестницы больше чем на `band_exit_bps`.
    PriceLeft,
    /// Ни одной ноги биржа не поставила (пост-онли заявка пересекла спред,
    /// В-72) — «сигнал без входа», а не снятие: в счётчики снятий не входит.
    NotPlaced,
    /// Подтверждение отмены входа не пришло за `CANCEL_WAIT_NS` (F8b, В5/Р2):
    /// вход снимался, но биржа не ответила — круг освобождается, а не висит
    /// «занятым» до конца записи. Заявка могла остаться в рынке: это цена
    /// предохранителя, и она названа, а не спрятана.
    CancelTimeout,
}

/// Что сделал последний вызов `on_event`. `Idle` — ничего не произошло на
/// этом событии (ждём книгу, ждём таймаут, ждём исполнения) — самый частый
/// исход на живом потоке, где событий много, а решений мало.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Action {
    Idle,
    EntrySubmitted {
        order_id: u64,
        side: HbtSide,
        price: f64,
    },
    /// Вход кончился без позиции: не исполнился и снят по условию F5 (стена
    /// снята / цена ушла из полосы) или по потолку срока жизни —
    /// либо биржа не поставила ни одной ноги (пост-онли заявка пересекла
    /// спред, В-72). Круг освобождается: у такого сигнала входа не было, и
    /// «занято» он не занимает.
    EntryTimedOut {
        order_id: u64,
        /// Почему вход кончился без позиции (F5, В-74).
        reason: EntryCancelReason,
    },
    ExitSubmitted {
        order_id: u64,
        side: HbtSide,
        price: f64,
        reason: ExitReason,
        /// E7: ушла часть позиции, круг продолжается остатком.
        partial: bool,
    },
}

/// Решение о выходе из позиции: цена, тип (тейкер — по рынку, мейкер —
/// лимитом), причина и доля позиции (E7). `None` — выходить не пора или
/// книги нет (тогда круг остаётся в своей фазе к следующему событию, а не
/// теряется молча).
#[derive(Debug, Clone, Copy, PartialEq)]
struct ExitDecision {
    px: f64,
    taker: bool,
    reason: ExitReason,
    frac: f64,
}

/// Что решает выход: у плана Decision 20 — только горизонт; у сделки-отскока
/// (В-44) — стоп, съедание, трейл, тейк, дедлайн, и **порядок здесь часть
/// плана**: стоп приоритетнее тейка (если цена проскочила оба уровня за
/// один кадр, честнее считать, что выбило стопом), съедание всей плотности —
/// раньше трейла, трейл — раньше тейка, половинное съедание — после тейка,
/// прилипание и дедлайн — последними. Вынесено из `on_event` (аудит 21.09,
/// С2), чтобы порядок приоритетов был одной функцией и проверялся отдельно.
///
/// `maker_allowed = false` — лимитка выхода **уже стоит** в рынке
/// (`ExitPending`, аудит 21.09 Б1): мейкерские причины (тейк 1:1, горизонт
/// Decision 20) не рассматриваются — вторая лимитка на тот же остаток не
/// нужна, — а рыночные (стоп, съедание, трейл, прилипание, дедлайн) решают,
/// снимать ли её и добивать остаток тейкером.
/// Лучшие цены и сторона входа — то, от чего решается выход.
#[derive(Debug, Clone, Copy, PartialEq)]
struct Quotes {
    bid: f64,
    ask: f64,
    entry_side: HbtSide,
}

#[allow(clippy::too_many_lines)]
fn decide_exit<MD, B>(
    bot: &B,
    state: &mut StrategyState,
    entry_ns: i64,
    now: i64,
    quotes: Quotes,
    maker_allowed: bool,
) -> Option<ExitDecision>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    let Quotes {
        bid,
        ask,
        entry_side,
    } = quotes;
    let (px, taker, reason, frac) = match state.plan {
        TradePlan::SpreadHold => {
            if !maker_allowed || now.saturating_sub(entry_ns) < HOLD_NS {
                return None;
            }
            let px = exit_price(entry_side, bid, ask)?;
            (px, false, ExitReason::Horizon, 1.0)
        }
        TradePlan::Bounce {
            entry_px,
            stop_px,
            take_px,
            deadline_ns,
            trail_bps,
            trail_activate_bps,
            early_exit_ns,
            level_px,
            tick_px,
            take_frac,
            eaten_half_pct,
            eaten_all_pct,
            eaten_half_frac,
            exit_eat_pct,
            exit_gone_pct,
            gone_trail_bps,
            gone_be,
            ..
        } => {
            // F4 (В-78): стоп и тейк — от **средней цены исполненного**
            // входа, а не от плановой `entry_px`: лестница и частичное
            // исполнение дают другую среднюю, а форма задаёт уровни
            // расстояниями от входа. Сдвиг — целое число тиков
            // (`level_shift`), при полном исполнении по плановой цене
            // он ноль и числа прежних прогонов не меняются.
            let shift = level_shift(state.entry_vwap(), entry_px, tick_px);
            let (stop_px, take_px, entry_px) = (stop_px + shift, take_px + shift, entry_px + shift);
            // Трейл-тейк (решение владельца 2026-09-13): следим за
            // лучшим исходом и выходим по рынку, когда цена откатилась
            // от него на `trail_bps`, но не раньше, чем прибыль дошла
            // до `trail_activate_bps`. Пока трейл включён, фиксированный
            // `take_px` не работает — иначе он и был бы выходом, а мы
            // как раз пробуем тянуть дальше 1:1.
            let favourable = match entry_side {
                HbtSide::Buy => bid,
                _ => ask,
            };
            state.observe_favourable(favourable);
            // Текущий размер стены на уровне — база и для съедания E7, и для
            // F7 `gone<W>`. Без валидного тика/цены размера уровня не
            // существует: `now_qty` = 0, но **ни** «ноль на уровне», ни
            // «стена снята» из этого не следуют (`level_ok`) — иначе вырождённый
            // план с `tick_px = 0` читался бы как полностью съеденная стена.
            let level_ok = tick_px > 0.0 && level_px > 0.0;
            #[allow(clippy::cast_possible_truncation)]
            let level_tick = if level_ok {
                (level_px / tick_px).round() as i64
            } else {
                0
            };
            let depth = bot.depth(state.asset_no);
            let now_qty = if level_ok {
                match entry_side {
                    HbtSide::Buy => depth.bid_qty_at_tick(level_tick),
                    _ => depth.ask_qty_at_tick(level_tick),
                }
            } else {
                0.0
            };
            if level_ok && now_qty > state.level_qty_max {
                state.level_qty_max = now_qty;
            }
            // Съедание плотности (E5/E7): остаток на цене уровня
            // против максимума с входа, в процентах. Без валидного уровня
            // процента нет (`level_ok`) — как было до F7.
            let eaten_pct = if level_ok && state.level_qty_max > 0.0 {
                (1.0 - now_qty / state.level_qty_max) * 100.0
            } else {
                0.0
            };
            // F7 (Б-75): проверка форм выхода «съели» / «сняли». Накопленное
            // исполнение **в стену** (`state.eaten_qty`) зачитывает драйвер
            // (`run_round::observe_wall_trades`): буфер последних сделок
            // (`bot.last_trades`) живёт под управлением драйвера и чистится на
            // каждом шаге, поэтому здесь читается только накопленная сумма.
            // Порядок: стоп и трейл честнее тейка; `eat`/`gone` — защитные
            // выходы, ниже тейка и выше «прилипания» и дедлайна.
            let eat_hit = exit_eat_pct > 0.0
                && state.level_qty_at_entry > 0.0
                && state.eaten_qty >= state.level_qty_at_entry * exit_eat_pct / 100.0;
            let gone_hit = exit_gone_pct > 0.0
                && state.level_qty_at_entry > 0.0
                // Размер уровня читается только при валидном тике: иначе «ноль
                // на уровне» — это отсутствие данных, а не снятая стена.
                && level_ok
                && now_qty < state.level_qty_at_entry * (1.0 - exit_gone_pct / 100.0)
                && state.eaten_qty < (state.level_qty_at_entry - now_qty) * 0.5;
            // Трейл после снятия (владелец 23.09): снятие взводит трейл ценой этого события
            // (защёлка — дальше пик ведётся и без стены), выход — откат от пика после снятия.
            let gone_trail = gone_trail_bps > 0.0;
            if gone_trail && (gone_hit || state.gone_peak > 0.0) {
                state.observe_gone_peak(favourable);
            }
            let gone_trail_hit = gone_trail
                && state.gone_peak > 0.0
                && entry_px > 0.0
                && (state.gone_peak - favourable).abs() / entry_px * 10_000.0 >= gone_trail_bps;
            // Безубыток после снятия (владелец 23.09): снятие взводит защёлку; стоп переносится в
            // цену, при которой круг закрывается в ноль с комиссиями (вход мейкером, выход тейкером),
            // как только позиция у неё или лучше. Жёсткий режим закрывает позицию хуже безубытка сразу.
            if gone_be > 0 && gone_hit {
                state.gone_seen = true;
            }
            let be_px = match entry_side {
                HbtSide::Buy => entry_px * (1.0 + crate::lob::costs::ROUNDTRIP_FEES_BPS / 10_000.0),
                _ => entry_px * (1.0 - crate::lob::costs::ROUNDTRIP_FEES_BPS / 10_000.0),
            };
            if state.gone_seen && !state.be_active && entry_px > 0.0 {
                let at_be = match entry_side {
                    HbtSide::Buy => favourable >= be_px,
                    _ => favourable <= be_px,
                };
                if at_be {
                    state.be_active = true;
                }
            }
            let be_hard_exit = gone_be == 2 && state.gone_seen && !state.be_active;
            let stop_eff = if state.be_active {
                match entry_side {
                    HbtSide::Buy => stop_px.max(be_px),
                    _ => stop_px.min(be_px),
                }
            } else {
                stop_px
            };
            let (stop_hit, take_hit) = match entry_side {
                HbtSide::Buy => (bid <= stop_eff, bid >= take_px),
                _ => (ask >= stop_eff, ask <= take_px),
            };
            let trail_hit = if trail_bps > 0.0 && entry_px > 0.0 {
                let gain_bps = (state.best_favourable - entry_px).abs() / entry_px * 10_000.0;
                let give_back_bps =
                    (state.best_favourable - favourable).abs() / entry_px * 10_000.0;
                gain_bps >= trail_activate_bps && give_back_bps >= trail_bps
            } else {
                false
            };
            // Частичный тейк срабатывает один раз: после него остаток
            // на 1:1 не закрывается — бежит до стопа/дедлайна/трейла/
            // съедания (E7 «остаток по замедлению»).
            let take_partial = take_frac > 0.0 && take_frac < 1.0;
            let take_active = !(take_partial && state.partial_done);
            let eaten_all_hit = eaten_all_pct > 0.0 && eaten_pct >= eaten_all_pct;
            let eaten_half_hit =
                eaten_half_pct > 0.0 && !state.partial_done && eaten_pct >= eaten_half_pct;
            if stop_hit {
                // Сработал перенесённый в безубыток стоп — это защита по снятию («сняли»), а не стоп.
                let reason = if stop_eff != stop_px {
                    ExitReason::WallGone
                } else {
                    ExitReason::Stop
                };
                (stop_eff, true, reason, 1.0)
            } else if be_hard_exit {
                match exit_price(entry_side, bid, ask) {
                    Some(px) => (px, true, ExitReason::WallGone, 1.0),
                    None => return None,
                }
            } else if eaten_all_hit {
                match exit_price(entry_side, bid, ask) {
                    Some(px) => (px, true, ExitReason::Eaten, 1.0),
                    None => return None,
                }
            } else if trail_hit {
                (favourable, true, ExitReason::Trail, 1.0)
            } else if maker_allowed && trail_bps <= 0.0 && take_hit && take_active {
                (
                    take_px,
                    false,
                    ExitReason::Take,
                    if take_partial { take_frac } else { 1.0 },
                )
            } else if eaten_half_hit {
                match exit_price(entry_side, bid, ask) {
                    Some(px) => (px, true, ExitReason::Eaten, eaten_half_frac),
                    None => return None,
                }
            } else if eat_hit {
                match exit_price(entry_side, bid, ask) {
                    Some(px) => (px, true, ExitReason::EatenByTrades, 1.0),
                    None => return None,
                }
            } else if gone_hit && !gone_trail && gone_be == 0 {
                match exit_price(entry_side, bid, ask) {
                    Some(px) => (px, true, ExitReason::WallGone, 1.0),
                    None => return None,
                }
            } else if gone_trail_hit {
                // Выход трейла после снятия — та же причина «сняли»: колонки `forms.csv`
                // не меняются, а форма (`gone<W>tr<T>`) говорит, как именно вышли.
                (favourable, true, ExitReason::WallGone, 1.0)
            } else if early_exit_ns > 0
                && now.saturating_sub(entry_ns) >= early_exit_ns
                && still_at_level(entry_side, bid, ask, level_px, tick_px)
            {
                // Досрочный выход (B4, В-58 п. 5): «прилипание» —
                // касание длится дольше `X` секунд, а уровень так и
                // остался лучшей ценой. Порядок проверок часть плана:
                // стоп и трейл (если сработали) честнее, тейк-лимит
                // тоже — он дал бы мейкерскую цену, а здесь выход по
                // рынку.
                match exit_price(entry_side, bid, ask) {
                    Some(px) => (px, true, ExitReason::Early, 1.0),
                    None => return None,
                }
            } else if now.saturating_sub(entry_ns) >= deadline_ns {
                match exit_price(entry_side, bid, ask) {
                    Some(px) => (px, true, ExitReason::Deadline, 1.0),
                    None => return None,
                }
            } else {
                return None;
            }
        }
    };
    Some(ExitDecision {
        px,
        taker,
        reason,
        frac,
    })
}

/// Подача заявки выхода по решению `decide_exit`: размер — своя позиция
/// круга (F4, В-78), дробный выход (E7) — вниз до кратного шага лота, стоп и
/// дедлайн — по рынку (тейкер, IOC), тейк и горизонт — лимитом (мейкер,
/// GTC). Вынесено из `on_event` (аудит 21.09): та же подача нужна и после
/// снятия зависшей лимитки тейка.
fn submit_exit<MD, B>(
    bot: &mut B,
    state: &mut StrategyState,
    entry_ns: i64,
    exit_side: HbtSide,
    decision: ExitDecision,
) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    let ExitDecision {
        px,
        taker,
        reason,
        frac,
    } = decision;
    let order_id = state.take_order_id();
    // Размер выхода — **своя позиция круга** (F4, В-78), а не плановый
    // размер: вход может исполниться частично (модель очереди по
    // объёму) или лестницей, и выход на плановый размер переворачивал
    // бы позицию, оставляя круг незакрытым. `Bot::position` крейта на
    // роль источника не годится — он частичного исполнения не видит
    // (находка F3), поэтому позиция ведётся в состоянии по ордерам.
    // Своей позиции нет (исполнение не отразилось) — прежняя
    // подстановка планового размера круга.
    // Свободная позиция: минус остаток стоящих сирот выхода (F8c, ревью 22.09
    // п. 4) — иначе исполнятся и сирота, и новый выход, и круг уйдёт в перепрод.
    let pos = {
        let pos = state.free_position();
        if pos > 0.0 {
            pos
        } else if state.position() > 0.0 {
            // Вся позиция зарезервирована сиротой выхода — ждём её (или её
            // отмены) на следующем событии, новой заявки не ставим.
            return Ok(Action::Idle);
        } else {
            state.qty
        }
    };
    // Дробный выход (E7): доля позиции, вниз до кратного шага лота;
    // ноль лотов — значит делить нечего, выходим целиком.
    let (exit_qty, partial) = if frac > 0.0 && frac < 1.0 {
        let lot = match state.plan {
            TradePlan::Bounce { lot_qty, .. } => lot_qty,
            TradePlan::SpreadHold => 0.0,
        };
        let raw = pos * frac;
        let q = if lot > 0.0 {
            (raw / lot).floor() * lot
        } else {
            raw
        };
        if q > 0.0 && q < pos {
            (q, true)
        } else {
            (pos, false)
        }
    } else {
        (pos, false)
    };
    if partial {
        state.partial_done = true;
    }
    // Стоп и дедлайн — по рынку (тейкер, IOC); тейк и горизонт —
    // лимитом (мейкер, GTC). Это не деталь реализации: издержки
    // `costs` считают тейкера и мейкера по-разному, и бэктест должен
    // видеть тот же тип ордера, что поставит живой контур.
    let (tif, ord_type) = if taker {
        (TimeInForce::IOC, OrdType::Market)
    } else {
        (TimeInForce::GTC, OrdType::Limit)
    };
    match exit_side {
        HbtSide::Buy => {
            bot.submit_buy_order(state.asset_no, order_id, px, exit_qty, tif, ord_type, false)?;
        }
        _ => {
            bot.submit_sell_order(state.asset_no, order_id, px, exit_qty, tif, ord_type, false)?;
        }
    }
    // Заявка выхода только ушла — исполнение зачтёт `observe_exit` на
    // следующем событии (крейт обрабатывает отклик на ближайшем
    // `elapse`), поэтому позиция закрытой ещё не считается.
    state.exit_accounted = 0.0;
    state.phase = if state.position() <= 0.0 {
        Phase::Idle
    } else {
        Phase::ExitPending { order_id, entry_ns }
    };
    Ok(Action::ExitSubmitted {
        order_id,
        side: exit_side,
        price: px,
        reason,
        partial,
    })
}

/// Одна функция стратегии (A6, D-СТРАТЕГИЯ). Вызывается один раз на событие
/// потока — какое именно событие произошло, эта функция не спрашивает: она
/// смотрит на `bot.current_timestamp()`/`bot.depth()`/`bot.orders()` в
/// момент вызова, что и есть контракт `Bot<MD>` что в `Backtest`, что в
/// `LiveBot` (`current_timestamp` — время внутри данных или локальные часы
/// соответственно, `ARCHITECTURE.md` A6). Позиция круга — **своя**
/// (`StrategyState::position`, по исполненному в ордерах крейта), а не
/// `bot.position`: крейт обновляет позицию только на `Filled` и частичного
/// исполнения не видит (F3/В-78).
///
/// Не аллоцирует (`ARCHITECTURE.md`, запрет 1): никаких `Vec`/`String` на
/// своём пути, только копируемые `Phase`/`Action` и вызовы `Bot<MD>`.
/// Не вызывает часы напрямую (запрет 2 `interfaces.md`) — время только через
/// `bot.current_timestamp()`. Не делает REST и не строит/подписывает ордер
/// после решения (запреты 4, 5) — `submit_*_order` крейта не имеет отношения
/// к `bybit::sign`, это ответственность `Bot<MD>` (бэктест — симуляция,
/// живой — коннектор фазы 2, вне этого прохода).
/// Позиция открыта: решение выхода (`decide_exit`) и подача (`submit_exit`).
fn on_holding<MD, B>(
    bot: &mut B,
    state: &mut StrategyState,
    now: i64,
    entry_ns: i64,
) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    let Some((bid, ask)) = best_prices(bot.depth(state.asset_no)) else {
        // Без книги выйти нельзя — круг остаётся Holding к следующему
        // событию, а не теряется молча.
        return Ok(Action::Idle);
    };
    let Some(entry_side) = entry_side(state.sigma) else {
        return Ok(Action::Idle);
    };
    let exit_side = match entry_side {
        HbtSide::Buy => HbtSide::Sell,
        _ => HbtSide::Buy,
    };
    // Что и в каком порядке решает выход — `decide_exit`; как
    // подаётся заявка — `submit_exit`.
    let quotes = Quotes {
        bid,
        ask,
        entry_side,
    };
    match decide_exit(bot, state, entry_ns, now, quotes, true) {
        Some(decision) => submit_exit(bot, state, entry_ns, exit_side, decision),
        None => Ok(Action::Idle),
    }
}

/// Заявка выхода в рынке: учёт исполненного, возврат остатка в план, снятие
/// зависшей лимитки по рыночной причине (аудит 21.09, Б1).
fn on_exit_pending<MD, B>(
    bot: &mut B,
    state: &mut StrategyState,
    now: i64,
    order_id: u64,
    entry_ns: i64,
) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    state.observe_exit(bot, order_id);
    if state.position() <= 0.0 {
        state.phase = Phase::Idle;
        return Ok(Action::Idle);
    }
    // Заявка выхода решена (исполнена, снята или отвергнута) и больше
    // не стоит в рынке: остаток позиции ведём по плану дальше —
    // прежними часами круга (дедлайн считается от входа, а не от
    // выхода). Так закрывается и частичный выход E7, и выход, который
    // модель очереди по объёму отдала не целиком (F4, В-78): раньше
    // такой остаток ждал заявку, которой уже нет, до конца записи.
    let (resolved, resting_maker) = match bot.orders(state.asset_no).get(&order_id) {
        Some(o) => {
            let open = matches!(
                o.status,
                Status::None | Status::New | Status::PartiallyFilled
            );
            (
                o.req == Status::None && !open,
                o.req == Status::None && o.order_type == OrdType::Limit && open,
            )
        }
        None => (true, false),
    };
    if resolved {
        state.phase = Phase::Holding { entry_ns };
        return Ok(Action::Idle);
    }
    // Аудит 21.09, Б1: лимитка тейка стоит в рынке (не исполнена или
    // исполнена частично — под моделью очереди по объёму это норма),
    // а остаток позиции при этом **не ведётся**: стоп, дедлайн, трейл
    // и съедание для него не проверялись, и круг ждал до конца записи
    // (`EndOfData`), теряя все дальнейшие сигналы суток. Теперь
    // остаток под стоящей лимиткой решается теми же рыночными
    // причинами: сработала — снимаем лимитку, а после подтверждения
    // отмены остаток закрывается тейкером через `Holding` (условие
    // стопа/дедлайна держится и на следующем событии).
    if resting_maker {
        let (Some((bid, ask)), Some(entry_side)) = (
            best_prices(bot.depth(state.asset_no)),
            entry_side(state.sigma),
        ) else {
            return Ok(Action::Idle);
        };
        let quotes = Quotes {
            bid,
            ask,
            entry_side,
        };
        if let Some(decision) = decide_exit(bot, state, entry_ns, now, quotes, false) {
            if decision.taker {
                bot.cancel(state.asset_no, order_id, false)?;
                state.phase = Phase::ExitCancelPending {
                    order_id,
                    entry_ns,
                    cancel_sent_ns: now,
                };
            }
        }
    }
    Ok(Action::Idle)
}

/// Отмена лимитки выхода летит: ждём, пока заявка перестанет быть открытой.
/// `cancel_sent_ns` — часы отправки отмены; по ним работает потолок
/// `CANCEL_WAIT_NS` (F8b, В5/Р2). Заявка, чей запрос постановки ещё летел в
/// момент рыночной причины, снимается повторно на следующем шаге — иначе она
/// осталась бы в рынке, а фаза ждала бы её вечно.
fn on_exit_cancel_pending<MD, B>(
    bot: &mut B,
    state: &mut StrategyState,
    now: i64,
    order_id: u64,
    entry_ns: i64,
    cancel_sent_ns: i64,
) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    state.cancel_open(bot, order_id)?;
    // Отмена лимитки выхода летит; исполнение могло её обогнать
    // (та же гонка, что у входа, 2026-09-18) — считаем исполненное и
    // ждём, пока заявка перестанет быть открытой.
    state.observe_exit(bot, order_id);
    if state.position() <= 0.0 {
        state.phase = Phase::Idle;
        return Ok(Action::Idle);
    }
    let open = match bot.orders(state.asset_no).get(&order_id) {
        Some(o) => {
            o.req != Status::None
                || matches!(
                    o.status,
                    Status::None | Status::New | Status::PartiallyFilled
                )
        }
        None => false,
    };
    if !open {
        state.phase = Phase::Holding { entry_ns };
        return Ok(Action::Idle);
    }
    // F8b (В5/Р2): подтверждение отмены не пришло за потолок — остаток позиции
    // ведёт план (`Holding`), а не ждёт биржу до конца записи. Заявка выхода
    // могла остаться в рынке: предохранитель назван `CancelTimeout`, но
    // короче круга он не притворяется — позиция остаётся под управлением
    // стратегии, а не бросается.
    if now.saturating_sub(cancel_sent_ns) >= CANCEL_WAIT_NS {
        state.exit_cancel_timeouts = state.exit_cancel_timeouts.saturating_add(1);
        state.adopt_orphans(order_id, 1, OrphanKind::Exit);
        state.phase = Phase::Holding { entry_ns };
    }
    Ok(Action::Idle)
}

/// Вход в рынке: накопление позиции по ногам, срок жизни и причины снятия (F4/F5).
fn on_entry_pending<MD, B>(
    bot: &mut B,
    state: &mut StrategyState,
    now: i64,
    order_id: u64,
    sent_ns: i64,
    legs: u8,
) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    // F4 (В-78): вход копит позицию. Первая исполнившаяся нога
    // остальные **не снимает** — лестница набирает объём, пока жив
    // вход; об исполненном и средней цене судим по ордерам крейта,
    // потому что `bot.position` частичного исполнения не видит.
    let snap = state.observe_entry(bot, order_id, legs);
    if !snap.open {
        // Вход решён: ни одна нога не стоит и запросов в пути нет —
        // всё, что могло исполниться, исполнено; остальное снято или
        // отвергнуто биржей.
        if state.position() > 0.0 {
            state.enter_holding(now);
            return Ok(Action::Idle);
        }
        // Позиции нет: либо вход истёк, либо ни одной ноги не
        // поставила биржа (пост-онли заявка пересекла спред, В-72) —
        // «сигнал без входа». Круг свободен сразу, а не висит
        // «занятым» до конца срока жизни входа.
        state.phase = Phase::Idle;
        return Ok(Action::EntryTimedOut {
            order_id,
            reason: EntryCancelReason::NotPlaced,
        });
    }
    // F5 (В-74): вход живёт, пока стена жива и цена в полосе, — это
    // события рынка, а не таймер. Проверяются **раньше** потолка:
    // если условие и потолок совпали на одном кадре, честнее назвать
    // событие, которое и было поводом снять вход.
    if let Some(reason) = state.entry_cancel_reason(bot) {
        state.cancel_resting(bot, order_id, legs)?;
        state.phase = Phase::CancelPending {
            order_id,
            legs,
            reason,
            cancel_sent_ns: now,
        };
        return Ok(Action::Idle);
    }
    if now.saturating_sub(sent_ns) >= state.plan.entry_ttl_ns() {
        state.cancel_resting(bot, order_id, legs)?;
        state.phase = Phase::CancelPending {
            order_id,
            legs,
            reason: EntryCancelReason::Ttl,
            cancel_sent_ns: now,
        };
        return Ok(Action::Idle);
    }
    Ok(Action::Idle)
}

/// Отмена входа летит: гонка с исполнением (2026-09-18) и переход в `Holding`/`Idle`.
/// `cancel_sent_ns` — часы отправки отмены, по ним работает потолок
/// `CANCEL_WAIT_NS` (F8b, В5/Р2); снятие повторяется на каждом шаге, пока
/// нога, чей запрос постановки был в полёте, не станет снимаемой.
fn on_cancel_pending<MD, B>(
    bot: &mut B,
    state: &mut StrategyState,
    now: i64,
    order_id: u64,
    legs: u8,
    reason: EntryCancelReason,
    cancel_sent_ns: i64,
) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    // F8b (В5/Р2): повтор снятия. Нога, чей запрос постановки летел в момент
    // снятия входа, тогда пропущена (`cancel_resting` снимает только `New`/
    // `PartiallyFilled` без запроса в полёте) — без повтора она осталась бы в
    // рынке, а фаза «отмена летит» ждала бы её вечно.
    state.cancel_resting(bot, order_id, legs)?;
    // Исполнение обогнало отмену — позиция есть, ведём её по плану.
    // Пока хоть одна нога ещё стоит или снимается, вход не решён:
    // позицию добираем (F4, В-78), а не бросаем на половине.
    let snap = state.observe_entry(bot, order_id, legs);
    if !snap.open {
        if state.position() > 0.0 {
            state.enter_holding(now);
            return Ok(Action::Idle);
        }
        state.phase = Phase::Idle;
        return Ok(Action::EntryTimedOut { order_id, reason });
    }
    // Потолок ожидания: подтверждение отмены не пришло — круг освобождается
    // под тем же правилом, что и при подтверждённой отмене (позиция есть →
    // ведём её, нет → причина называется). Заявка могла остаться в рынке:
    // это предохранитель, и он назван `CancelTimeout`.
    if now.saturating_sub(cancel_sent_ns) >= CANCEL_WAIT_NS {
        // Ноги остаются сиротами (F8c, К1): снятие повторится на каждом
        // событии, исполнение погасится по рынку и будет посчитано.
        state.adopt_orphans(order_id, legs, OrphanKind::Entry);
        if state.position() > 0.0 {
            state.enter_holding(now);
            return Ok(Action::Idle);
        }
        state.phase = Phase::Idle;
        return Ok(Action::EntryTimedOut {
            order_id,
            reason: EntryCancelReason::CancelTimeout,
        });
    }
    Ok(Action::Idle)
}

/// Сигнал есть — постановка входа: одиночная лимитка, лестница `grid_*` или
/// лестница формы F6.
fn on_idle<MD, B>(bot: &mut B, state: &mut StrategyState, now: i64) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    let Some(side) = entry_side(state.sigma) else {
        return Ok(Action::Idle);
    };
    // Цена входа: у Decision 20 — свой край спреда (нужна книга), у
    // сделки-отскока — цена, посчитанная уровнем заранее (В-44), и
    // книга для этого не нужна: вход стоит лимитом перед плотностью
    // и ждёт, пока цена подойдёт.
    let px = match state.plan {
        TradePlan::SpreadHold => {
            let Some((bid, ask)) = best_prices(bot.depth(state.asset_no)) else {
                return Ok(Action::Idle);
            };
            match entry_price(side, bid, ask) {
                Some(px) => px,
                None => return Ok(Action::Idle),
            }
        }
        TradePlan::Bounce { entry_px, .. } => entry_px,
    };
    // Время жизни входа: у Decision 20 ордер стоит у своего спреда с
    // `GTX` (пост-онли, как было); у сделки-отскока тип задан планом:
    // по В-72 (решение владельца 20.09) вход **только мейкером** —
    // пост-онли `GTX`, и заявка, пересекшая спред, биржей
    // отклоняется (`Expired`), то есть считается не поставленной
    // (`legs_rejected`). `GTC` остался ради гейта «те же круги»:
    // прежние прогоны сняты с тейкерским входом (находка T38: `GTX` в
    // момент касания отвергается ровно там, где спред сжался до тика),
    // и воспроизводит их `--no-post-only`.
    // Ждать подтверждения запроса нужно только плану В-44: у касания
    // длительность бывает нулевой, и снять заявку по TTL раньше
    // подтверждения нельзя — крейт отвечает `OrderRequestInProcess`
    // (`backtest/proc/local.rs:222`). У Decision 20 снятие идёт через
    // 2 с, там ждать нечего.
    let (entry_tif, entry_wait) = match state.plan {
        TradePlan::SpreadHold => (TimeInForce::GTX, false),
        TradePlan::Bounce { post_only, .. } => (
            if post_only {
                TimeInForce::GTX
            } else {
                TimeInForce::GTC
            },
            true,
        ),
    };
    // Вход лестницей (решение владельца 2026-09-13): вместо одного
    // лимита — `grid_legs` штук с шагом `grid_step_px`, каждая
    // следующая дальше от плотности в сторону рынка. Размер делится
    // между ногами. С F4 (В-78) ноги **копят позицию**: исполнившаяся
    // первой остальные не снимает — лестница набирает объём, пока жив
    // вход, а средняя цена исполненного ведёт стоп и тейк.
    //
    // F6 (В-73): если у плана есть лестница формы
    // (`ladder<N>x<from>..<to>[w<k>]`), ноги берутся **из неё** — у
    // каждой свой целый тик и своя доля (нижняя нога может весить
    // вдвое: «основной объём к сайзу» [T 1:31:42]). Прежний вход
    // (`ladder.n == 0`) идёт прежним путём — на этом стоит гейт «те же
    // круги». Нога, чья цена уже перекрыла лучший аск (для покупки),
    // ставится как пост-онли (`GTX`) и получает от биржи `Expired` —
    // это и есть «не ставится» (`legs_rejected`, F4/В-72).
    let (legs, ladder, step, tick_px) = match state.plan {
        TradePlan::Bounce {
            grid_legs,
            grid_step_px,
            ladder,
            tick_px,
            ..
        } => {
            let legs = if ladder.n > 0 {
                ladder.n
            } else {
                grid_legs.max(1)
            };
            (legs, ladder, grid_step_px, tick_px)
        }
        TradePlan::SpreadHold => (1u8, EntryLadder::NONE, 0.0f64, 0.0f64),
    };
    let first_id = state.next_order_id;
    for i in 0..u64::from(legs) {
        // Нога лестницы формы — свой тик и своя доля; прежний вход —
        // `px ± шаг × i` равными долями (F4: `qty / legs`).
        let (px_i, qty_i) = if ladder.n > 0 {
            let j = usize::try_from(i).unwrap_or(usize::from(ladder.n - 1));
            if j >= usize::from(ladder.n) {
                continue;
            }
            #[allow(clippy::cast_precision_loss)]
            (ladder.ticks[j] as f64 * tick_px, state.qty * ladder.frac[j])
        } else {
            #[allow(clippy::cast_precision_loss)]
            (
                match side {
                    HbtSide::Buy => px + step * i as f64,
                    _ => px - step * i as f64,
                },
                state.qty / f64::from(legs),
            )
        };
        let order_id = state.take_order_id();
        match side {
            HbtSide::Buy => {
                bot.submit_buy_order(
                    state.asset_no,
                    order_id,
                    px_i,
                    qty_i,
                    entry_tif,
                    OrdType::Limit,
                    entry_wait,
                )?;
            }
            _ => {
                bot.submit_sell_order(
                    state.asset_no,
                    order_id,
                    px_i,
                    qty_i,
                    entry_tif,
                    OrdType::Limit,
                    entry_wait,
                )?;
            }
        }
    }
    state.phase = Phase::EntryPending {
        order_id: first_id,
        sent_ns: now,
        legs,
    };
    Ok(Action::EntrySubmitted {
        order_id: first_id,
        side,
        price: px,
    })
}

pub fn on_event<MD, B>(bot: &mut B, state: &mut StrategyState) -> Result<Action, B::Error>
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    let now = bot.current_timestamp();
    // F8c (К1): сироты после потолка отмены — снять снова, учесть исполнение.
    state.sweep_orphans(bot)?;
    match state.phase {
        Phase::Holding { entry_ns } => on_holding(bot, state, now, entry_ns),
        Phase::ExitPending { order_id, entry_ns } => {
            on_exit_pending(bot, state, now, order_id, entry_ns)
        }
        Phase::ExitCancelPending {
            order_id,
            entry_ns,
            cancel_sent_ns,
        } => on_exit_cancel_pending(bot, state, now, order_id, entry_ns, cancel_sent_ns),
        Phase::EntryPending {
            order_id,
            sent_ns,
            legs,
        } => on_entry_pending(bot, state, now, order_id, sent_ns, legs),
        Phase::CancelPending {
            order_id,
            legs,
            reason,
            cancel_sent_ns,
        } => on_cancel_pending(bot, state, now, order_id, legs, reason, cancel_sent_ns),
        Phase::Idle => on_idle(bot, state, now),
    }
}

