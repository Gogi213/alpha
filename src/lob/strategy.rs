//! Стратегия — одна функция `on_event<MD, B: Bot<MD>>` (A6, D-СТРАТЕГИЯ,
//! таск 15). Идёт в `Backtest` крейта (`lob/backtest.rs:506`, шаг 6.3) и, в
//! фазе 2, в `LiveBot` — без единой правки: обе стороны реализуют один и тот
//! же `hftbacktest::types::Bot<MD>`, и это то самое A6 «стратегия пишется под
//! `Bot<MD>` крейта».
//!
//! Экономические примитивы не переизобретены здесь второй раз — это была бы
//! Reinvention (`interfaces.md`, правило 5): вход мейкером у своей стороны
//! спреда, время жизни входа, горизонт выхода и знак стороны уже названы и
//! проверены в `lob::backtest` (`entry_side`, `entry_price`, `exit_price`,
//! `ENTRY_TTL_NS`, `HOLD_NS`, `SIGMA_LONG`/`SIGMA_SHORT` — все `pub`), и этот
//! файл их переиспользует как есть. Разница с `backtest::drive_cell` — не в
//! экономике сделки, а в форме: `drive_cell` управляет временем бэктеста
//! пакетно, по заранее известному списку сигналов (`&[Signal]`), и не может
//! быть вызвана на живом сокете, где будущих событий не существует.
//! `on_event` — ровно одно событие за вызов, без `elapse`/`wait_*` внутри
//! себя: кто и когда продвигает часы стороны — решает вызывающий (тест ниже
//! и, в фазе 2, реальный live-цикл), а не эта функция.
//!
//! `best_prices` ниже — единственная реализация в `src/` (находка ревью,
//! таск 17): `lob::backtest` больше не держит одноимённый приватный хелпер
//! (снесён при переработке движка на очередь), так что копировать здесь
//! нечего — оставлена своя, потому что вызывающему (`on_event`) нужна ровно
//! эта проверка `INVALID_MIN`/`INVALID_MAX` перед тем же `entry_price`/
//! `exit_price` из `lob::backtest`.

use hftbacktest::depth::{MarketDepth, INVALID_MAX, INVALID_MIN};
use hftbacktest::types::{
    Bot, Event, OrdType, Side as HbtSide, Status, TimeInForce, EXCH_BUY_TRADE_EVENT,
    EXCH_SELL_TRADE_EVENT,
};

use crate::lob::backtest::{
    entry_price, entry_side, executed_qty, exit_price, ENTRY_TTL_NS, HOLD_NS,
};

/// Лучшие цены стороны как `(bid, ask)`, `None` — книга неполна
/// (`best_bid_tick`/`best_ask_tick` ещё на `INVALID_MIN`/`INVALID_MAX`,
/// до первого снапшота).
fn best_prices<MD: MarketDepth>(depth: &MD) -> Option<(f64, f64)> {
    if depth.best_bid_tick() == INVALID_MIN || depth.best_ask_tick() == INVALID_MAX {
        return None;
    }
    let (bid, ask) = (depth.best_bid(), depth.best_ask());
    if bid.is_finite() && ask.is_finite() && bid > 0.0 && ask > 0.0 {
        Some((bid, ask))
    } else {
        None
    }
}

/// Снимок ног входа по ордерам крейта (F4, В-78): накопленное исполненное
/// (`qty − leaves_qty`; у крейта `exec_qty` — объём **последнего** исполнения,
/// а не сумма), стоимость исполненного (`exec_price × исполненное`) и признак
/// «вход ещё решается» — в рынке стоит хоть одна нога или её запрос
/// (постановка/снятие) ещё не подтверждён биржей.
///
/// `Bot::position` крейта для этого не годится: `Local` обновляет позицию
/// только на `status == Filled`, поэтому частично исполненная нога (модель
/// очереди по объёму, F3) остаётся `PartiallyFilled` и позиции не даёт —
/// находка F3. Считается по ордерам (`orders(asset).get(&id)`), без кучи и без
/// `HashMap`: ног у плана единицы, лишних структур на пути события нет.
struct EntrySnapshot {
    /// Накопленное исполненное по всем ногам входа.
    qty: f64,
    /// Накопленная стоимость исполненного: `Σ exec_price × исполненное`.
    notional: f64,
    /// Вход ещё решается: нога стоит в рынке или её запрос летит.
    open: bool,
}

/// Снять снимок ног входа `first_id .. first_id + legs`. Нога, которой в учёте
/// крейта уже нет (биржа её не знает — терминальна и снята с учёта), вход не
/// держит: считать её «решается» значило бы ждать её вечно.
fn entry_snapshot<MD, B>(bot: &B, asset_no: usize, first_id: u64, legs: u8) -> EntrySnapshot
where
    MD: MarketDepth,
    B: Bot<MD>,
{
    let mut snap = EntrySnapshot {
        qty: 0.0,
        notional: 0.0,
        open: false,
    };
    for i in 0..u64::from(legs.max(1)) {
        let Some(order) = bot.orders(asset_no).get(&first_id.saturating_add(i)) else {
            continue;
        };
        if order.req != Status::None
            || matches!(order.status, Status::New | Status::PartiallyFilled)
        {
            snap.open = true;
        }
        let executed = executed_qty(order);
        if executed > 0.0 {
            snap.qty += executed;
            snap.notional += order.exec_price() * executed;
        }
    }
    snap
}

/// Сдвиг уровней стопа и тейка к **средней цене исполненного** входа (F4,
/// В-78). Форма задаёт стоп и тейк расстояниями от цены входа, поэтому, когда
/// реальная средняя другая (частичное исполнение, лестница), оба уровня
/// сдвигаются на ту же разницу — расстояния формы сохраняются.
///
/// Средняя приводится к сетке тиков (цены живут на тиках, так же поступает
/// крейт при постановке), поэтому сдвиг — целое число тиков; при полном
/// исполнении по плановой цене он **ровно ноль** (обе величины — произведение
/// одного и того же целого числа тиков на шаг), и числа прежних прогонов не
/// меняются — на этом стоит гейт «те же круги» (F3/F4).
fn level_shift(entry_vwap: Option<f64>, entry_px: f64, tick_px: f64) -> f64 {
    let Some(vwap) = entry_vwap else {
        return 0.0;
    };
    if !vwap.is_finite() || !entry_px.is_finite() || tick_px <= 0.0 {
        return 0.0;
    }
    let snapped = (vwap / tick_px).round() * tick_px;
    if (snapped - entry_px).abs() < tick_px * 0.5 {
        0.0
    } else {
        snapped - entry_px
    }
}

/// Стоит ли лучшая цена стороны **на уровне касания** (B4, В-58 п. 5):
/// «касание не кончилось» — цена не ушла ни в отскок, ни сквозь уровень.
/// Сравнение с точностью половины тика: цены собираются умножением целых тиков
/// на шаг, и равенство `f64` здесь было бы проверкой арифметики, а не рынка.
/// Уровень берётся со стороны входа: у лонга (бид-уровень) это лучший бид, у
/// шорта — лучший аск. Выключенный или неполный план (`tick_px = 0`) не даёт
/// «прилипания»: считать его на неизвестном шаге — выдумывать признак.
fn still_at_level(entry_side: HbtSide, bid: f64, ask: f64, level_px: f64, tick_px: f64) -> bool {
    if tick_px <= 0.0 || level_px <= 0.0 {
        return false;
    }
    let side_px = match entry_side {
        HbtSide::Buy => bid,
        _ => ask,
    };
    (side_px - level_px).abs() < tick_px * 0.5
}

/// Потолок ожидания подтверждения отмены — предохранитель фаз `CancelPending`
/// (вход) и `ExitCancelPending` (лимитка выхода), один механизм на обе (F8b,
/// В5/Р2 аудита 21.09).
///
/// Число — решение владельца 2026-09-21 (В-79): 1 с. Измеренная В-68 задержка
/// снятия по WS trade с боевого сервера: медиана 3.98 мс, p95 4.55, p99 5.01,
/// max 5.42 мс (100 циклов); REST-хвост до 15.5 мс. Потолок в ~200 раз выше
/// измеренного p95 и в ~70 раз выше REST-максимума, поэтому **при задержке
/// снятия В-68** в бэктесте он не срабатывает (числа прежних прогонов не
/// меняются — гейт «те же круги» это проверяет: `f3-queue-gate.sh` требует
/// нулей `n_entry_cancelled_cancel_timeout`/`n_exit_cancel_timeout`). Это
/// свойство измеренных RTT, не общее: сетка с `--median-rtt-ns cancel=` выше
/// потолка включит его, и колонки это покажут. В живом контуре потолок
/// освобождает круг, если подтверждение отмены не пришло: без него фаза ждёт
/// биржу бесконечно, сигналы суток теряются (ровно то, ради чего закрывался Б1).
///
/// Срабатывание — не «отмена прошла»: заявка могла остаться в рынке, поэтому
/// потолок только освобождает круг под управлением плана (`Holding` при
/// позиции), а причина называется `CancelTimeout` — видно в `forms.csv`.
/// Сама заявка становится **сиротой** (F8c, К1): снятие повторяется на каждом
/// событии в любой фазе, исполнение сироты считается и гасится
/// (`StrategyState::sweep_orphans`).
pub const CANCEL_WAIT_NS: i64 = 1_000_000_000;

/// Фаза одного круга. Спрятана от вызывающего (`interfaces.md`: модуль
/// `lob/strategy` «прячет: триггер, состояние») — снаружи виден только
/// `Action`, возвращённый из `on_event`.
#[derive(Debug, Clone, Copy, PartialEq)]
enum Phase {
    /// Ждём случая войти: следующий валидный тик со спредом — и есть
    /// триггер (D-ОРДЕР: цена и размер к этому моменту уже известны заранее,
    /// сборка кадра на живом пути — забота `commands::lob::react`, не эта
    /// функция — здесь только решение `Bot<MD>`).
    Idle,
    /// Вход отправлен, ждём исполнения или истечения `entry_ttl_ns`. Лестница
    /// ставит несколько ордеров подряд: `order_id` — первый, всего `legs`.
    /// С F4 (В-78) первая исполнившаяся нога **не снимает остальные**:
    /// позиция копится, пока жив вход, а её размер и средняя цена считаются по
    /// ордерам крейта (`entry_snapshot`) — `Bot::position` частичного
    /// исполнения не видит.
    EntryPending {
        order_id: u64,
        sent_ns: i64,
        legs: u8,
    },
    /// Позиция открыта, ждём `HOLD_NS` до выхода.
    Holding { entry_ns: i64 },
    /// Выход отправлен. `entry_ns` — часы круга (их же ведёт `Holding`),
    /// чтобы остаток позиции после неполного выхода вернулся в план: так
    /// ведётся и частичный выход E7, и выход, который модель очереди по
    /// объёму отдала не целиком (F4, В-78).
    ExitPending { order_id: u64, entry_ns: i64 },
    /// Лимитка выхода снимается по рыночной причине (аудит 21.09, Б1: стоп,
    /// дедлайн, трейл или съедание наступили, пока тейк стоял в рынке
    /// частично исполненным) — ждём подтверждения отмены, потом остаток
    /// закрывается тейкером через `Holding`. `cancel_sent_ns` — часы отправки
    /// отмены: по ним считается потолок ожидания `CANCEL_WAIT_NS` (F8b, В5/Р2).
    ExitCancelPending {
        order_id: u64,
        entry_ns: i64,
        cancel_sent_ns: i64,
    },
    /// Вход истёк, отмена отправлена — ждём ответа биржи. Если, пока отмена
    /// летела (RTT), заявка исполнилась, позиция открыта: идём в `Holding`, а
    /// не в `Idle`. Найдено 2026-09-18: раньше после истечения стратегия сразу
    /// считала себя свободной, исполненная в гонке заявка оставалась без
    /// выхода, и все дальнейшие сигналы были «позиция занята» (на ZEC за 20 ч
    /// круги шли только первые ~27 минут).
    CancelPending {
        order_id: u64,
        legs: u8,
        /// Почему вход снимается — несётся до подтверждения отмены, чтобы
        /// `EntryTimedOut` назвал событие рынка (F5, В-74), а не потолок.
        reason: EntryCancelReason,
        /// Часы отправки отмены — потолок ожидания `CANCEL_WAIT_NS`
        /// (F8b, В5/Р2). Повторное снятие ног, чей запрос постановки был
        /// в полёте в момент потолка срока жизни, идёт с тем же отсчётом.
        cancel_sent_ns: i64,
    },
}

/// Ёмкость ног лестницы входа (F6, В-73) — размер массива в `EntryLadder`.
/// Форма с `N` больше — отказ при разборе имени (`EntryForm::parse`), а не
/// молчаливое усечение: у движка счёт ног идёт битовой маской (`run_round`),
/// и «ещё пара ног» там уже не считается.
pub const MAX_ENTRY_LEGS: usize = 8;

/// Ноги лестницы входа (F6, В-73): целые тики цен и доли позиции. Ноги идут
/// **от стены к рынку** (`ticks[0]` — ближайшая к стене, `ticks[n-1]` — самая
/// дальняя), доли нормированы в сумму 1. `n == 0` — входа-лестницы нет: план
/// исполняет прежний вход (`entry_px`/`grid_legs`/`grid_step_px`) — на нём
/// стоит гейт «те же круги» (F3/F4/F5).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct EntryLadder {
    pub n: u8,
    pub ticks: [i64; MAX_ENTRY_LEGS],
    pub frac: [f64; MAX_ENTRY_LEGS],
}

impl EntryLadder {
    /// Вход без лестницы: прежний одиночный лимит.
    pub const NONE: Self = Self {
        n: 0,
        ticks: [0; MAX_ENTRY_LEGS],
        frac: [0.0; MAX_ENTRY_LEGS],
    };

    /// Добавить ногу; `false` — ёмкость исчерпана. Вызывающий (`bounce_plan`)
    /// обязан отказать раньше: имя формы проверено разбором `EntryForm`.
    pub fn push(&mut self, tick: i64, frac: f64) -> bool {
        let i = usize::from(self.n);
        if i >= MAX_ENTRY_LEGS {
            return false;
        }
        self.ticks[i] = tick;
        self.frac[i] = frac;
        self.n = self.n.saturating_add(1);
        true
    }

    /// Средняя цена входа в тиках — по долям ног (вес × цена, F6): от неё
    /// `bounce_plan` считает стоп и тейк формы (стратегия после F4 сдвигает их
    /// к фактической средней исполненного).
    #[allow(clippy::cast_precision_loss)]
    pub fn weighted_avg_tick(&self) -> f64 {
        let mut sum = 0.0;
        for i in 0..usize::from(self.n) {
            sum += self.frac[i] * self.ticks[i] as f64;
        }
        sum
    }

    /// Тик дальней (самой близкой к рынку) ноги — по ней меряется «цена ушла
    /// из полосы» (F5, В-74). `None` — лестницы нет.
    pub fn outer_tick(&self) -> Option<i64> {
        (self.n > 0).then(|| self.ticks[usize::from(self.n - 1)])
    }
}

/// План сделки — **данные**, а не вторая стратегия (A6): что именно ловить и
/// где выходить, решает уровень `lob/levels` (касание В-44, смерть уровня),
/// `on_event` только исполняет план. Оба варианта идут через одну и ту же
/// функцию, поэтому сделка-отскок попадает и в `Backtest`, и в `LiveBot` без
/// правок.
///
/// `large_enum_variant`: вариант `Bounce` (F6 добавил в него `EntryLadder` —
/// ноги лестницы: тики и доли) крупнее пустого `SpreadHold`. План ходит по
/// значению (`Copy`) и копируется в горячем пути (`on_event`, `legs_of`,
/// `drive_signal`), где аллокаций быть не должно (A1–A9): упаковка варианта в
/// `Box` запретила бы `Copy` и внесла бы индирекцию в решение на событии.
/// Размер плана — цена того, что ноги лестницы уже посчитаны (`bounce_plan`),
/// а стратегия только ставит их.
#[allow(clippy::large_enum_variant)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum TradePlan {
    /// Decision 20 (как было): вход мейкером у своей стороны спреда, выход
    /// ровно на `HOLD_NS`, без стопа и тейка. Числа прежнего бэктеста этим
    /// вариантом не меняются — на нём стоит шов старого движка.
    SpreadHold,
    /// В-44, сделка-отскока: цены и срок приходят снаружи — лимитный вход по
    /// `entry_px` (за тик перед плотностью), стоп по рынку при сделке на
    /// `stop_px` (за тик внутри плотности), тейк лимитом `take_px`
    /// (R 1:1), дедлайн `deadline_ns` от момента входа — после него выход по
    /// рынку; неисполненный вход живёт, пока стена жива и цена в полосе, а
    /// `entry_ttl_ns` — предохранительный потолок (F5, В-74).
    Bounce {
        entry_px: f64,
        stop_px: f64,
        take_px: f64,
        deadline_ns: i64,
        /// Предохранительный **потолок** срока жизни неисполненного входа,
        /// нс (F5, В-74). Это не таймер: вход снимается раньше по условиям
        /// `level_floor_qty`/`band_exit_bps`, а потолок — страховка (сетка
        /// замера {60, 300, 1800} с приходит флагом `--entry-ttl-secs`).
        /// Прежний режим «до конца касания» — `entry_ttl_ns = end − start`
        /// касания; он же — гейт «те же круги».
        entry_ttl_ns: i64,
        /// Порог В-66 в единицах крейта (`--h3-usd / цена уровня`, считает
        /// `bounce_plan`): размер **на `level_px` в текущем кадре** ниже него
        /// — стена снята (F5, В-74), все ноги входа снимаются, фаза `Idle`.
        /// `0` — условие выключено (прежний режим `touch`).
        level_floor_qty: f64,
        /// Полоса ухода цены, bps (F5, В-74, **число замера**, не константа):
        /// лучшая цена нашей стороны дальше дальней ноги лестницы больше чем
        /// на это число — цена ушла из полосы, вход снимается. `0` — условие
        /// выключено (прежний режим `touch`).
        band_exit_bps: f64,
        /// Досрочный выход «по прилипанию» (B4, В-58 п. 5): секунды `X` из
        /// предрегистрированного набора {1, 2, 3} в наносекундах, `0` —
        /// выключен. Если через `X` после входа лучшая цена стороны всё ещё
        /// стоит на уровне входа касания (`level_px` с точностью до половины
        /// `tick_px`), касание не разрешилось — выходим по рынку с причиной
        /// `Early`.
        early_exit_ns: i64,
        /// Цена уровня касания `P` — по ней решается «уровень ещё держит»
        /// (B4). Не путать с `entry_px`: вход может стоять от фронтранера.
        level_px: f64,
        /// Шаг цены инструмента: сравнение «цена ещё на уровне» — с точностью
        /// половины тика, а не равенством `f64` (цены приходят из целых тиков,
        /// но собираются умножением на шаг).
        tick_px: f64,
        /// Вход пост-онли (`GTX`) или обычным лимитом (`GTC`). Решение
        /// владельца 20.09 (В-72): у сделки-отскока вход **только мейкером**,
        /// пост-онли, — лимитка, пересекающая спред, биржей отклоняется
        /// (`Expired`) и считается **не поставленной** (`legs_rejected`).
        /// Поле осталось параметром для гейта «те же круги»: прежние
        /// `rounds.csv`/`forms.csv` сняты при `GTC`, и их воспроизводит
        /// `--no-post-only` (F4).
        post_only: bool,
        /// Трейл-тейк: откат от лучшей цены «в пользу позиции», bps, при
        /// котором выходим по рынку. `0` — трейл выключен, работает
        /// фиксированный `take_px` (решение владельца 2026-09-13: тянуть
        /// прибыль дальше 1:1).
        trail_bps: f64,
        /// Прибыль от входа, после которой трейл включается, bps. До неё
        /// работает только стоп — иначе трейл выбивал бы на первом шуме.
        trail_activate_bps: f64,
        /// Вход лестницей (решение владельца 2026-09-13): сколько лимитов
        /// ставить вместо одного. `1` — прежнее поведение.
        grid_legs: u8,
        /// Шаг лестницы в цене (не в тиках: тик знает вызывающий, у стратегии
        /// его нет). Первая нога — `entry_px`, каждая следующая дальше от
        /// плотности, в сторону рынка.
        grid_step_px: f64,
        /// Лестница входа формы F6 (В-73): ноги — целые тики и доли позиции,
        /// `EntryLadder::NONE` (`n == 0`) — прежний вход по `entry_px` и
        /// `grid_*` (гейт «те же круги»). Ноги заданы **абсолютными тиками**,
        /// а не шагом: форма `ladder<N>x<from>..<to>[w<k>]` даёт разные цены на
        /// одном расстоянии (округление вверх до тика), совпавшие тики
        /// складываются в одну ногу, а доля нижней ноги может быть вдвое
        /// больше — шагом и числом ног это не выразить.
        ladder: EntryLadder,
        /// E7 (владелец 19.09: «позиция одна за раз, но может быть дробной»):
        /// доля позиции, закрываемая тейком `take_px`. `1.0` — весь остаток
        /// (как было); `0.5` — половина, остаток бежит дальше до стопа,
        /// дедлайна, трейла или съедания. Срабатывает один раз.
        take_frac: f64,
        /// E5/E7 по чужим ботам (`density-bots-2026-09-19.md`, их дефолты):
        /// съедание плотности уровня от **максимума с входа**, %, при котором
        /// закрывается `eaten_half_frac` позиции по рынку. `0` — выключено.
        eaten_half_pct: f64,
        /// Съедание, %, при котором закрывается **весь** остаток по рынку.
        /// `0` — выключено.
        eaten_all_pct: f64,
        /// Доля позиции на первом пороге съедания (у ботов — 50 %).
        eaten_half_frac: f64,
        /// Размер плотности уровня в момент сигнала, в единицах крейта (лоты ×
        /// шаг лота) — стартовый максимум для съедания. `0` — пороги съедания
        /// не работают (размера нет).
        level_qty: f64,
        /// Шаг лота инструмента в единицах крейта: дробный выход округляется
        /// **вниз** до кратного шага; если получился ноль — выходим целиком.
        lot_qty: f64,
        /// F7 (Б-75): выход «съели» — накопленные сделки в стену ≥ X % от
        /// размера стены на входе. `0` — выключено. Вход в сетку как `eat<X>`.
        exit_eat_pct: f64,
        /// F7 (Б-75): выход «сняли» — размер стены упал ниже (1 − W %) от
        /// размера на входе, И сделками съедено < половины падения. `0` —
        /// выключено. Вход в сетку как `gone<W>`.
        exit_gone_pct: f64,
        /// Трейл после снятия стены (владелец 2026-09-23: «если стену сняли и мы в позиции, то
        /// трейл»): при сработавшем `gone<W>` позиция не закрывается сразу, а ведётся трейлом —
        /// выход по рынку, когда цена откатилась от лучшей **после снятия** на `gone_trail_bps`
        /// (bps от входа). Снятие — защёлка: вернувшаяся стена трейл не выключает. `0` — выход
        /// сразу, как в F7. Вход в сетку как `gone<W>tr<T>`.
        gone_trail_bps: f64,
        /// Безубыток после снятия стены (владелец 2026-09-23: «снятие — стоп в ноль, дальше базовый
        /// трейлинг»): `1` — мягкий (`gone<W>be`): стоп переносится в безубыток (вход плюс круг
        /// комиссий), как только после снятия цена у безубытка или лучше; `2` — жёсткий
        /// (`gone<W>bex`): то же, но если на снятии позиция хуже безубытка — выход по рынку сразу.
        /// `0` — выключено. Базовый трейл плана работает как обычно.
        gone_be: u8,
    },
}

