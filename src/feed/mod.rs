//! `Feed` — единый поток событий (`ARCHITECTURE.md` A5): один трейт, две
//! реализации — из бинлога (`replay::ReplayFeed`, поверх `binlog::Reader`) и
//! с сокета (`live::LiveFeed`, поверх `bybit::conn::Transport`). Вызывающий
//! код — рекордер `lob session` (таск 04) и, в фазе 2, стратегия таска 15 —
//! держит `&mut dyn Feed` и не знает, откуда идут события: ветки `if live`
//! нет нигде выше этого модуля (интерфейсы, «Из брифа, дословно»).
//!
//! Оба источника размечены одним и тем же типом `Event`. `symbol` — индекс
//! инструмента в пуле сессии (`u8`, не `String`): тег на каждое событие не
//! имеет права аллоцировать, а `String` пришлось бы клонировать на каждое
//! сообщение потока — ровно та аллокация на событие, которую гейт GC считает
//! счётчиком (`interfaces.md`, запрет 1). Кто такой инструмент под этим
//! индексом — знает вызывающий код (он же строил пул и раздавал индексы),
//! здесь это не нужно.
//!
//! `Gap` — кадр, который источник потерял: не разобрался, разрыв `u`,
//! книга пересеклась, сокет переподключился. Поток продолжается следующим
//! событием — сессия теряет кадр, а не сессию целиком (критерий приёмки
//! таска 04). Вызывающий код решает, что делать с этим сигналом (строка в
//! `gaps.csv`, как у `commands::record`), сам `Feed` не пишет файлов и не
//! принимает решений.

pub mod live;
pub mod replay;

/// Один шаг единого потока.
#[derive(Debug, Clone, PartialEq)]
pub enum Event {
    /// Разобранное сообщение потока: обновление книги или сделка одного
    /// инструмента пула. `local_ts_ns` — метка «сразу после `recv`, до
    /// разбора» (`H12`) в живом режиме; в реплее — метка, под которой кадр
    /// лёг в бинлог при записи (то же поле `Record::local_ts_ns`).
    Market {
        symbol: u16,
        local_ts_ns: i64,
        /// Длительность разбора одного сырого кадра в наносекундах —
        /// суббюджет «разбор» `PLAN.md` 3.1 (`p99 < 200 мкс`, таск 04).
        /// `Some` в живом режиме (`live::LiveFeed`, метка через тот же
        /// `Clock`, что и `local_ts_ns`, сразу после `bybit::ws::
        /// parse_message` в `bybit::conn::Connection::handle_raw`); `None`
        /// в реплее (`replay::ReplayFeed`) — там нет стадии разбора кадра
        /// с сокета, печатать здесь ноль означало бы измеренное там, где
        /// ничего не измерялось (правило 1 `interfaces.md`: изобретённое
        /// число запрещено).
        parse_latency_ns: Option<i64>,
        payload: crate::bybit::ws::Event,
    },
    /// Кадр потерян. `detail` — то же, что легло бы строкой `gaps.csv`;
    /// `kind` — причина по классам (таск 25): вызывающий считает
    /// переподключения и ресинки за прогон числом, а не разбором строки.
    /// `depth` — поток стакана, которого потеря касается (T45), если она его
    /// касается: `Some(200)` у разрыва `u` глубокого потока, `Some(50)` — у
    /// быстрого, `None` у всего, что потоку не принадлежит (разрыв сокета
    /// роняет оба потока сразу, неразобранный кадр и чужой маршрут — тоже
    /// ничей). По этому полю вызывающий сбрасывает доверие и считает разрывы
    /// **раздельно по потокам** — разрыв в одном не имеет права выглядеть
    /// разрывом в другом.
    Gap {
        symbol: u16,
        local_ts_ns: i64,
        kind: GapKind,
        depth: Option<u32>,
        /// Тишина на момент этого события, наносекунды — только у
        /// `GapKind::MarketSilence` (`bybit::conn::ConnEvent::MarketSilence`),
        /// `None` у остальных причин: они не измеряют длительность, а этот
        /// класс — только её и несёт. Растёт от события к событию внутри
        /// одного эпизода (см. `first_of_episode`) — читатель, которому нужен
        /// максимум эпизода, а не первое срабатывание, берёт последнее
        /// значение перед тем, как эпизод кончится.
        silence_ns: Option<i64>,
        /// Только у `GapKind::MarketSilence`: `true` — первое превышение
        /// порога этого эпизода (по нему считается `session.json.
        /// silence_episodes`), `false` — повторное событие того же ещё не
        /// кончившегося эпизода (только обновляет `silence_max_ns`, `stderr`
        /// уже отпечатал предупреждение на первом). Всегда `false` у прочих
        /// причин — поле для них не имеет смысла, как `first_of_socket` не
        /// имеет смысла вне `Disconnected`.
        first_of_episode: bool,
        /// Причина структурно, не строкой (ремонт W2, ревью 23.09): `live::
        /// LiveFeed::next_event` раньше собирала `String` через `format!`/
        /// `to_string()` на каждый `Gap`, включая `Unrouted`/`MarketSilence`,
        /// чью деталь никто не читает (`commands::lob::session` уходит из
        /// ветки `continue`, не тронув поле) — аллокация на потоке решений
        /// без потребителя, запрет 1 `interfaces.md`. Строку собирает
        /// писатель `gaps.csv` (`Display`, ниже) ровно там, где решено, что
        /// строка действительно нужна.
        detail: GapDetail,
    },
    /// Тик таймера источника (таск 25): живой `Feed` шлёт его раз в
    /// `tick` (`live::LiveFeed::spawn_with_ticks`), даже когда рынок и сеть
    /// молчат — единственный способ дать вызывающему периодический сброс
    /// кадра и проверку дедлайна «по таймеру рантайма, не по приходу
    /// события». Реплей тика не шлёт: у бинлога нет своего настенного
    /// времени. `local_ts_ns` — тот же `Clock`, что метит `Market`.
    Tick { local_ts_ns: i64 },
}

/// Класс потерянного кадра — один в один варианты `bybit::conn::ConnEvent`,
/// кроме `Message`. `Disconnected` — переподключение транспорта;
/// `SequenceGap`/`BookInvariant` — книга источника ушла на ресинк снапшотом.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GapKind {
    ParseFailed,
    SequenceGap,
    BookInvariant,
    /// Разрыв сокета, первый инструмент веера — считается один раз на
    /// сокет (`session.json.reconnects`).
    Disconnected,
    /// Тот же разрыв, остальные инструменты того же сокета (таск 28):
    /// своя строка `gaps.csv` и свой сброс `synced` у каждого, но
    /// переподключение уже посчитано.
    DisconnectedSameSocket,
    /// Рыночный кадр, чей топик не сопоставлен ни одному инструменту
    /// сокета (`bybit::conn::ConnEvent::Unrouted`): чьи это данные —
    /// неизвестно, поэтому ни строки `gaps.csv`, ни сброса книги, только
    /// счётчик `session.json.unrouted`.
    Unrouted,
    /// `connect()` не удался: сокет не открылся вовсе (`bybit::conn::
    /// ConnEvent::ConnectFailed`). Отдельный класс, а не `Disconnected`,
    /// ровно потому, что раньше отказ рукопожатия не давал **ни строки
    /// `gaps.csv`, ни счётчика** — устойчивый 403/429 выглядел как вечно
    /// тихий ретрай (аудит K1, 2026-09-17). Строка на каждый инструмент
    /// сокета, как у разрыва: в `gaps.csv` символ — колонка.
    ConnectFailed,
    /// Биржа отказала в подписке на топик инструмента (A8.3, 2026-09-18,
    /// `bybit::conn::ConnEvent::SubscribeFailed`): данных по инструменту не
    /// будет вовсе, пока он в пуле. Отдельный класс, а не `ParseFailed` и не
    /// `Unrouted`: кадр даже не пришёл — не согласован сам топик, и это
    /// относится к инструменту, а не к сокету. Шов покрытия (В-59): у
    /// инструмента нет данных, но по обе стороны записи честные; считается,
    /// сутки не роняет.
    SubscribeFailed,
    /// Молчание рынка (`bybit::conn::ConnEvent::MarketSilence`, V5, доработка
    /// 2026-09-24): дольше `recv_timeout` нет `Book`/`Trade`, но транспорт
    /// жив — решение владельца 24.09 не рвать соединение по тишине
    /// неликвидной монеты. Не потеря кадра и не шов покрытия — строки
    /// `gaps.csv` не даёт (как `Unrouted`), только счётчик эпизодов и
    /// максимум длительности в `session.json` (`Event::Gap::silence_ns`).
    MarketSilence,
}

/// Деталь `Event::Gap` — данные, а не готовый текст (ремонт W2, ревью 23.09):
/// `live::LiveFeed::next_event` собирает эти варианты из полей `bybit::conn::
/// ConnEvent` напрямую, без `format!`/`to_string()` на потоке решений (запрет
/// 1). Текст собирает читатель через `Display` — тот же самый, байт в байт,
/// что раньше строился в `next_event`: писатель `gaps.csv` (`commands::lob::
/// session`) зовёт его ровно там, где решено, что строка для журнала
/// действительно нужна (не для `Unrouted`/`MarketSilence` — их деталь
/// читатель не разворачивает вовсе, см. `Event::Gap::detail`).
#[derive(Debug, Clone, PartialEq)]
pub enum GapDetail {
    /// Кадр не разобрался — исходная ошибка разбора (`bybit::ws::ParseError`).
    ParseFailed(crate::bybit::ws::ParseError),
    /// Разрыв `u` потока `.depth`: ждали `expected`, пришло `got`.
    SequenceGap { depth: u32, expected: u64, got: u64 },
    /// Инвариант книги потока `.depth` нарушен (`book::ApplyError` — не
    /// только `SequenceGap`: `PriceNotOnTick`/`QtyNotOnStep`/`Crossed`).
    BookInvariant {
        depth: u32,
        err: crate::book::ApplyError,
    },
    /// Транспорт переподключился — шов покрытия (один текст для
    /// `GapKind::Disconnected` и его копий `DisconnectedSameSocket`, как и
    /// раньше: `bybit::conn::ConnEvent::Disconnected` несёт только
    /// `first_of_socket`, деталь от него не зависит).
    Disconnected,
    /// `connect()` не удался: `http_status` — код рукопожатия, если биржа
    /// отказала им (`None` — обрыв/TLS/DNS), `attempt` — номер попытки.
    ConnectFailed {
        attempt: u32,
        http_status: Option<u16>,
        err: String,
    },
    /// Топик кадра не сопоставлен ни одному инструменту сокета — деталь не
    /// читается никем (`commands::lob::session` уходит из `continue` раньше),
    /// вариант нужен только для типа поля.
    Unrouted,
    /// Биржа отказала в подписке: `topic` — из `ret_msg`, если он там назван,
    /// `ret_msg` — как есть.
    SubscribeFailed {
        topic: Option<String>,
        ret_msg: String,
    },
    /// ОС-поток шарда ввода-вывода завершился (V12) — его инструменты больше
    /// не получают данных.
    ShardDied,
    /// Молчание рынка живо `silence_ns` — деталь не читается никем
    /// (`commands::lob::session` считает счётчик и максимум и уходит из
    /// `continue`, строки `gaps.csv` тишина не даёт), вариант несёт число на
    /// случай, если это когда-нибудь понадобится другому читателю.
    MarketSilence { silence_ns: i64 },
}

impl std::fmt::Display for GapDetail {
    /// Byte-for-byte те же строки, что раньше строил `format!`/`to_string()`
    /// внутри `live::LiveFeed::next_event` — `gaps.csv` не имеет права
    /// измениться этим ремонтом.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ParseFailed(err) => write!(f, "кадр не разобрался: {err:?}"),
            Self::SequenceGap {
                depth,
                expected,
                got,
            } => write!(
                f,
                "разрыв u потока .{depth}: ждали {expected}, пришло {got} — ресинк снапшотом"
            ),
            Self::BookInvariant { depth, err } => {
                write!(f, "книга потока .{depth} нарушена: {err:?} — ресинк снапшотом")
            }
            Self::Disconnected => f.write_str("транспорт переподключился — шов покрытия"),
            Self::ConnectFailed {
                attempt,
                http_status,
                err,
            } => match http_status {
                Some(status) => write!(
                    f,
                    "connect() отклонён биржей: HTTP {status} — {err} (попытка {attempt})"
                ),
                None => write!(f, "connect() не удался: {err} (попытка {attempt})"),
            },
            Self::Unrouted => f.write_str("топик кадра не сопоставлен ни одному инструменту сокета"),
            Self::SubscribeFailed { topic, ret_msg } => match topic {
                Some(topic) => write!(f, "подписка не состоялась: {topic} — {ret_msg}"),
                None => write!(f, "подписка не состоялась: {ret_msg}"),
            },
            Self::ShardDied => f.write_str(
                "ОС-поток шарда ввода-вывода завершился — его инструменты больше не получают данных",
            ),
            Self::MarketSilence { silence_ns } => write!(
                f,
                "рыночных событий (Book/Trade) нет {silence_ns} нс — соединение живо, не рвётся"
            ),
        }
    }
}

/// A5: итератор, а не колбэк. Одна и та же сигнатура обслуживает и
/// рекордер (таск 04), и, без единой правки, стратегию `on_event` (таск 15).
pub trait Feed {
    fn next_event(&mut self) -> Option<Event>;
}

/// Расширение пула на ходу (таск 34, R89: «добавлять на запись без
/// перезапуска») и снятие с записи (A8.1, 2026-09-17). Отдельный трейт, не
/// метод `Feed`: сам поток событий (`next_event`) не меняется, и стратегия
/// `on_event` таска 15 его не знает. Индексы новых инструментов
/// **продолжают** нумерацию пула — `Event::*::symbol` первого добавленного
/// равен прежней длине пула, — поэтому вызывающий код обязан класть свои
/// состояния (`SymbolState` сессии) в том же порядке и той же партией, иначе
/// кадр уйдёт в чужой файл. Живые подписки не трогаются: новая партия —
/// новые соединения.
/// Реплей (`replay::ReplayFeed`) ни того, ни другого не умеет — бинлог уже
/// записан; он возвращает `live::LayoutError::StaticSource`, а не молчаливый
/// `Ok`.
pub trait DynamicPool {
    fn add(&mut self, members: Vec<live::PoolMember>) -> Result<Vec<u16>, live::LayoutError>;

    /// Снятие с записи на ходу (A8.1): перечисленные индексы уходят из пула,
    /// источник обязан перестать слать их события. Индексы **не
    /// переиспользуются** — ни этим вызовом, ни последующим `add`: история
    /// остаётся у вызывающего (`SymbolState` с закрытыми писателями), а
    /// вернувшийся в пул символ получает новый индекс, как новый. Ошибка —
    /// состав прежний: вызывающий ничего не снимает.
    ///
    /// Возвращает индексы **соседей**, чей сокет пришлось пересобрать
    /// (A8.1b, 2026-09-18): у них между остановкой старого соединения и
    /// снапшотом нового данных нет — это шов покрытия, и вызывающий обязан
    /// сделать его видимым (строка `gaps.csv` на каждый). Пустой список —
    /// снятие не задело никого.
    fn remove(&mut self, symbols: &[u16]) -> Result<Vec<u16>, live::LayoutError>;
}
