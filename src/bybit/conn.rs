//! Живое подключение: подписки, ресинк, local_ts на возврате из recv.
//!
//! `ws.rs` — только разбор, без сокета и без времени (его же собственный
//! заголовок это и говорит). Этот файл — обратное: сокет, часы, переподключение
//! и решение о ресинке. Разделение ровно по этой границе даёт то, что требует
//! задача: сокет спрятан за трейтом `Transport`, и вся логика реконнекта и
//! ресинка гоняется в тестах на сценарном транспорте, без единого обращения
//! к сети — а разбор байт в структуры уже проверен отдельно, в `ws.rs`.
//!
//! **`local_ts` ставится сразу по возврату из `recv`, до разбора** (`H12`,
//! `ASSUMPTION H12`) — метка живёт в этом файле и нигде больше, ровно потому
//! что только здесь есть точка «сразу после `recv`».
//!
//! Книга (`crate::book::Book`) здесь тоже применяется — не для стратегии (та
//! строит свою из событий, которые уходят наружу через канал), а чтобы решить,
//! когда слать `orderbook.<depth>` заново: только у сокета есть право написать
//! в него, поэтому решение "разрыв → ресинк" обязано жить рядом с сокетом, а не
//! на другом конце канала, откуда до сокета не дотянуться. С T45 книг на
//! инструмент **две** — по одной на поток глубины (`SUBSCRIBED_DEPTHS`): `u` у
//! `.50` и `.200` свои, и разрыв одного потока не имеет права ни считаться
//! разрывом другого, ни глушить его ресинк.
//!
//! **Отступление от `ARCHITECTURE.md`.** Черновик архитектуры называет канал
//! до потока решений «crossbeam»; в `Cargo.toml` крейта `crossbeam-channel` нет
//! и добавлять его не в этом файле (это чужой файл). Используется
//! `tokio::sync::mpsc`: у него `Receiver::blocking_recv()` устроен буквально
//! для моста «асинхронный производитель — синхронный потребитель», то есть для
//! ровно того же разделения, которое описывает A3 (тут — `tokio`, там — один
//! поток без блокировок). Смысл решения не меняется, меняется имя канала.

use crate::book::{ApplyError, Book};
use crate::bybit::ws::{self, Event};
use std::future::Future;
use std::time::{Duration, SystemTime, UNIX_EPOCH};
use tokio::sync::mpsc;
use tokio::time::MissedTickBehavior;
use tokio_tungstenite::tungstenite::Utf8Bytes;

/// Глубина стакана из шага 0.1 плана: буквально `orderbook.50.<symbol>`. Не
/// параметр — это не измеренное число и не порог, а часть протокола, которую
/// задаёт сам план, дословно.
pub(crate) const ORDERBOOK_DEPTH: u32 = 50;

/// Глубина второго, глубокого потока: `orderbook.200.<symbol>` (T45). Не
/// изобретённое число: 200 — имя топика из документации Bybit v5
/// (`https://bybit-exchange.github.io/docs/v5/websocket/public/orderbook`,
/// «Level 200`) и одновременно то, что уже замерено живым A/B
/// (`docs/findings/depth-200-ab-2026-09-15.md`): `.200` публикуется раз в
/// 100 мс против 20 мс у `.50`, и он же дешевле по байтам и процессору
/// (−19 % байт, −44 % CPU на том же пуле). Тот же факт протокола, что и
/// `ORDERBOOK_DEPTH`, — поэтому константа рядом с ним, а не параметр.
pub(crate) const ORDERBOOK_DEEP_DEPTH: u32 = 200;

/// Потоки стакана коллектора сессии (T45), в порядке слотов
/// `session::SymbolState::streams`: быстрый `.50` первым, глубокий `.200`
/// вторым. Один сокет несёт оба потока по каждому инструменту (`feed::live`
/// передаёт этот набор в `PoolConnConfig::depths`): порядок между потоками
/// задаёт биржа полем `seq` («cross sequence»), а не наши соединения, —
/// разнеси мы потоки по сокетам, этот порядок пришлось бы восстанавливать
/// самим. `FAST_STREAM`/`DEEP_STREAM` — слоты этих двух глубин.
pub(crate) const SUBSCRIBED_DEPTHS: [u32; 2] = [ORDERBOOK_DEPTH, ORDERBOOK_DEEP_DEPTH];

/// Слот быстрого потока: ровно сегодняшнее поведение, файл лежит в корне
/// сессии (`<root>/<SYMBOL>-<день>.binlog`).
pub(crate) const FAST_STREAM: usize = 0;

/// Слот глубокого потока: свой файл в подкаталоге
/// (`<root>/deep/<SYMBOL>-<день>.binlog`), чтобы резолверы корня его не
/// видели.
pub(crate) const DEEP_STREAM: usize = 1;

/// Источник времени для `local_ts`. Трейт, а не прямой вызов часов — по той же
/// причине, что `ARCHITECTURE.md` A2 даёт этому пути (рекордер, без `Bot`
/// крейта) собственный `Clock`: там, где нет `Bot::current_timestamp()`, нужен
/// свой источник, и здесь он именно им и является. Единственная причина, по
/// которой это трейт, а не голый `SystemTime::now()`, — тесты: без него нельзя
/// было бы отличить «метка стоит до разбора» от «после», не устраивая гонку с
/// настоящими часами внутри теста.
pub trait Clock: Send {
    /// Наносекунды от эпохи Unix. Наносекунды — потому что `exch_ts` (`cts`/`T`
    /// биржи) идёт в миллисекундах, и сравнение `exch_ts <= local_ts` (шаг 0.5,
    /// GC) — это умножение на 10⁶ на стороне вызывающего кода, а не отдельная
    /// единица времени, которую каждый потребитель конвертирует по-своему.
    fn now_ns(&self) -> i64;
}

/// Системные часы. Единственная реализация, которую видит боевой код и,
/// поскольку сети в тестах нет, единственная, которую видят и тесты этого
/// файла — часы не сеть, дважды звонить бирже не нужно, чтобы их вызвать.
///
/// `SystemTime`, не `Instant`: `local_ts` обязан быть сравним с временем биржи
/// (эпоха Unix), а `Instant` — непрозрачная точка отсчёта без неё. Плата за
/// это в том, что `SystemTime` не гарантированно монотонны при скачке
/// NTP-коррекции — и это ровно то, что независимо и постоянно проверяет
/// `lob clock` (шаг 0.5: `|offset| < 5 мс`, без скачков `> 1 мс`), а не
/// свойство, которое обязан восстанавливать этот файл.
#[derive(Debug, Default, Clone, Copy)]
pub struct SystemClock;

impl Clock for SystemClock {
    fn now_ns(&self) -> i64 {
        Self::ns_since_epoch(SystemTime::now())
    }
}

impl SystemClock {
    /// Вынесено из `now_ns` отдельной чистой функцией ровно ради тестируемости
    /// отката: настоящие часы хоста «раньше эпохи» не устроить, а `SystemTime`
    /// раньше эпохи сконструировать можно (`UNIX_EPOCH - Duration::from_secs(..)`)
    /// — тест дёргает эту функцию таким временем напрямую, не полагаясь на
    /// сломанные часы настоящего хоста.
    ///
    /// Раньше здесь стоял `.expect(...)`: мёртвая RTC или несконфигурированная
    /// VM отдают `SystemTime::now() < UNIX_EPOCH`, и это падало на первом же
    /// фрейме — рекордер, рассчитанный на недели без присмотра, гас в первую
    /// же секунду работы. Панике здесь взяться неоткуда: `Err` несёт `Duration`
    /// ровно той величины, на которую часы отстают от эпохи, и это превращается
    /// в отрицательную метку, а не в аварийную остановку. Число будет заведомо
    /// неверным, но обнаружить и сообщить о сломанных часах хоста — работа
    /// `lob clock` (шаг 0.5, `ARCHITECTURE.md`), а не горячего пути `recv`.
    /// Касты точные для дат до 2262 года (`as_nanos` ~1.7e18 сейчас против
    /// `i64::MAX` ~9.2e18).
    #[allow(clippy::cast_possible_truncation)]
    fn ns_since_epoch(now: SystemTime) -> i64 {
        match now.duration_since(UNIX_EPOCH) {
            // `as_nanos()` — `u128`; для дат до 2262 года влезает в `i64` без
            // обрезки, а дальше этот код проживёт свою жизнь много раз.
            Ok(since_epoch) => since_epoch.as_nanos() as i64,
            Err(err) => -(err.duration().as_nanos() as i64),
        }
    }
}

/// Один фрейм транспорта. `Text` — единственный вид, который несёт протокол
/// Bybit; `Closed` — конец сессии, независимо от того, кто её закрыл, сервер
/// или сеть: вызывающему коду обе причины важны одинаково — сокет мёртв,
/// нужно переподключаться.
///
/// `Text` несёт `Utf8Bytes` (тип `tungstenite::Message::Text`), не `String`:
/// `WsTransport::recv` отдаёт его как есть, без лишней копии валидных байт в
/// новую строку — `ws::parse_message_into` берёт `&str` через `Deref`,
/// разбору всё равно, чем владеет байтовое представление.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Frame {
    Text(Utf8Bytes),
    Closed,
}

/// Ошибка транспорта. Вариантов два, и они различаются не текстом, а
/// реакцией: `Io` — обрыв (таймаут, разрыв TCP, ошибка TLS), ответ один:
/// переподключение с бэкоффом; `Http` — **биржа отказала в рукопожатии**
/// (`tungstenite::Error::Http`), и статус тут несущая информация: `403`
/// (гео-блок с этого IP) и `429` (рейт-лимит) требуют не долбить адрес, а
/// разбираться, тогда как текст ошибки у них почти одинаковый (аудит K1).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TransportError {
    Io(String),
    Http { status: u16, msg: String },
}

impl TransportError {
    /// HTTP-статус отказа рукопожатия, если отказ был именно таким.
    pub fn http_status(&self) -> Option<u16> {
        match self {
            Self::Http { status, .. } => Some(*status),
            Self::Io(_) => None,
        }
    }

    pub fn message(&self) -> &str {
        match self {
            Self::Io(msg) | Self::Http { msg, .. } => msg,
        }
    }
}

impl std::fmt::Display for TransportError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Io(msg) => write!(f, "{msg}"),
            Self::Http { status, msg } => write!(f, "HTTP {status}: {msg}"),
        }
    }
}

/// Сокет за трейтом — единственное, что делает эту логику тестируемой без
/// сети (design constraint задачи). Продовая реализация — `WsTransport` поверх
/// `tokio-tungstenite`; в тестах — целиком в памяти сценарный `ScriptedTransport`.
///
/// Методы возвращают `impl Future<..> + Send`, а не `async fn`: обычный
/// `async fn` в трейте не даёт задать `+ Send` на возвращаемом future, а без
/// него `Connection::run` нельзя было бы передать в `tokio::spawn` (там это
/// нужно тестам — сессия крутится в фоне, пока тест читает из канала).
pub trait Transport: Send {
    fn send_text(&mut self, msg: String)
        -> impl Future<Output = Result<(), TransportError>> + Send;
    fn recv(&mut self) -> impl Future<Output = Result<Frame, TransportError>> + Send;
}

/// Открывает новый транспорт. Отдельно от `Transport`: переподключение создаёт
/// новый сокет, а не чинит старый — TCP-соединение, разорванное сетью, чинить
/// нечем, и попытка переиспользовать `Transport` после `Closed` не имеет
/// смысла ни для реального сокета, ни для сценарного.
pub trait TransportConnector: Send {
    type Transport: Transport;
    fn connect(&mut self) -> impl Future<Output = Result<Self::Transport, TransportError>> + Send;
}

/// Экспоненциальный бэкофф переподключения. Поля, не константы: интервал
/// переподключения не задан ни в `PLAN.md`, ни протоколом биржи — это наш
/// выбор эксплуатации, и план прямо запрещает изобретать числа в теле кода,
/// а не в параметре, который выставляет вызывающий код.
#[derive(Debug, Clone, Copy)]
pub struct BackoffConfig {
    pub initial: Duration,
    pub max: Duration,
    pub multiplier: u32,
}

impl BackoffConfig {
    /// Задержка перед попыткой номер `attempt` (считая с нуля). Через
    /// `checked_pow`/`checked_mul`, а не `*`: на долгой сессии число попыток
    /// не ограничено ничем, кроме времени, и обычное умножение рано или
    /// поздно переполнило бы `Duration` и запаниковало вместо того, чтобы
    /// просто упереться в `max`.
    fn delay_for_attempt(&self, attempt: u32) -> Duration {
        let scaled = self
            .multiplier
            .checked_pow(attempt)
            .and_then(|factor| self.initial.checked_mul(factor));
        match scaled {
            Some(d) if d < self.max => d,
            _ => self.max,
        }
    }
}

/// Планировщик задержки перед следующей попыткой подключения — то же
/// назначение для бэкоффа, какое `Clock` уже даёт для меток времени:
/// подменяемый источник, без которого тест FIX 2 (счётчик попыток не
/// сбрасывается) не отличить от гонки с настоящими часами. `tokio::time::
/// pause` сюда не подключить без фичи `test-util` в `Cargo.toml`, а она вне
/// зоны этого таска — поэтому подмена собственная, не крейтовая: тестовый
/// `Backoff` не спит по-настоящему вовсе, а лишь записывает запрошенную
/// задержку (`RecordingBackoff`, `mod tests`).
trait Backoff: Send {
    fn wait(&self, dur: Duration) -> impl Future<Output = ()> + Send;
}

/// Продовая реализация — настоящее ожидание, без него `run` вело бы себя
/// иначе, чем сейчас.
struct RealBackoff;

impl Backoff for RealBackoff {
    fn wait(&self, dur: Duration) -> impl Future<Output = ()> + Send {
        tokio::time::sleep(dur)
    }
}

/// Конфигурация одного подключения. Каждое поле — то, что план не задаёт
/// числом и что этот файл не имеет права выдумать: символ и шаги цены/размера
/// приходят из отбора инструмента (шаг 0.4, `instruments.csv`), интервал
/// пинга — из требования протокола Bybit (не из `PLAN.md`), бэкофф — из
/// эксплуатационного решения вызывающего кода.
#[derive(Debug, Clone)]
pub struct ConnConfig {
    pub symbol: String,
    /// Шаг цены в 1e-9 — тот же масштаб, что `book::Book::new` уже требует.
    pub tick_e9: i64,
    /// Шаг количества в 1e-9, тот же смысл.
    pub step_e9: i64,
    /// Bybit требует периодический `{"op":"ping"}`, иначе сервер рвёт
    /// соединение по своему таймауту (документированное поведение биржи,
    /// не число из `PLAN.md` — поэтому параметр, а не константа здесь).
    pub ping_interval: Duration,
    /// Порог молчания — двух разных видов, оба проверяются в ветке пинга
    /// `run_with_backoff` (единственной, что гарантированно срабатывает
    /// каждые `ping_interval` — `timeout(recv_timeout, transport.recv())`
    /// рядом с ней пересоздаётся на каждый виток и почти никогда не успевает
    /// истечь сам, пока хоть что-то отвечает, поэтому настоящая защита от
    /// молчания — здесь, а не там). (1) Ни одного кадра вовсе, даже `pong`
    /// (`last_any_frame_ns`), дольше `recv_timeout` — транспорт действительно
    /// мёртв (TCP мог остаться живым, а данных, включая протокольные, не
    /// будет вовсе), соединение рвётся и переподключается, строка `gaps.csv`
    /// как у обычного разрыва. (2) Кадры (`pong`) идут, а `Book`/`Trade`
    /// (`last_market_ns`) нет дольше `recv_timeout` — решение владельца
    /// 24.09: это нормальная тишина неликвидной монеты, не повод рвать
    /// соединение; только предупреждение в `stderr` (одно на эпизод) и
    /// `ConnEvent::MarketSilence` для счётчика и максимума в `session.json`
    /// (см. `run_with_backoff`). У боевых вызывающих значение — 2 ×
    /// `ping_interval`: пинг уходит каждый интервал, и порог короче этого
    /// удвоения в обоих случаях недостижим без ответа хоть на что-то.
    /// Отдельное поле, а не вывод из `ping_interval` тут же, чтобы тест мог
    /// задать короткий интервал пинга и длинный таймаут независимо.
    pub recv_timeout: Duration,
    pub backoff: BackoffConfig,
}

/// Один инструмент мультиплексированного соединения (таск 28): к символу и
/// его шагам добавлен **глобальный** индекс в пуле вызывающего — тот же
/// `u16`, которым `feed::Event` метит событие. Соединение не знает, как
/// вызывающий раскладывает пул по сокетам, и не имеет права придумывать
/// свою нумерацию: маршрут события — этот индекс, отданный сюда снаружи.
#[derive(Debug, Clone)]
pub struct SymbolSpec {
    pub symbol: String,
    pub tick_e9: i64,
    pub step_e9: i64,
    pub index: u16,
}

/// Конфигурация соединения, несущего топики **многих** инструментов
/// (таск 28). Прежний одно-символьный `ConnConfig` — её частный случай
/// (`From`), поэтому `commands::record` и `commands::lob::pick::measure`
/// не менялись: `Connection::new` принимает оба.
///
/// Почему вообще много символов на сокет: Bybit v5 документирует
/// «Do not build over 500 connections in 5 minutes. This is counted per
/// WebSocket domain» — при одном сокете на инструмент пул в 500
/// инструментов расходует весь пятиминутный бюджет соединений домена
/// одним стартом, и любой шторм переподключений уже не влезает. Предел,
/// который на самом деле ограничивает подписки одного сокета, другой:
/// «For one public connection, you cannot have length of "args" array over
/// 21,000 characters» (`MAX_ARGS_CHARS`), а числа `args` в запросе для
/// Futures нет вовсе («No args limit for Futures and Spread for now»).
#[derive(Debug, Clone)]
pub struct PoolConnConfig {
    pub symbols: Vec<SymbolSpec>,
    /// Потоки стакана, на которые подписывается **это** соединение, в порядке
    /// слотов своего состояния (`Session::books`/`resyncing`): имена топиков
    /// `orderbook.<depth>.<symbol>`. У коллектора сессии (`feed::live`) это
    /// `SUBSCRIBED_DEPTHS` — быстрый `.50` и глубокий `.200` (T45); у
    /// однопоточных вызывающих (`commands::record`, `commands::lob::pick::
    /// measure`, `From<ConnConfig>` ниже) — только быстрый `.50`: их книга и
    /// бинлог одни и потока не различают, а две разные последовательности `u`
    /// в одной книге — это разрыв на каждом втором сообщении.
    pub depths: Vec<u32>,
    /// Bybit требует периодический `{"op":"ping"}`, иначе сервер рвёт
    /// соединение по своему таймауту (документированное поведение биржи,
    /// не число из `PLAN.md` — поэтому параметр, а не константа здесь).
    pub ping_interval: Duration,
    /// Молчание, после которого соединение считается мёртвым (V5,
    /// 2026-09-17) — см. `ConnConfig::recv_timeout`; у боевых вызывающих
    /// 2 × `ping_interval`.
    pub recv_timeout: Duration,
    pub backoff: BackoffConfig,
}

/// Предел суммарной длины массива `args` **одного публичного соединения**
/// Bybit v5, дословно: «For one public connection, you cannot have length
/// of "args" array over 21,000 characters»
/// (`https://bybit-exchange.github.io/docs/v5/ws/connect`, проверено
/// 2026-09-12). Факт протокола, не измеренное и не назначенное число: он и
/// задаёт, сколько инструментов влезает в сокет (`feed::live::
/// plan_connections`).
pub(crate) const MAX_ARGS_CHARS: usize = 21_000;

