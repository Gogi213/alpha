/// Событие, которое соединение отдаёт наружу. Вызывающий код сам решает, что
/// с ним делать (собственную книгу вести, писать в бинлог, считать метрики) —
/// этот файл знает только протокол Bybit и сокет, а не то, что происходит с
/// событием дальше.
#[derive(Debug, Clone, PartialEq)]
pub enum ConnEvent {
    /// Одно событие потока, `local_ts_ns` — метка, поставленная до разбора.
    /// `parsed_ts_ns` — вторая метка через тот же `Clock`, поставленная
    /// сразу после `ws::parse_message` (таск 04, суббюджет «разбор»
    /// `PLAN.md` 3.1: `p99 < 200 мкс`); `parsed_ts_ns - local_ts_ns` —
    /// длительность разбора одного сырого кадра. До этого поля суббюджет
    /// разбора был неизмерим отсюда вовсе — единственная метка стояла до
    /// разбора, и ничего не стояло после (handoff-04-1, ТУПИК 3).
    Message {
        local_ts_ns: i64,
        parsed_ts_ns: i64,
        event: Event,
    },
    /// Сырой фрейм не разобрался. Метка всё равно есть — она берётся до
    /// разбора и не зависит от его исхода; иначе этот вариант доказывал бы,
    /// что `local_ts` ставится после разбора, а не до.
    ParseFailed {
        local_ts_ns: i64,
        err: ws::ParseError,
    },
    /// `book::Book::apply` вернул `SequenceGap`: пропущенное сообщение, книга
    /// этого потока внутри этого файла больше не доверяется. Соединение уже
    /// отправило повторную подписку на `orderbook.<depth>` **этого** потока и
    /// ждёт свежий снапшот; дельты между разрывом и снапшотом наружу не идут
    /// вовсе (см. `handle_raw`). `depth` — признак потока из топика: разрыв
    /// `.200` не должен ни считаться разрывом `.50`, ни глушить его ресинк.
    SequenceGap { depth: u32, expected: u64, got: u64 },
    /// `book::Book::apply` вернул `PriceNotOnTick`, `QtyNotOnStep` или `Crossed` —
    /// любую ошибку `ApplyError`, кроме `SequenceGap`. Реакция внутри файла та
    /// же: ресинк снапшотом (см. `handle_raw`), но раньше эти три варианта не
    /// долетали наружу вовсе — наружу шёл только `SequenceGap`, а `Crossed`
    /// (книга гарантированно испорчена) и `PriceNotOnTick` (смена тик-сайза
    /// биржи посреди записи, `PLAN.md` шаг 0.3) были не видны никому, кто
    /// слушает только `out`. Несёт саму ошибку, а не только текст лога: адресату
    /// нужны числа (`price_e9`/`tick_e9` и т.д.), чтобы отличить смену тика от
    /// пересечения книги, а не только факт «что-то не так». `depth` — поток,
    /// книга которого нарушена (та же роль, что у `SequenceGap`).
    BookInvariantViolated { depth: u32, err: ApplyError },
    /// Сокет закрылся (сервером или сетью). Переподключение уже запущено.
    /// Событие приходит **на каждый инструмент** этого сокета: на
    /// мультиплексированном соединении (таск 28) молчание для остальных
    /// означало бы, что они не сбросят `synced` и продолжат писать дельты
    /// в книгу, которой больше нет. `first_of_socket` отделяет сам разрыв
    /// (его и считает `session.json.reconnects` — один на сокет) от его
    /// копий по инструментам. Выбор «строка `gaps.csv` на инструмент», а не
    /// «одна строка с перечнем»: у `gaps.csv` символ — колонка, и покрытие
    /// инструмента считается по его собственным строкам.
    Disconnected { first_of_socket: bool },
    /// `connect()` не удался: сокет не открылся, подписки не было, данных нет
    /// (аудит K1, 2026-09-17). До этого события отказ рукопожатия не покидал
    /// `Connection::run` — устойчивый `403`/`429` приводил к вечно тихому
    /// ретраю: `gaps.csv` пуст, `reconnects` не растёт, заметить можно было
    /// только по остановке роста бинлога. `attempt` — номер попытки в цикле
    /// переподключения (1 — первая), `http_status` — код рукопожатия, если
    /// биржа отказала именно им (`None` — обрыв/TLS/DNS). Событие, как и
    /// `Disconnected`, уходит на **каждый** инструмент сокета: в `gaps.csv`
    /// символ — колонка.
    ConnectFailed {
        local_ts_ns: i64,
        attempt: u32,
        http_status: Option<u16>,
        err: String,
    },
    /// Рыночный кадр, чей топик не сопоставлен ни одному инструменту этого
    /// сокета (таск 28). Наружу как рынок он пойти не может — приписать его
    /// «индексу сокета» значило бы записать чужой стакан в бинлог первого
    /// инструмента соединения, — но и исчезать молча не вправе: этот
    /// вариант его считает (`session.json.unrouted`). В норме не
    /// встречается: подписки сокета и его список инструментов — одно и то
    /// же множество.
    Unrouted { local_ts_ns: i64 },
    /// Биржа отказала в подписке (A8.3, 2026-09-18): топик не согласован —
    /// символа нет в листинге/переименован, площадка не отдаёт этот поток.
    /// До этого события отказ вообще не покидал `Connection::run`: ответ
    /// `{"success":false,…}` разбирался как «pong и прочее» (`ws::Event::
    /// Other`), и инструмент молча оставался без данных — ни строки
    /// `gaps.csv`, ни счётчика, — что и показал живой прогон с несуществующим
    /// символом. Атрибуция — по топику из ответа (`ws::topic_symbol`), а не по
    /// сокету: биржа отвечает на каждый несогласованный топик отдельно, и
    /// соседи по той же партии подписок живут. Индекс события — инструмент
    /// топика; топик не разрешился — первый инструмент сокета, как у событий
    /// без символа.
    SubscribeFailed {
        local_ts_ns: i64,
        /// Топик из `ret_msg` биржи, если он там назван.
        topic: Option<String>,
        /// `ret_msg` как есть — попадает в деталь строки `gaps.csv`.
        ret_msg: String,
    },
    /// Молчание рынка (`Book`/`Trade`) дольше `recv_timeout`, пока транспорт
    /// отвечает хоть чем-то — не обязательно рынком (V5, доработка
    /// 2026-09-24 — решение владельца 24.09: тишина по неликвидной монете
    /// нормальна, соединение по ней не рвётся). Не разрыв: транспорт жив,
    /// подписка не трогается, книга не сбрасывается — поэтому не
    /// `Disconnected` и в `gaps.csv` строки не даёт (`feed::live` считает его
    /// отдельно, тем же приёмом, что `Unrouted`). Отправляется на каждом тике
    /// пинга, пока эпизод не кончился (следующий `Book`/`Trade`) — иначе
    /// `session.json.silence_max_ns` застыл бы на значении первого
    /// срабатывания (≈`recv_timeout`), а не на фактической длине эпизода, в
    /// том числе ещё идущего на момент записи сводки. `first_of_episode`
    /// отделяет само предупреждение (в `stderr` — одно на эпизод,
    /// `session.json.silence_episodes` считает по нему) от последующих
    /// тихих обновлений максимума того же эпизода — та же роль, что у
    /// `Disconnected::first_of_socket`.
    MarketSilence {
        local_ts_ns: i64,
        silence_ns: i64,
        first_of_episode: bool,
    },
}

/// Куда `Connection::run` отдаёт разобранные события — трейт-шов, а не
/// голый `mpsc::Sender<ConnEvent>` (таск 20, находка профиля пула:
/// `feed::live::LiveFeed` раньше заводил на КАЖДОЕ соединение собственный
/// канал плюс отдельную задачу-таск, чья единственная работа — приклеить
/// индекс инструмента и переслать во второй, общий канал; на восьми
/// соединениях это восемь лишних задач и двойной проход каждого события
/// через `mpsc` на одном ОС-потоке, и замер (`lob session`, `queue_p99_ns`)
/// поймал этот виток дороже самого разбора JSON — `918.6` мкс против
/// `686.0` на живой сессии `data/recording-eco/20260911T182544Z-before`).
/// `impl Future<..> + Send`, не `async fn` в трейте — та же причина, что и у
/// `Transport`/`TransportConnector`/`Backoff` этого файла: обычный `async
/// fn` в трейте не даёт `+ Send` на результате, а без него `Connection::run`
/// нельзя передать в `tokio::spawn`.
/// `symbol_idx` — глобальный индекс инструмента в пуле вызывающего
/// (`SymbolSpec::index`), таск 28: одно соединение несёт топики многих
/// инструментов, и получатель обязан узнать инструмент из самого события,
/// а не из того, какому соединению принадлежит канал. Одно-символьному
/// вызывающему (`commands::record`, `pick::measure`) индекс не нужен — их
/// реализация ниже его игнорирует, `--help` и поведение не изменились.
pub trait ConnSink: Send {
    fn send_event(&self, symbol_idx: u16, ev: ConnEvent) -> impl Future<Output = ()> + Send;
}

/// Прежнее поведение, без изменений: `commands::record`, `commands::lob::
/// pick::measure` и тесты этого файла заводят простой `mpsc::channel::
/// <ConnEvent>` и передают `Sender` в `Connection::run` напрямую — им
/// пересылка не нужна, потребитель уже знает свой единственный символ.
/// Ошибка отправки (получатель закрылся) проглатывается тем же способом,
/// каким её раньше проглатывал каждый отдельный вызов `out.send(..).await`
/// внутри `run_with_backoff`/`handle_raw` — получатель мог закрыться
/// осознанно, это не повод ронять поток ввода-вывода.
impl ConnSink for mpsc::Sender<ConnEvent> {
    async fn send_event(&self, _symbol_idx: u16, ev: ConnEvent) {
        let _ = self.send(ev).await;
    }
}

/// Формат пинга задан протоколом Bybit, а не `PLAN.md`: `{"op":"ping"}` без
/// топика. Не в `ws.rs` — тот файл не мой, и там это было бы разбором
/// входящего, а это исходящее сообщение транспорта, как `sub_orderbook` и
/// `sub_trades`, только для них место уже занято в чужом файле.
fn ping_message() -> String {
    r#"{"op":"ping"}"#.to_string()
}

/// Состояние одной сессии сокета: книга, флаг ресинка и флаг «сессия уже
/// переслала хоть одно сообщение». Собраны в одну структуру и переданы в
/// `handle_raw` одним аргументом — не ради красоты, а потому что порознь
/// список аргументов `handle_raw` перевалил бы за предел, который держит
/// clippy (`too_many_arguments`): все три поля описывают состояние ОДНОЙ
/// сессии одного сокета, а не что-то концептуально разное, так что это ещё и
/// более честная группировка, а не обход линта.
struct Session {
    /// Книга на каждый инструмент соединения **и каждый его поток глубины**,
    /// в порядке `cfg.symbols` и `cfg.depths`: первый индекс — слот маршрута,
    /// второй — слот потока (таск 28 / T45). Предвыделенные `Vec`, индексы —
    /// слоты; ни `HashMap`, ни аллокации на событие. Книги потоков
    /// независимы: `u` у `.50` и `.200` свои, разрыв одного не трогает
    /// другой (замер `docs/findings/depth-200-ab-2026-09-15.md`, «Склейка
    /// потоков»: по каждому потоку — своя книга и своя проверка `u`).
    books: Vec<Vec<Book>>,
    /// Не даёт слать повторную ресинк-подписку на каждую следующую дельту,
    /// пока мы уже ждём снапшот — иначе разрыв на секунду превратился бы в
    /// шторм из сотен подписок в секунду. Флаг **на инструмент и поток**:
    /// ресинк одного символа не должен глушить ресинк соседа по сокету, а
    /// ресинк `.200` — ресинк `.50` того же символа (T45).
    resyncing: Vec<Vec<bool>>,
    /// Ставится в `true`, как только сессия переслала наружу хоть одно
    /// `ConnEvent::Message`. Решает судьбу счётчика бэкоффа в `run` — сервер,
    /// который принимает рукопожатие и тут же рвёт соединение, не должен
    /// казаться «здоровым» одним лишь фактом успешной подписки.
    productive: bool,
}

/// Одно подключение: инструменты, состояние ресинка и сокет за
/// `TransportConnector`.
pub struct Connection<C: TransportConnector> {
    connector: C,
    cfg: PoolConnConfig,
    /// Маршрут «символ топика → слот в `cfg.symbols`»: отсортированный по
    /// имени массив, поиск двоичный (`log2 500 ≈ 9` сравнений). Не
    /// `HashMap` — запрет 7 горячего пути; строится один раз в `new`, на
    /// событие не аллоцирует.
    route: Vec<(Box<str>, u16)>,
}

/// Метки и маршрут одного сырого кадра — три значения, которые
/// `handle_raw` получает от `run`. Отдельной структурой, а не тремя
/// аргументами: список аргументов `handle_raw` иначе перевалил бы за
/// предел clippy (`too_many_arguments`), а все три описывают ровно один
/// кадр.
struct FrameMeta<'a> {
    local_ts_ns: i64,
    parsed_ts_ns: i64,
    /// Символ из топика (`ws::parse_message_into`). `None` — топик без
    /// символа (`pong`, ответ на подписку) или неразобранное имя.
    symbol: Option<&'a str>,
}

/// Заимствованный вид маршрута одного соединения: инструменты,
/// отсортированная таблица имён и потоки глубины этого соединения.
/// Отдельным типом, а не методами на `Connection`, ровно по одной причине:
/// `&Connection<C>`, живущий поперёк `.await`, требовал бы `C: Sync` от
/// каждого транспорта — а маршрут не зависит от транспорта вовсе и `Sync`
/// сам по себе.
#[derive(Clone, Copy)]
struct Route<'a> {
    symbols: &'a [SymbolSpec],
    table: &'a [(Box<str>, u16)],
    /// Потоки глубины соединения (`PoolConnConfig::depths`): слот потока —
    /// позиция глубины в этом списке.
    depths: &'a [u32],
}

impl Route<'_> {
    /// Слот инструмента по имени из топика. `None` — топик не наш
    /// (`pong`, подтверждение подписки) или символ этому сокету не
    /// принадлежит (биржа прислала чужое — не наше дело чинить).
    fn slot_of(&self, symbol: &str) -> Option<usize> {
        self.table
            .binary_search_by(|probe| probe.0.as_ref().cmp(symbol))
            .ok()
            .map(|i| usize::from(self.table[i].1))
    }

    /// Слот потока по глубине из топика. Линейный поиск по списку потоков
    /// соединения (у коллектора их два) — ни `HashMap`, ни аллокаций на
    /// событие (запрет 7). `None` — глубина не нашего соединения.
    fn stream_of(&self, depth: u32) -> Option<usize> {
        self.depths.iter().position(|&d| d == depth)
    }

    /// Глобальный индекс инструмента для событий без символа (`pong`,
    /// `Disconnected`, неразобранный кадр): первый инструмент соединения.
    /// Придумывать «индекс никого» нельзя — `feed::Event` метит символом
    /// каждое событие; а такие события несут не рынок, а состояние сокета,
    /// и по сокету они и атрибутируются.
    fn socket_index(&self) -> u16 {
        self.symbols.first().map_or(0, |s| s.index)
    }

    /// Разрыв сокета — событие каждого его инструмента (см. doc
    /// `ConnEvent::Disconnected`).
    async fn broadcast_disconnected<O: ConnSink>(&self, out: &O) {
        for (i, spec) in self.symbols.iter().enumerate() {
            out.send_event(
                spec.index,
                ConnEvent::Disconnected {
                    first_of_socket: i == 0,
                },
            )
            .await;
        }
    }

    /// Отказ `connect()` — событие каждого инструмента сокета (см. doc
    /// `ConnEvent::ConnectFailed`). `first_of_socket` тут не нужен: считать
    /// «одно переподключение на сокет» нечего, сокет не открылся, поэтому
    /// строка `gaps.csv` и счётчик — по инструментам, у каждого свои.
    async fn broadcast_connect_failed<O: ConnSink>(
        &self,
        out: &O,
        local_ts_ns: i64,
        attempt: u32,
        err: &TransportError,
    ) {
        for spec in self.symbols.iter() {
            out.send_event(
                spec.index,
                ConnEvent::ConnectFailed {
                    local_ts_ns,
                    attempt,
                    http_status: err.http_status(),
                    err: err.message().to_string(),
                },
            )
            .await;
        }
    }
}

impl<C: TransportConnector> Connection<C> {
    pub fn new(connector: C, cfg: impl Into<PoolConnConfig>) -> Self {
        let cfg: PoolConnConfig = cfg.into();
        let mut route: Vec<(Box<str>, u16)> = cfg
            .symbols
            .iter()
            .enumerate()
            .map(|(slot, s)| {
                (
                    s.symbol.as_str().into(),
                    u16::try_from(slot).unwrap_or(u16::MAX),
                )
            })
            .collect();
        route.sort_by(|a, b| a.0.cmp(&b.0));
        Self {
            connector,
            cfg,
            route,
        }
    }

    fn route(&self) -> Route<'_> {
        Route {
            symbols: &self.cfg.symbols,
            table: &self.route,
            depths: &self.cfg.depths,
        }
    }

    /// Основной цикл: подключение → две подписки → чтение с пересылкой в
    /// `out`, пока сокет жив → бэкофф и заново, если нет. Не возвращается сам
    /// по себе — остановка снаружи: оборвать `JoinHandle` (как в тестах) или
    /// закрыть `out`, после чего `send` начнёт возвращать ошибку, которую этот
    /// цикл молча игнорирует, а не паникует на ней (получатель мог закрыться
    /// осознанно, это не повод ронять поток ввода-вывода).
    ///
    /// Тонкая обёртка над `run_with_backoff` с настоящим ожиданием
    /// (`RealBackoff`) — прод не видит разницы, только тесты подменяют
    /// планировщик задержки, чтобы не зависеть от настоящих часов (FIX 2).
    pub async fn run(self, clock: impl Clock + 'static, out: impl ConnSink + 'static) {
        self.run_with_backoff(clock, out, RealBackoff).await;
    }

    async fn run_with_backoff(
        mut self,
        clock: impl Clock + 'static,
        out: impl ConnSink + 'static,
        backoff: impl Backoff,
    ) {
        let mut attempt: u32 = 0;
        // Один буфер событий на соединение, переживает и сообщения, и
        // переподключения (таск 24): `ws::parse_message_into` очищает его и
        // наполняет заново на каждый кадр, так что список событий после
        // первого сообщения не аллоцирует — а `handle_raw` вычерпывает его
        // `drain`, не забирая владение.
        let mut events: Vec<Event> = Vec::new();
        loop {
            let mut transport = match self.connector.connect().await {
                Ok(t) => t,
                Err(err) => {
                    // Отказ рукопожатия не молчит (K1, 2026-09-17): событие
                    // уходит на каждый инструмент сокета — строка `gaps.csv`
                    // и счётчик в `session.json`, а не «вечно тихий ретрай».
                    let local_ts_ns = clock.now_ns();
                    self.route()
                        .broadcast_connect_failed(
                            &out,
                            local_ts_ns,
                            attempt.saturating_add(1),
                            &err,
                        )
                        .await;
                    backoff
                        .wait(self.cfg.backoff.delay_for_attempt(attempt))
                        .await;
                    attempt = attempt.saturating_add(1);
                    continue;
                }
            };

            // Новый сокет — новая последовательность `u` с нуля. Прошлая книга,
            // флаг ресинка и флаг «сессия была полезной» относятся к прошлой
            // сессии и не несут смысла здесь: старое состояние иначе выглядело
            // бы как разрыв в первом же сообщении новой сессии, хотя это
            // просто новое начало. Три поля собраны в одну структуру, а не
            // переданы в `handle_raw` по отдельности — иначе список аргументов
            // перевалил бы за предел, который держит clippy (`too_many_arguments`),
            // ровно тем сигналом, который эта структура и объединяет: все три
            // описывают состояние ОДНОЙ сессии, а не что-то из разных миров.
            let mut session = Session {
                books: self
                    .cfg
                    .symbols
                    .iter()
                    .map(|s| {
                        self.cfg
                            .depths
                            .iter()
                            .map(|_| Book::new(s.tick_e9, s.step_e9))
                            .collect()
                    })
                    .collect(),
                resyncing: vec![vec![false; self.cfg.depths.len()]; self.cfg.symbols.len()],
                productive: false,
            };

            // Одна подписка на весь набор инструментов сокета вместо двух
            // сообщений на инструмент (таск 28): для linear Bybit v5 не
            // ограничивает число `args` в запросе, ограничена только их
            // суммарная длина на соединение (`MAX_ARGS_CHARS`) — её
            // соблюдает раскладка вызывающего. У коллектора сессии в ней с
            // T45 по три топика на инструмент: `.50`, `.200` и лента
            // (`PoolConnConfig::depths`); одно-символьные вызывающие
            // подписываются только на `.50`.
            let route = self.route();
            let names: Vec<&str> = route.symbols.iter().map(|s| s.symbol.as_str()).collect();
            let subscribed = transport
                .send_text(ws::sub_pool(&self.cfg.depths, &names))
                .await
                .is_ok();
            if !subscribed {
                // Раньше эта ветка отступала молча: ни `gaps.csv`, ни счётчика
                // разрывов — сокет открылся, но ни разу не заявил о себе перед
                // повторной попыткой. Три другие смерти сокета внутри этого
                // файла (закрытый фрейм, неудавшийся пинг, неудавшийся ресинк)
                // уже шлют `Disconnected` до `continue`/`break` — этой было
                // самое время встать в тот же ряд.
                route.broadcast_disconnected(&out).await;
                backoff
                    .wait(self.cfg.backoff.delay_for_attempt(attempt))
                    .await;
                attempt = attempt.saturating_add(1);
                continue;
            }
            // Бэкофф здесь больше НЕ сбрасывается. Сброс сразу по успешной
            // подписке проверял только рукопожатие, а не сессию: сервер,
            // который принимает подписку и тут же рвёт соединение — рейт-лимит,
            // сброс нагрузки, дефектный прокси — заставлял бы цикл держаться
            // пола бэкоффа вечно, повторно долбя один и тот же адрес на
            // максимальной частоте. Признак «сессия была полезной» —
            // `session.productive`; сброс происходит только после него, когда
            // сессия уже закончилась.

            let mut ping_due = tokio::time::interval(self.cfg.ping_interval);
            // Таймаут приёма (V5, 2026-09-17): полуживое соединение — TCP жив,
            // данных нет (зависший прокси, сервер перестал публиковать) —
            // раньше висело бесконечно: ни разрыва, ни переподключения, ни
            // строки `gaps.csv`, только молча переставший расти бинлог.
            //
            // Доработка V5 (2026-09-24, ревью нашло: ветка `frame = timeout(
            // recv_timeout, transport.recv())` ниже почти никогда не успевает
            // истечь сама): у боевых вызывающих `recv_timeout` — 2 ×
            // `ping_interval` (`feed::live`, `commands::record`, `pick::
            // measure`), а её таймаут пересоздаётся на каждый виток внешнего
            // `loop`. Тик пинга (каждые `ping_interval`) — тоже такой виток, и
            // он неизбежно довитывает раньше, чем успевает истечь вдвое
            // больший `recv_timeout` — сам этот таймаут оказывается
            // недостижим, пока пинг вообще ходит (он остаётся резервным
            // детектором на случай, если `ping_interval` когда-то зададут
            // длиннее `recv_timeout`, как делает `silent_socket_times_out_
            // and_reports_disconnected` в тестах). Настоящая защита от
            // молчания — здесь, в ветке пинга, единственной, что гарантированно
            // срабатывает каждые `ping_interval`, короче любого используемого
            // `recv_timeout`. Она считает молчание по двум разным часам:
            //
            // 1) `last_any_frame_ns` — час последнего кадра ЛЮБОГО вида,
            //    включая `pong`/`Event::Other`: если не отвечает уже и он,
            //    транспорт действительно мёртв (TCP мог остаться жив, а
            //    данных, включая протокольные, не будет вовсе) — разрыв и
            //    переподключение, как раньше.
            // 2) `last_market_ns` — час последнего `Book`/`Trade`: `pong`
            //    его не двигает, он не рынок. Решение владельца 24.09: тишина
            //    рынка по неликвидной монете — нормальное явление, не повод
            //    рвать соединение (переподключение не возвращает рынку
            //    сделки, только теряет время на рукопожатие и рискует
            //    поймать разрыв аккурат в момент, когда кадр наконец пришёл
            //    бы). Порог по этому часу не рвёт — только наблюдение:
            //    предупреждение в stderr не чаще одного на эпизод молчания
            //    (`silence_warned` ниже) и `ConnEvent::MarketSilence` на
            //    каждом тике эпизода (не только на первом) — иначе
            //    `session.json.silence_max_ns` застыл бы на значении первого
            //    срабатывания, а не на фактической длине эпизода.
            let recv_timeout = self.cfg.recv_timeout;
            let recv_timeout_ns = i64::try_from(recv_timeout.as_nanos()).unwrap_or(i64::MAX);
            // Missed-тики копятся по умолчанию и стреляют очередью один за
            // другим при первой возможности; `Delay` вместо этого просто
            // сдвигает следующий тик, что и нужно для пинга — частый залп не
            // держит соединение живее одного вовремя отправленного.
            ping_due.set_missed_tick_behavior(MissedTickBehavior::Delay);
            // `interval` тикает немедленно при создании; без этого пинг ушёл
            // бы сразу вслед за подпиской, до всякого интервала.
            ping_due.tick().await;
            // Отсчёт обоих часов — от момента подписки, а не от нуля/эпохи:
            // свежее соединение, которое ещё не успело ничего прислать, не
            // обязано считаться мёртвым мгновенно.
            let mut last_any_frame_ns = clock.now_ns();
            let mut last_market_ns = last_any_frame_ns;
            // Один эпизод молчания рынка — одно предупреждение (решение
            // владельца выше): взводится при первом превышении порога в
            // ветке пинга, снимается первым же `Book`/`Trade` — там же, где
            // двигается `last_market_ns`.
            let mut silence_warned = false;

            loop {
                tokio::select! {
                    frame = tokio::time::timeout(recv_timeout, transport.recv()) => {
                        let frame = match frame {
                            Ok(frame) => frame,
                            Err(_) => {
                                // Молчание дольше двух пингов: соединение
                                // считается мёртвым и уходит в переподключение
                                // тем же путём, что обрыв (V5).
                                eprintln!(
                                    "conn: молчание дольше {recv_timeout:?} (2 × пинг) — \
                                     соединение считается мёртвым, переподключаюсь",
                                );
                                route.broadcast_disconnected(&out).await;
                                break;
                            }
                        };
                        match frame {
                            Ok(Frame::Text(raw)) => {
                                // Метка ставится здесь и нигде позже — до
                                // единственного вызова `parse_message_into` ниже.
                                // Это и есть `H12`: точка "сразу после recv".
                                let local_ts_ns = clock.now_ns();
                                // Любой кадр — доказательство, что транспорт
                                // жив, до всякого разбора (даже кадр, который
                                // не разберётся, — не молчание, это данные,
                                // просто плохие). Двигается безусловно, в
                                // отличие от `last_market_ns` ниже.
                                last_any_frame_ns = local_ts_ns;
                                // Разбор — синхронный вызов, ни одного `.await`
                                // между `local_ts_ns` и `parsed_ts_ns`, поэтому
                                // сделан здесь, а не внутри `handle_raw`: только
                                // так вторая метка (таск 04, суббюджет «разбор»,
                                // `PLAN.md` 3.1) берётся через `&clock` без
                                // необходимости проносить ссылку на `Clock`
                                // через границу `.await` `handle_raw` — общий
                                // параметр `impl Clock + 'static` не обязан быть
                                // `Sync`, а ссылка, живущая поперёк чужого
                                // `.await`, обязана.
                                let symbol = match ws::parse_message_into(&raw, &mut events) {
                                    Ok(symbol) => symbol,
                                    Err(err) => {
                                        out.send_event(
                                            route.socket_index(),
                                            ConnEvent::ParseFailed { local_ts_ns, err },
                                        )
                                        .await;
                                        continue;
                                    }
                                };
                                // Только это двигает `last_market_ns` (V5,
                                // доработка 2026-09-24): `pong`/подтверждение
                                // подписки (`Event::Other`) — не рынок и не
                                // обязаны продлевать соединению жизнь, сколько
                                // бы их ни пришло.
                                if events
                                    .iter()
                                    .any(|e| matches!(e, Event::Book(_) | Event::Trade(_)))
                                {
                                    last_market_ns = local_ts_ns;
                                    // Рынок вернулся — эпизод молчания кончен
                                    // (см. `silence_warned` у объявления
                                    // `last_market_ns`): следующее превышение
                                    // порога снова достойно предупреждения.
                                    silence_warned = false;
                                }
                                let parsed_ts_ns = clock.now_ns();
                                let alive = Self::handle_raw(
                                    &mut events,
                                    FrameMeta {
                                        local_ts_ns,
                                        parsed_ts_ns,
                                        symbol,
                                    },
                                    route,
                                    &mut session,
                                    &mut transport,
                                    &out,
                                )
                                .await;
                                if !alive {
                                    break;
                                }
                            }
                            Ok(Frame::Closed) | Err(_) => {
                                route.broadcast_disconnected(&out).await;
                                break;
                            }
                        }
                    }
                    _ = ping_due.tick() => {
                        // Единственная ветка, гарантированно достигаемая
                        // каждые `ping_interval` (см. комментарий у
                        // `recv_timeout` выше) — здесь и только здесь
                        // проверяется настоящее молчание, в обоих смыслах.
                        let now_ns = clock.now_ns();
                        // 1) Ни кадра вовсе, даже `pong` — транспорт мёртв.
                        // Проверяется первой: если не отвечает уже и pong,
                        // говорить о «тишине рынка» бессмысленно — это не
                        // тишина ликвидности, а мёртвый сокет.
                        if now_ns.saturating_sub(last_any_frame_ns) > recv_timeout_ns {
                            eprintln!(
                                "conn: ни одного кадра (даже pong) дольше {recv_timeout:?} — \
                                 транспорт мёртв, переподключаюсь",
                            );
                            route.broadcast_disconnected(&out).await;
                            break;
                        }
                        // 2) Кадры идут, а рынок (Book/Trade) молчит —
                        // решение владельца 24.09: не рвать, только
                        // наблюдать (см. комментарий у `recv_timeout` выше).
                        let silence_ns = now_ns.saturating_sub(last_market_ns);
                        if silence_ns > recv_timeout_ns {
                            let first_of_episode = !silence_warned;
                            if first_of_episode {
                                // `silence_warned` держит предупреждение
                                // одноразовым на эпизод; снимается первым же
                                // `Book`/`Trade`. Событие в канал уходит и на
                                // последующих тиках того же эпизода (ниже) —
                                // без этой строки в stderr, только для
                                // максимума в `session.json`.
                                let names: Vec<&str> =
                                    route.symbols.iter().map(|s| s.symbol.as_str()).collect();
                                eprintln!(
                                    "conn: рыночных событий (Book/Trade) нет дольше \
                                     {recv_timeout:?} у соединения [{}] — тишина {:?}, \
                                     не рву (владелец 24.09), только наблюдаю",
                                    names.join(","),
                                    Duration::from_nanos(u64::try_from(silence_ns).unwrap_or(0)),
                                );
                                silence_warned = true;
                            }
                            out.send_event(
                                route.socket_index(),
                                ConnEvent::MarketSilence {
                                    local_ts_ns: now_ns,
                                    silence_ns,
                                    first_of_episode,
                                },
                            )
                            .await;
                        }
                        if transport.send_text(ping_message()).await.is_err() {
                            route.broadcast_disconnected(&out).await;
                            break;
                        }
                    }
                }
            }

            // Сессия закончилась — здесь и только здесь решаем судьбу счётчика.
            // `session.productive` ставится в `handle_raw` при первой же
            // пересланной `Message`: если хоть одна дошла, соединение доказало,
            // что живёт не одним рукопожатием, и счётчик обнуляется — быстрый
            // реконнект после нормальной работы не должен наказываться прошлым
            // бэкоффом. Если нет — соединение росло от предыдущего значения
            // `attempt` (а не с нуля, как раньше), и задержка следующей попытки
            // растёт, а не топчется на полу. Порог «пересланное сообщение», а
            // не «сессия прожила N секунд»: он не изобретает время эксплуатации
            // (которого план не задаёт) и не требует своих часов внутри цикла
            // подключения — здесь уже есть ровно то состояние, что нужно.
            if session.productive {
                attempt = 0;
            } else {
                attempt = attempt.saturating_add(1);
            }
            backoff
                .wait(self.cfg.backoff.delay_for_attempt(attempt))
                .await;
        }
    }

    /// Обрабатывает уже разобранные события одного сырого фрейма: применяет
    /// обновления книги к локальной книге сессии и решает, пересылать ли
    /// событие наружу. Возвращает `false`, если сессию нужно закрывать
    /// (отправка ресинка в уже мёртвый сокет не удалась). Разбор (и обе
    /// метки, `local_ts_ns` до него и `parsed_ts_ns` сразу после) сделан
    /// вызывающим кодом в `run` — см. комментарий там.
    async fn handle_raw<O: ConnSink>(
        events: &mut Vec<Event>,
        meta: FrameMeta<'_>,
        route: Route<'_>,
        session: &mut Session,
        transport: &mut C::Transport,
        out: &O,
    ) -> bool {
        let FrameMeta {
            local_ts_ns,
            parsed_ts_ns,
            symbol,
        } = meta;
        // Маршрут кадра — один двоичный поиск на кадр, не на событие:
        // все события одного сырого сообщения принадлежат одному топику.
        let slot = symbol.and_then(|s| route.slot_of(s));
        let idx = slot.map_or_else(|| route.socket_index(), |slot| route.symbols[slot].index);
        // Доказательство индексации ниже (V11 аудита 2026-09-17: раньше она
        // держалась немым инвариантом, а его рефакторинг ломает молча).
        // `slot` — позиция в `cfg.symbols`: `Connection::new` строит таблицу
        // имён (`route`, отсортированную **только для поиска** по имени) с
        // индексом `enumerate` по `cfg.symbols`, а `route.symbols` — тот же
        // `cfg.symbols` как есть. `session.books` и `session.resyncing` собраны
        // обходом `cfg.symbols` (внешняя длина) и `cfg.depths` (внутренняя),
        // поэтому обе длины совпадают по построению, а не по договорённости;
        // `stream` приходит из `route.stream_of` — это позиция в том же
        // `cfg.depths`.
        debug_assert_eq!(
            session.books.len(),
            route.symbols.len(),
            "книги строятся обходом тех же символов, что и маршрут"
        );
        debug_assert!(
            session.books.iter().all(|b| b.len() == route.depths.len()),
            "внутренняя длина книг — число потоков того же соединения"
        );
        debug_assert_eq!(
            session.resyncing.len(),
            session.books.len(),
            "флаги ресинка — по одной строке на символ"
        );
        for event in events.drain(..) {
            // Рынок без известного маршрута наружу не идёт (приписать его
            // «индексу сокета» значило бы записать чужой стакан в бинлог
            // первого инструмента соединения), но и не исчезает молча —
            // `Unrouted` его считает. Служебное (`Other`: pong,
            // подтверждение подписки) символа не имеет и идёт по сокету.
            if slot.is_none() && !matches!(event, Event::Other) {
                if let Event::SubscribeFailed { topic, ret_msg } = &event {
                    // A8.3: отказ подписки — служебное событие сокета, но
                    // привязанное к инструменту **топика** из ответа: биржа
                    // отвечает на каждый несогласованный топик отдельно, а
                    // остальные топики той же партии подписаны (замер
                    // 2026-09-18). Не `Message`: рынка здесь нет.
                    let idx = topic
                        .as_deref()
                        .and_then(ws::topic_symbol)
                        .and_then(|name| route.slot_of(name))
                        .map_or_else(|| route.socket_index(), |slot| route.symbols[slot].index);
                    // Ответ биржи уже доказывает, что сокет жив (`productive`
                    // сбрасывает бэкофф в `run` при следующем подключении).
                    session.productive = true;
                    out.send_event(
                        idx,
                        ConnEvent::SubscribeFailed {
                            local_ts_ns,
                            topic: topic.clone(),
                            ret_msg: ret_msg.clone(),
                        },
                    )
                    .await;
                    continue;
                }
                out.send_event(route.socket_index(), ConnEvent::Unrouted { local_ts_ns })
                    .await;
                continue;
            }
            if let (Event::Book(update), Some(slot)) = (&event, slot) {
                // Поток — из топика (глубина в `Update`, T45) и из набора
                // потоков **этого** соединения (`cfg.depths`). Книжной
                // глубины, на которую сокет не подписан, здесь быть не может
                // (топик наш, но поток чужой — например, `orderbook.500` у
                // коллектора или `.200` у `lob record`); приписать её
                // какому-либо файлу значило бы записать поток, которого мы не
                // подписывали, поэтому она считается `Unrouted` — ровно как
                // кадр без символа, и так же не исчезает молча.
                let Some(stream) = route.stream_of(update.depth) else {
                    out.send_event(route.socket_index(), ConnEvent::Unrouted { local_ts_ns })
                        .await;
                    continue;
                };
                match session.books[slot][stream].apply(update) {
                    Ok(()) => {
                        session.resyncing[slot][stream] = false;
                    }
                    Err(err) => {
                        // Любая ошибка `apply` — не только `SequenceGap` — по
                        // контракту `book::ApplyError` означает «книга больше
                        // не доверена» (см. комментарий на самом типе в
                        // `book/mod.rs`). Реакция одна и та же: ресинк
                        // снапшотом. Флаг `resyncing` не даёт слать повторную
                        // подписку на каждую следующую дельту, пока мы уже
                        // ждём снапшот — иначе разрыв на секунду превратился
                        // бы в шторм из сотен подписок в секунду.
                        if !session.resyncing[slot][stream] {
                            session.resyncing[slot][stream] = true;
                            // `SequenceGap` несёт свои `expected`/`got` в
                            // отдельном варианте `ConnEvent` уже давно; три
                            // остальных варианта `ApplyError` раньше здесь не
                            // упоминались вовсе — ветка ловила только разрыв
                            // `u`, а `PriceNotOnTick`/`QtyNotOnStep`/`Crossed`
                            // проваливались в тот же ресинк молча, без единого
                            // события наружу. `Crossed` — уже точно испорченная
                            // книга, `PriceNotOnTick` — ровно то, чем план (шаг
                            // 0.3) обнаруживает смену тик-сайза биржи; оба не
                            // имеют права быть невидимыми снаружи этого файла.
                            // `depth` в обоих вариантах — тот же поток, чья
                            // книга нарушена: счётчики разрывов в `session.json`
                            // раздельные по потокам (T45).
                            match &err {
                                ApplyError::SequenceGap { expected, got } => {
                                    out.send_event(
                                        idx,
                                        ConnEvent::SequenceGap {
                                            depth: update.depth,
                                            expected: *expected,
                                            got: *got,
                                        },
                                    )
                                    .await;
                                }
                                _ => {
                                    out.send_event(
                                        idx,
                                        ConnEvent::BookInvariantViolated {
                                            depth: update.depth,
                                            err: err.clone(),
                                        },
                                    )
                                    .await;
                                }
                            }
                            // Ресинк — только по этому инструменту **и этому
                            // потоку**: сосед по сокету свою последовательность
                            // не терял, и `.200` того же символа — тоже своя
                            // последовательность `u`.
                            if transport
                                .send_text(ws::sub_orderbook(
                                    update.depth,
                                    &route.symbols[slot].symbol,
                                ))
                                .await
                                .is_err()
                            {
                                // Три способа умереть внутри select! в `run`
                                // обязаны выглядеть одинаково снаружи: закрытый
                                // фрейм и неудавшийся пинг уже шлют `Disconnected`
                                // перед тем, как разорвать цикл. Эта отправка —
                                // тоже путь смерти сокета, просто обнаруженный
                                // на один вызов глубже (внутри ресинка, а не в
                                // самом `select!`); без события здесь вызывающий
                                // код, размечающий границы сессии по
                                // `Disconnected`, одну из трёх смертей не увидит
                                // никогда — раньше именно так и было.
                                route.broadcast_disconnected(out).await;
                                return false;
                            }
                        }
                        // Не пересылаем: книга с этим событием не совпадает ни
                        // с чем, чему можно доверять, а «продолжить как ни в
                        // чём не бывало» — ровно то поведение, которое план
                        // запрещает прямым текстом.
                        continue;
                    }
                }
            }
            // Хоть одно сообщение дошло до пересылки — сессия доказала, что
            // живёт не одним только рукопожатием подписки. Это и есть признак
            // «полезной» сессии для сброса бэкоффа в `run` (см. комментарий
            // там); ставится безусловно, независимо от того, успеет ли `out`
            // принять сообщение — сам факт, что было что переслать, уже
            // случился и не зависит от состояния канала на другом конце.
            session.productive = true;
            out.send_event(
                idx,
                ConnEvent::Message {
                    local_ts_ns,
                    parsed_ts_ns,
                    event,
                },
            )
            .await;
        }
        true
    }
}

/// Публичный линейный поток Bybit v5. Адрес — факт протокола биржи (как имена
/// топиков в `ws.rs`), а не измеренное число и не порог: запрет изобретённых
/// констант — про них, не про адреса.
pub const PUBLIC_LINEAR_URL: &str = "wss://stream.bybit.com/v5/public/linear";

/// Реальный сокет: `tokio-tungstenite` за тем же трейтом, что и сценарный
/// транспорт тестов. Сеть в тестах этого файла не участвует — этот тип
/// проверяется тем, что компилируется и что он единственная реализация
/// `Transport`, которая ходит в сеть, а не отдельным сетевым тестом.
pub struct WsTransport {
    stream: tokio_tungstenite::WebSocketStream<
        tokio_tungstenite::MaybeTlsStream<tokio::net::TcpStream>,
    >,
}

impl Transport for WsTransport {
    fn send_text(
        &mut self,
        msg: String,
    ) -> impl Future<Output = Result<(), TransportError>> + Send {
        use futures::SinkExt;
        async move {
            self.stream
                // 0.30: `Text` несёт `Utf8Bytes`, конверсия из `String`
                // тотальна (UTF-8 в UTF-8, не парсинг).
                .send(tokio_tungstenite::tungstenite::Message::Text(msg.into()))
                .await
                .map_err(|e| TransportError::Io(e.to_string()))
        }
    }

    fn recv(&mut self) -> impl Future<Output = Result<Frame, TransportError>> + Send {
        use futures::StreamExt;
        use tokio_tungstenite::tungstenite::Message as TungsteniteMessage;
        async move {
            loop {
                match self.stream.next().await {
                    // 0.30: `Text` уже несёт `Utf8Bytes` — тот же тип, что
                    // теперь и `Frame::Text` (2026-09-24): передаётся как
                    // есть, без копии валидных байт в новую строку.
                    Some(Ok(TungsteniteMessage::Text(text))) => return Ok(Frame::Text(text)),
                    Some(Ok(TungsteniteMessage::Close(_))) | None => return Ok(Frame::Closed),
                    // Ping/Pong/Binary/сырой Frame — не протокол Bybit поверх
                    // этого канала; WS-пинг `tungstenite` обслуживает сам,
                    // здесь их достаточно пропустить и ждать следующий фрейм.
                    Some(Ok(_)) => continue,
                    Some(Err(e)) => return Err(TransportError::Io(e.to_string())),
                }
            }
        }
    }
}

/// Коннектор публичного линейного потока. Один на процесс: каждый `connect`
/// открывает новый TCP+TLS+WS с нуля, потому что переподключение и есть новая
/// сессия сервера, а не восстановление старой (Bybit не хранит состояние
/// подписки между разрывами).
#[derive(Debug, Default, Clone, Copy)]
pub struct BybitPublicLinearConnector;

impl TransportConnector for BybitPublicLinearConnector {
    type Transport = WsTransport;

    async fn connect(&mut self) -> Result<WsTransport, TransportError> {
        let (stream, _response) = tokio_tungstenite::connect_async(PUBLIC_LINEAR_URL)
            .await
            .map_err(|e| match e {
                // Рукопожатие отклонено биржей: статус — единственное, по чему
                // 403 (гео-блок) отличается от 429 (рейт-лимит), и он должен
                // доехать до `gaps.csv`, а не остаться в тексте (K1).
                tokio_tungstenite::tungstenite::Error::Http(response) => TransportError::Http {
                    status: response.status().as_u16(),
                    msg: response
                        .status()
                        .canonical_reason()
                        .unwrap_or("рукопожатие отклонено")
                        .to_string(),
                },
                other => TransportError::Io(other.to_string()),
            })?;
        Ok(WsTransport { stream })
    }
}

